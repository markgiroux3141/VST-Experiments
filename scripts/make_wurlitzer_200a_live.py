"""The Wurlitzer 200A played live (docs/WURLITZER_PLAN.md, WZ4): its electronics with the reeds
as a medium in the netlist, and the OUTPUT selector.

    uv run python scripts/make_wurlitzer_200a_live.py [--check]

Writes config/circuits/wurlitzer_200a_live.yaml from config/circuits/wurlitzer_200a.yaml by
patching its text (its comments and sources carry over):

- the reeds: the stock file's stand-in (the audio input `in` through CREEDS, a source for
  -V0 dC / C_reeds) gives way to a `wurli_reeds` part on the plate node `pk` (the component
  WURLI_REEDS, circuitsim's reeds medium, its keys played by note events): it senses the
  plate's voltage and pushes the reeds' current -d((C_r + dC) V)/dt into it through their
  standing capacitance, so the plate's sag on a loud chord and the preamp's loading come out
  of the circuit (the stand-in held V at V0). `in` stays, unused (RIN holds it);
- OUTPUT (the switch `speakers`: 0 AUX, 1 SPEAKERS): the AUX jack's node becomes `aux`, and
  `out` reads either the AUX jack (volts) or the speaker terminals scaled by 1/5 (0 dBFS =
  20 V, the amp's clipping ~18-19 V peak into 8 ohm), through a readout that draws no current
  (a VCCS buffer into 1 ohm). Until WZ5's speakers, SPEAKERS is the terminals' voltage into
  the two 16 ohm resistors;
- the power amplifier is built only with SPEAKERS (its section's `when: [speakers]`): with
  the +15 V regulator ideal it meets the AUX path only at the main volume's wiper, where its
  input network (C8, C9, R27) stays in either way as the wiper's load, so AUX plays without
  it (WURLITZER_PLAN.md WZ4's status has the measured difference). A flip of OUTPUT is then a
  change of structure: a live stream restarts.

The generated file says it is generated; edit the stock file (or the patches here) and
rerun (`--check` exits 1 when the file on disk differs: tests/test_wurlitzer_live.py).
"""

