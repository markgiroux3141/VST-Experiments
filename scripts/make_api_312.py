def make() -> str:
    src = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    values = {k: v for k, v in src["values"].items() if k not in TEST_ONLY}
    values.update({k: {"value": v, "source": s} for k, (v, s) in VALUES.items()})
    sec = next(s for s in src["sections"] if s["title"] == "the 2520")
    node = {"out": "out2520"}

    def ren(p: dict) -> dict:
        p = dict(p)
        macro = next(iter(p))
        p[macro] = [node.get(n, n) for n in p[macro]]
        return p

    amp = {"title": "the 2520", "parts": {n: ren(p) for n, p in sec["parts"].items()}}
    rails = next(s for s in src["sections"] if s["title"] == "rails")
    r_parts = [n for n, p in amp["parts"].items() if "R" in p]
    c_parts = [n for n, p in amp["parts"].items() if "C" in p]
    doc = {
        "title": "API 312 mic preamp",
        "input": "in",
        "probes": ["out", "ia", "inp", "out2520", "inm", "vH", "vJ"],
        "full_scale": {
            "input_volts_peak": {
                "value": 1.0960,
                "source": "derived: 0.775 V rms x sqrt(2), 0 dBu (as ssl_4000e.yaml)",
            },
            "output_volts_peak": {
                "value": 17.36,
                "source": "derived: +24 dBu peak, the same scale as ssl_4000e.yaml's and "
                "telefunken_v76.yaml's outputs so the chains print comparably",
            },
        },
        "controls": CONTROLS,
        "values": values,
        "tolerance": {
            "source": "provisional: classes by part type (see the tol_* values)",
            "seed": "passive_seed",
            "spread": "passive_spread",
            "bands": {"r5": "tol_resistor_pct", "cap": "tol_cap_pct", "pot": "tol_pot_pct"},
            "classes": {
                "r5": ["RPA", "RPB", "RPSH", "RZ", "RF", "RG", "RBO", "RL", *r_parts],
                "cap": ["CZ", "CF", "CG", "CO", *c_parts],
                "pot": ["RGAIN"],
            },
        },
        "devices": src["devices"],
        "sections": [rails, *PRE_SECTIONS, amp],
    }
    return HEADER + yaml.safe_dump(doc, sort_keys=False, width=100, allow_unicode=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = make()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale: rerun scripts/make_api_312.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
