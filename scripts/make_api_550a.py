def _contact(a: str, b: str, positions: list[int]) -> dict:
    return {"R": [a, b], "r": "contact_ohm", "tolerance": "none", "in": positions}


def _r(a: str, b: str, key: str) -> dict:
    return {"R": [a, b], "r": key}


