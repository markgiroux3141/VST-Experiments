"""The API 550A equalizer as a circuit file (docs/EQ_PLAN.md EQ3):

    uv run python scripts/make_api_550a.py [--check]

Writes config/circuits/api_550a.yaml (the production circuit), api_550a_network.yaml (the
network check) and api_550a_live.yaml (what Play and the drafts run) from API's drawing
613-759 ("MODEL 550A EQUALIZER SCHEMATIC", data/schematics/api_550a/README.md),
config/circuits/api_2520_test.yaml (the 2520
op-amp's values, devices and section, so the op-amp lives in one file; A1 and A2 are two
instances of it) and config/circuits/api_312.yaml (the AP2503 output transformer's values).
`--check` exits 1 when a file on disk differs.

The live circuit (2026-11-15, the user's call: the real-time draft the cheap way, production
the real one): the same drawing with A1 / A2 as clamped `opamp` macros on the 2520's data
sheet and A3-A6 as unity buffers at the discrete followers' measured gain. The discrete
circuit's 30 transistors played 2.1x real time at draft-1x; the live one ~0.1x, within a fixed
tone of it (~0.1 dB, -0.5 dB at 20 kHz) and -70 dB past that on program (docs/EQ_PLAN.md EQ3,
"Live"). panel::Device::live_circuit plays it at the draft qualities.

How the drawing works (traced 2026-11-15; the README's "Reading"):

- The signal: the input (HIGH LEVEL through R1 11K against R2 7.5K, about -8 dB, or LOW LEVEL
  direct) -> A1, a non-inverting 2520 -> the band-pass filter (S2) -> A6, a discrete follower
  -> the HF cut string -> A4 -> the MF cut string -> A3 -> the LF cut string -> A2's + input.
  A2's feedback: its output -> R106 200 -> X -> the MF boost string -> A5 -> the LF boost
  string -> A2's - input. A2 -> C41 500 uF || R101 47 -> T1 (AP2503) -> the output (HIGH
  LEVEL the whole secondary, LOW LEVEL its tap). X -> R76 56 -> terminal 11, the gain trim.
- Each band is API's reciprocal bridge on one 11-position switch (S8A for HF): its rotor W
  taps either the boost string (positions 7-11) or the cut string (positions 1-5). A network
  loads W: in PEAK, a capacitor (S9B's) to the bus P, a capacitor (S9A's) from P to the drive
  node M, and from P a resistor (S8B's chain) to AC ground. The drive decks (S8D / S8E) put M
  on the band's cut source on positions 1-6, on its boost source on 7-11 (position 6 as the
  user read the drawing's overlapping arcs, 2026-11-15); at 6 the rotor sits on the park
  resistor (R48 10K) to M. Boost is 1 + R_up Y(s); with M on the cut string's source the cut
  is exactly its reciprocal. The peak's resonance is 1 / (2 pi sqrt(R_up R_q Ca Cb)), and
  R_up R_q is ~9.4e7 ohm^2 at every step: the frequency stays, the Q follows the gain
  (proportional Q).
- SHELF: HF's a capacitor (S9C's) in series with a resistor (S8C's chain) from W to AC ground
  (a high shelf); LF's a resistor (S6C's chain, through C14) from W to ground in parallel with
  a capacitor (S7C's) from W to M (a low shelf). MF has no shelf.
- The frequency decks are drawn with arc rotors: progressive shorting contacts, so each step
  clockwise adds a capacitor in parallel (S9A: C45; + C32; + C33; + C34; + C31). Position 1
  (Note 8: every switch drawn at its most counter-clockwise) is the band's highest frequency.
- The proportional-Q decks tap their chains on positions k and 12 - k alike (the drawing's
  frames), open at 6.
- The band-pass's shunt elements return to a bus G, tied to HF's AC ground B (C38) by S2
  (IN) through S1 (EQ IN); otherwise G is held near A1's output by R107 18K against R15 330K
  to B (bootstrapped: the shunts carry almost no current, the filter is out).

Not modelled: CR1 / CR2 (reverse-polarity diodes in the rails: the rails are ideal +-15 V at
the card, the user's call), the tally LED DS1 and R100, C35 / C36 (rail decoupling on ideal
rails), the 2520s' COM pins (their cases).
"""

