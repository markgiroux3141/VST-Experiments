def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = {OUT: make(), NET: make(ideal=True), LIVE: make(live=True)}
    if a.check:
        stale = [f.name for f, t in files.items()
                 if not f.exists() or f.read_text(encoding="utf-8") != t]  # fmt: skip
        for name in stale:
            print(f"{name} is stale: rerun scripts/make_api_550a.py")
        return 1 if stale else 0
    for f, t in files.items():
        f.write_text(t, encoding="utf-8", newline="\n")
        print(f"wrote {f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
