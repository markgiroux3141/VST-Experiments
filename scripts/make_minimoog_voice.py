def node(n: str, prefix: str = "k_", shared: dict = SHARED) -> str:
    n = str(n)
    if n == "0":
        return "0"
    return shared.get(prefix + n, prefix + n)


def rename_part(name, body, vrename, prefix="k_", suffix="_k", shared=SHARED):
    body = dict(body)
    macro = next((m for m in MACROS if m in body), None)
    if macro is not None:
        body[macro] = [node(x, prefix, shared) for x in body[macro]]
    for f in REF_FIELDS + ("at",):
        if f in body and isinstance(body[f], str) and body[f] in vrename:
            body[f] = vrename[body[f]]
    if "parts" in body:  # a switch's sub-parts
        body["parts"] = {
            n + suffix: rename_part(n, b, vrename, prefix, suffix, shared)
            for n, b in body["parts"].items()
        }
    return body


def kept_name(k: str) -> bool:
    """The keyboard's values the app reads by name (panel::KeyString, the gate's levels)."""
    return k.startswith("key_") or k.startswith("gate_")


