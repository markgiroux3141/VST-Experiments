"""Generate config/circuits/minimoog_voice.yaml: the filter board with the contour board joined
(docs/MINIMOOG_PLAN.md, MM4). Never edit the generated file; edit the two sources and rerun.

    uv run python scripts/make_minimoog_voice.py [--check]

The contour generators (minimoog_contour.yaml: its parts get an `_k` suffix, its values and devices
a `k_` prefix, its nodes a `k_` prefix) join the filter board (minimoog_filter_board.yaml):
  - the loudness contour's output node is the VCA's contour input (pin 9, `p9`, into R59);
  - the filter contour's output feeds AMOUNT OF CONTOUR: a 5K linear pot to ground, its wiper into
    R74 (pin 16); `amount` 0 is the old fixture (R74 to ground), so a circuit at 0 behaves as
    before;
  - the contour board's +9.3, -10 and +10 V are its own ideal rails (a partition needs a DC path to
    its sources);
  - the keyboard circuit (minimoog_keyboard.yaml: parts `_b`, values and devices `b_`, nodes `b_`;
    its key_* and gate_* values keep their names, the app reads them) replaces the filter board's
    KEYBOARD CONTROL fixture: its output (Q10's source, pins 4 / 5) is the board's keyboard node
    `kbd`
    (into KEYBOARD CONTROL 1 / 2), the control input `key` its pitch bar, the control input `gate`
    its trigger contact, and its trigger bus is the contour board's pin 20 (into CR10). Its current
    source isn't carried (on ideal rails a constant: its current is in key_v_per_semitone, measured
    by scripts/minimoog_keyboard_study.py --write), nor its unused audio input.
"""

import argparse
import sys

import yaml

from varimu.config import CONFIG_DIR

CIRC = CONFIG_DIR / "circuits"
OUT = CIRC / "minimoog_voice.yaml"
MACROS = ("R", "C", "V", "pot", "rheostat", "bjt", "jfet", "device")
SHARED = {"0": "0", "k_outl": "p9"}
KB_SHARED = {"0": "0", "b_out": "kbd", "b_tbus": "k_kg"}
KB_SKIP_SECTIONS = ("current source",)
KB_SKIP_PARTS = ("RIN",)
REF_FIELDS = ("r", "c", "v", "model", "taper_mid")
HEADER = """# GENERATED by scripts/make_minimoog_voice.py from minimoog_filter_board.yaml (the VCF
# and VCA, board No. 4), minimoog_contour.yaml (the two contour generators and the trigger, board
# No. 2) and minimoog_keyboard.yaml (the keyboard circuit, board No. 2): never edit this file.
# See that script's docstring for how they join, docs/MINIMOOG_PLAN.md MM4.
"""


def node(n: str, prefix: str = "k_", shared: dict = SHARED) -> str:
    n = str(n)
    if n == "0":
        return "0"
    return shared.get(prefix + n, prefix + n)


def rename_part(name, body, vrename, prefix="k_", suffix="_k", shared=SHARED):
    body = dict(body)
    macro = next((m for m in MACROS if m in body), None)
    if macro is not None:
        body[macro] = [node(x, prefix, shared) for x in body[macro]]
    for f in REF_FIELDS + ("at",):
        if f in body and isinstance(body[f], str) and body[f] in vrename:
            body[f] = vrename[body[f]]
    if "parts" in body:  # a switch's sub-parts
        body["parts"] = {
            n + suffix: rename_part(n, b, vrename, prefix, suffix, shared)
            for n, b in body["parts"].items()
        }
    return body


def kept_name(k: str) -> bool:
    """The keyboard's values the app reads by name (panel::KeyString, the gate's levels)."""
    return k.startswith("key_") or k.startswith("gate_")


def build() -> str:
    board = yaml.safe_load((CIRC / "minimoog_filter_board.yaml").read_text(encoding="utf-8"))
    cont = yaml.safe_load((CIRC / "minimoog_contour.yaml").read_text(encoding="utf-8"))
    kb = yaml.safe_load((CIRC / "minimoog_keyboard.yaml").read_text(encoding="utf-8"))

    # the contour's values and devices: prefixed
    vrename = {k: "k_" + k for k in list(cont["values"]) + list(cont["devices"])}
    out = dict(board)
    out["title"] = (
        "Minimoog voice: filter board (VCF, VCA) with the contour generators and the keyboard"
    )
    out["cv_inputs"] = {
        "key": node(kb["cv_inputs"]["key"], "b_", KB_SHARED),
        "gate": node(kb["cv_inputs"]["gate"], "b_", KB_SHARED),
    }
    out["probes"] = list(board["probes"]) + [
        "p9",
        "kbd",
        "k_kg",
        "k_env",
        "k_envl",
        "k_outn",
        "k_tb",
        "k_vtrig",
        "b_s9",
        "b_c6",
        "b_n24",
    ]

    out["controls"] = dict(board["controls"])
    for k, v in cont["controls"].items():
        out["controls"][k] = v
    for k, v in kb["controls"].items():
        out["controls"][k] = v
    out["controls"]["amount"] = {
        "value": 0.0,
        "min": 0.0,
        "max": 1.0,
        "unit": "rotation",
        "source": "the 204D manual's Table 7-3: a 5K linear pot (AMOUNT OF CONTOUR TO FILTER, "
        "the filter contour into R74 / pin 16); 0 = the wiper at ground",
    }

    out["values"] = {k: v for k, v in board["values"].items() if not kept_name(k)}
    for k, v in cont["values"].items():
        if k in ("r_load_ohm",):
            continue
        out["values"]["k_" + k] = v
    out["values"]["ramt_ohm"] = {
        "value": 5.0e3,
        "source": "Table 7-3: AMOUNT OF CONTOUR, 5K linear",
    }
    kbrename = {k: ("b_" + k) for k in list(kb["values"]) + list(kb["devices"]) if not kept_name(k)}
    for k, v in kb["values"].items():
        out["values"][kbrename.get(k, k)] = v

    out["devices"] = dict(board["devices"])
    for k, v in cont["devices"].items():
        d = dict(v)
        if isinstance(d.get("device"), str) and d["device"] in vrename:
            d["device"] = vrename[d["device"]]
        out["devices"]["k_" + k] = d
    kb_used = {
        b.get("model")
        for s in kb["sections"]
        if s["title"] not in KB_SKIP_SECTIONS
        for b in s["parts"].values()
    }
    for k, v in kb["devices"].items():
        if k not in kb_used:
            continue  # the current source's transistors
        d = dict(v)
        if isinstance(d.get("device"), str) and d["device"] in kbrename:
            d["device"] = kbrename[d["device"]]
        out["devices"][kbrename[k]] = d

    sections = [dict(s) for s in board["sections"]]
    for s in sections:  # AMOUNT OF CONTOUR: R74's far end is the wiper
        parts = {}
        for n, b in s["parts"].items():
            if n == "R74":
                b = dict(b)
                b["R"] = ["amt_w", "ctl"]
                parts[n] = b
                parts["RAMT"] = {"pot": ["0", "amt_w", "k_outn"], "r": "ramt_ohm", "at": "amount"}
            else:
                parts[n] = b
        s["parts"] = parts
    for s in cont["sections"]:
        if s["title"] == "rails":
            # +9.3, -10 and +10 V: the board's own ideal rails, as the VCA has (not its audio
            # input's leak)
            parts = {n: b for n, b in s["parts"].items() if n != "RIN"}
        else:
            parts = {}
            for n, b in s["parts"].items():
                if n in ("RIN", "RL", "RLL"):
                    continue  # the audio input and the test loads
                parts[n + "_k"] = rename_part(n, b, vrename)
        if s["title"] == "rails":
            parts = {n + "_k": rename_part(n, b, vrename) for n, b in parts.items()}
        if s["title"] == "trigger":
            # the gate's node (a control input) stays in the first partition with its section
            parts["RKG_k"] = {"R": ["k_kg", "0"], "r": "k_r_leak_ohm"}
        sections.append({"title": "contour: " + s["title"], "parts": parts})
    for s in kb["sections"]:
        if s["title"] in KB_SKIP_SECTIONS:
            continue
        parts = {
            n + "_b": rename_part(n, b, kbrename, "b_", "_b", KB_SHARED)
            for n, b in s["parts"].items()
            if n not in KB_SKIP_PARTS
        }
        sections.append({"title": "keyboard: " + s["title"], "parts": parts})
    out["sections"] = sections
    return HEADER + yaml.safe_dump(out, sort_keys=False, default_flow_style=None, width=200)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        print("up to date" if ok else "STALE: rerun scripts/make_minimoog_voice.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
