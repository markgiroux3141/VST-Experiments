def generate() -> str:
    text = PREAMP.read_text(encoding="utf-8")
    text = text.replace("\r\n", "\n")
    for old, new in patches():
        if text.count(old) != 1:
            raise SystemExit(f"patch anchor occurs {text.count(old)} times: {old[:70]!r}")
        text = text.replace(old, new)
    text = HEADER + text.rstrip("\n") + "\n"
    text += "\n" + SUPPLY
    text += board("a", "pre_a", "out", "a_amp", "out_rear_a", "spk_left_m", "spk_right_m")
    text += board("b", "pre_b", "out_r", "b_amp", "out_rear_b", "spk_right_m", "spk_left_m")
    return text


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate()
    if a.check:
        cur = OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if cur != text:
            print(f"{OUT} differs from the generator's output")
            return 1
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
