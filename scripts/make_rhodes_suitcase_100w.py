"""The whole Rhodes Mark I Suitcase (1978): the harp, the 100 W preamp (fig11-1) and the dual
50 W power amplifier (fig11-3) with its supply and four 12-inch speakers, as one netlist.

    uv run python scripts/make_rhodes_suitcase_100w.py [--check]

Writes config/circuits/rhodes_suitcase_100w.yaml from config/circuits/rhodes_suitcase.yaml
(the preamp, hand-written, its vibrato fitted to the reference recording by
scripts/suitcase_study.py) by patching its text: the preamp's outputs become `pre_a` /
`pre_b`, the stand-in loads (RLA ... CLB) go, and the amp boards A and B, the mains supply
and the speakers go in. Why generated, not added by hand: the two boards are the same
circuit twice (one generator, one place to fix), and the preamp-only file stays as the fast
test circuit for the pan's fit (suitcase_study.py runs it ~3x faster, with no 11,000 uF
reservoirs or speaker networks). The generated file says it is generated; edit this script
(or the preamp) and rerun (`--check` exits 1 when the file differs: tests/test_rhodes_amp.py).

The factory trims (OFFSET ADJUST to 0 V at each output, BIAS ADJ for a quiescent current)
are the constants OFFSET_* / BIAS_* below, set by scripts/rhodes_amp_trim.py --write.

Decisions (the user's standing words: "do whatever you need to so we can get close to the
real sound"; each written in docs/RHODES_PLAN.md "The Suitcase"):
- R18-R21: fig11-3 prints R18 and R21 as 0.5 ohm 5 W; the parts list (fig11-6.html) has four
  0.2 ohm 10 W nichrome assemblies, R18-R21, and the board (fig11-6.jpg) shows R18 / R19 as a
  pair along P2 and R20 / R21 as another. Used: **two 0.2 ohm in series per output
  transistor, 0.4 ohm**. The parts list is the assembly as built; two in series is the only
  pairing near the drawing's 0.5 (parallel would be 0.1, five times off), and 0.4 is inside
  the drawing's value with its stated 20% room; the difference in clipping power is ~2%.
- CR1 (1N4148 beside R2): its arrow points from the emitter node to Q1's base node (read at
  the drawing's zoom), a reverse-bias protection of Q1's base-emitter junction.
- The speakers: 1978's cabinets have the 8 ohm 12" ceramic speakers (a Reverb listing of a
  1978 pair, "50W 8 ohm"; ep-forum topic 6862; unbrokenstring.com), two in SERIES per
  channel: 16 ohm, the load the manual's fig11-9 names for the 80 W amp too. The early
  cabinets' 32 ohm pairs in parallel (CTS, 1971-75) are not this year's.
"""

