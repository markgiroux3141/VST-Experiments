"""Fit the Victorian synth's Leclanche cell to Carhart's 1891 polarization table: an EMF behind
an ohmic resistance and two polarization states (each an R || C in series: v' = i / C - v / RC),
the circuit's linear equivalent (docs/VICTORIAN_SYNTH_PLAN.md, "Power: wet cells").

    uv run python scripts/fit_leclanche.py [--write] [--show]

Data: data/datasheets/victorian/carhart_1891_leclanche.csv (a cell closed on 5 ohm for an hour,
then opened for an hour; its EMF read on brief open circuits, its current). The EMF behind the
states follows E(t) = E0 - sum v_k(t) with the cell's own current; R0 is the table's internal
resistance (its median). The fit's residuals are reported: a linear cell polarizes and recovers
with the same time constants, Carhart's falls faster than it recovers (MnO2's slow
depolarization), so the fit splits the difference.

--write saves config/victorian/leclanche.yaml (the values, their source and the residuals).
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

REPO = Path(__file__).resolve().parents[1]
DATA = REPO / "data" / "datasheets" / "victorian" / "carhart_1891_leclanche.csv"
OUT = REPO / "config" / "victorian" / "leclanche.yaml"
SOURCE = (
    "fit: scripts/fit_leclanche.py to Carhart, Primary Batteries (1891), p. 122, a Leclanche cell "
    "closed on 5 ohm for 60 min and opened for 60 min (web: https://archive.org/details/"
    "cu31924031227949; data/datasheets/victorian/carhart_1891_leclanche.csv)"
)


def load() -> dict[str, np.ndarray]:
    rows = list(csv.DictReader(DATA.open(encoding="utf-8")))

    def col(k):
        return np.array([float(r[k]) if r[k] != "" else np.nan for r in rows])

    return {k: col(k) for k in ("t_s", "closed", "emf_v", "terminal_v", "current_a", "r_int_ohm")}


def current(d: dict[str, np.ndarray], t: np.ndarray) -> np.ndarray:
    """The cell's current at t: the table's, interpolated while closed; 0 open."""
    m = ~np.isnan(d["current_a"]) & (d["closed"] == 1)
    i = np.interp(t, d["t_s"][m], d["current_a"][m])
    return np.where(t < 3600.0, i, 0.0)


def emf(x: np.ndarray, d: dict[str, np.ndarray], t_eval: np.ndarray) -> np.ndarray:
    """E0 - sum v_k at t_eval: the states advanced exactly per 1 s step (the current held)."""
    e0, *rt = x
    rs, taus = np.array(rt[0::2]), np.array(rt[1::2])
    t = np.arange(0.0, 7201.0, 1.0)
    i = current(d, t)
    v = np.zeros(len(rs))
    k = np.exp(-1.0 / taus)
    out = np.empty(len(t))
    for n in range(len(t)):
        out[n] = e0 - v.sum()
        v = i[n] * rs + (v - i[n] * rs) * k
    return np.interp(t_eval, t, out)


def fit() -> dict:
    d = load()
    m = ~np.isnan(d["emf_v"])
    te, ee = d["t_s"][m], d["emf_v"][m]
    # Start: a fast (~1 min) and a slow (~3 h) state. A third, middle one (~20 min) went to
    # zero in the fit: the table doesn't hold three.
    x0 = np.array([1.66, 1.5, 60.0, 1.5, 10000.0])
    lo = [1.3, 0.0, 5.0, 0.0, 1000.0]
    hi = [1.8, 5.0, 600.0, 20.0, 1e5]
    r = least_squares(
        lambda x: emf(x, d, te) - ee,
        x0,
        bounds=(lo, hi),
        x_scale=[0.1, 1.0, 50.0, 1.0, 5000.0],
    )
    e0, r1, t1, r2, t2 = (float(v) for v in r.x)
    res = emf(r.x, d, te) - ee
    r0 = float(np.nanmedian(d["r_int_ohm"]))
    # The terminal voltage on 5 ohm the model gives, against the table's.
    mt = ~np.isnan(d["terminal_v"])
    vt_model = emf(r.x, d, d["t_s"][mt]) - current(d, d["t_s"][mt]) * r0
    vt_res = vt_model - d["terminal_v"][mt]
    return {
        "e0_v": e0,
        "r0_ohm": r0,
        "states": [
            {"r_ohm": r1, "tau_s": t1},
            {"r_ohm": r2, "tau_s": t2},
        ],
        "emf_rms_v": float(np.sqrt(np.mean(res**2))),
        "emf_max_v": float(np.max(np.abs(res))),
        "terminal_rms_v": float(np.sqrt(np.mean(vt_res**2))),
        "emf_residuals": {str(int(t)): float(x) for t, x in zip(te, res, strict=True)},
    }


def yaml_text(f: dict) -> str:
    def val(v: float, extra: str = "") -> str:
        return f'{{value: {v:.6g}, source: "{SOURCE}{extra}"}}'

    lines = [
        "# The Victorian synth's Leclanche cell (docs/VICTORIAN_SYNTH_PLAN.md,",
        '# "Power: wet cells"):',
        "# GENERATED by scripts/fit_leclanche.py (--write); don't edit by hand.",
        "# EMF e0 behind r0 and two polarization states, each an R || C in series",
        "# (tau = R C): the cell's linear equivalent. Built into circuits by",
        "# varimu/victorian/cells.py.",
        f"# Fit: EMF rms {f['emf_rms_v'] * 1e3:.1f} mV, max {f['emf_max_v'] * 1e3:.1f} mV over",
        "# the hour closed and the hour open; terminal voltage on 5 ohm rms"
        f" {f['terminal_rms_v'] * 1e3:.1f} mV.",
        "",
        "cell:",
        f"  e0_v: {val(f['e0_v'])}",
        "  r0_ohm: " + val(f["r0_ohm"], " (the table's internal resistance, median)"),
    ]
    for k, s in enumerate(f["states"], 1):
        lines.append(f"  r{k}_ohm: {val(s['r_ohm'])}")
        lines.append(f"  tau{k}_s: {val(s['tau_s'])}")
    lines += [
        "",
        "residuals_v: " + json.dumps(f["emf_residuals"]),
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--show", action="store_true")
    a = ap.parse_args()
    f = fit()
    print(json.dumps({k: v for k, v in f.items() if k != "emf_residuals"}, indent=1))
    if a.show:
        import matplotlib.pyplot as plt

        d = load()
        t = np.arange(0, 7201, 10.0)
        x = [f["e0_v"]] + [y for s in f["states"] for y in (s["r_ohm"], s["tau_s"])]
        m = ~np.isnan(d["emf_v"])
        plt.plot(d["t_s"][m] / 60, d["emf_v"][m], "o", label="Carhart 1891: EMF")
        plt.plot(t / 60, emf(np.array(x), d, t), label="fit")
        plt.xlabel("minutes")
        plt.ylabel("V")
        plt.legend()
        out = REPO / "reports" / "victorian" / "leclanche_fit.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        plt.savefig(out, dpi=110)
        print(f"wrote {out}")
    if a.write:
        OUT.write_text(yaml_text(f), encoding="utf-8", newline="\n")
        print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
