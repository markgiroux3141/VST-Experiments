"""The Pultec HLF-3C program and sound effects filter as a circuit file (docs/EQ_PLAN.md EQ1):

    uv run python scripts/make_pultec_hlf3c.py [--check]

Writes config/circuits/pultec_hlf3c.yaml from the tables below: the hand-drawn schematic's
HLF-3C table (each position's capacitors) and the same sheet's HLF-3 drawing (the tapped
toroids' inductances), data/schematics/pultec_hlf3c/README.md. `--check` exits 1 when the
file on disk differs.

The circuit: in -> the 600 ohm source -> the IN-OUT key -> C-1 -> (L-1 to common) -> C-2 ->
L-2 -> (C-3 to common) -> L-3 -> the key -> the 600 ohm load. A constant-K high-pass T, then
a constant-K low-pass T (each a 3rd-order Butterworth in its own terminations). OFF: C-1 and
C-2 shorted, L-1 not connected; C-3 not connected, L-2 and L-3 shorted (the drawing's table).
Each coil position is a separate inductor with its tap's resistance (the toroids' unused
turns carry no current); a change of position rewires the circuit.
"""

from __future__ import annotations

import argparse
import math
import sys

import yaml

from varimu.config import CONFIG_DIR

OUT = CONFIG_DIR / "circuits" / "pultec_hlf3c.yaml"

DESIGN_OHM = 500.0  # "CONSTANT-K 500 ohm" (the drawing)

# LOW CUT-OFF: position (cps) -> (C-1 = C-2 in uF from the HLF-3C table, L-1 in mH from the
# HLF-3's LF toroid).
LOW = {
    50: (5.13, 800.0),
    80: (4.13, 500.0),
    100: (3.13, 390.0),
    150: (2.13, 260.0),
    250: (1.13, 160.0),
    500: (0.63, 80.0),
    750: (0.38, 52.0),
    1000: (0.26, 39.0),
    1500: (0.19, 26.0),
    2000: (0.13, 20.0),
}

# HIGH CUT-OFF: position (cps) -> (C-3 in uF from the HLF-3C table, L-2 = L-3 in mH from the
# HLF-3's HF toroids; None: derived, the HLF-3 has no 15 kc position).
HIGH = {
    1500: (0.4, 52.0),
    2000: (0.33, 39.0),
    3000: (0.22, 26.0),
    4000: (0.15, 20.0),
    5000: (0.1066, 16.0),
    6000: (0.1, 13.0),
    8000: (0.075, 10.0),
    10000: (0.068, 8.0),
    12000: (0.05, 6.5),
    15000: (0.039, None),
}

# The coils' resistance: the EQP-1A's tapped toroid, 14 ohm at its 27 mH tap, as sqrt(L).
DCR_REF_OHM, DCR_REF_H = 14.0, 0.027
DCR_SOURCE = (
    "derived: 14 ohm x sqrt(L / 27 mH), the EQP-1A's tapped toroid (a vendor's 14 ohm first "
    "tap, its taps' resistance as the turns, sqrt(L): data/schematics/pultec_eqp1a/README.md); "
    "provisional: the HLF-3C's coils' resistance isn't published"
)

HEADER = """\
# GENERATED by scripts/make_pultec_hlf3c.py: edit that script and rerun.
#
# Pultec HLF-3C program and sound effects filter (docs/EQ_PLAN.md EQ1; sources
# data/schematics/pultec_hlf3c/README.md):
#   "man: ..."       Pulse Techniques' HLF-3C sheet (the brochure)
#   "dwg: ..."       the hand-drawn schematic's HLF-3C table ("newer version with 15 kHz")
#   "dwg-hlf3: ..."  the same sheet's drawing of the older HLF-3 (the coils' taps in mH)
#   "derived: ..."   computed from those (constant-K design at the drawing's 500 ohm)
#
# Passive, no power: a constant-K high-pass T (C-1, L-1 to common, C-2) then a constant-K
# low-pass T (L-2, C-3 to common, L-3), between a 600 ohm source and a 600 ohm load. The
# brochure's "insertion loss: zero" is against the line it sits in: the output's full scale is
# half the input's, so the key at OUT (a 600 ohm source straight into 600 ohm) reads 0 dB.
# The coils are linear (molybdenum permalloy toroids of the period: provisional).

"""


def _f(v: float) -> float:
    return float(f"{v:.6g}")


def dcr_ohm(l_h: float) -> float:
    return _f(DCR_REF_OHM * math.sqrt(l_h / DCR_REF_H))


def _contact(a: str, b: str, pos: int) -> dict:
    return {"R": [a, b], "r": "contact_ohm", "tolerance": "none", "in": [pos]}


def values() -> dict:
    v: dict[str, dict] = {
        "source_impedance_ohm": {
            "value": 600.0,
            "source": "man: IMPEDANCE 500-600 ohms, input and output (the studio's 600 ohm line)",
        },
        "load_ohm": {
            "value": 600.0,
            "source": "man: IMPEDANCE 500-600 ohms, input and output",
        },
        "contact_ohm": {
            "value": 0.01,
            "source": "provisional: model knowledge (a rotary switch's or key's contact, ~10 mOhm)",
        },
        "numerical_leak_ohm": {
            "value": 1.0e9,
            "source": "numerical: a DC path for the network's ends while the key is at OUT",
        },
        "passive_seed": {
            "value": 0,
            "genome": "passives.seed",
            "source": "numerical: which set of parts a unit is built from",
        },
        "passive_spread": {
            "value": 0.0,
            "genome": "passives.spread",
            "source": "provisional: fraction of each part's tolerance band its deviation spans "
            "(0 = every part at its printed value)",
        },
        "tol_filter_c_pct": {
            "value": 5.0,
            "source": "provisional: model knowledge (a filter's capacitors set its frequencies: "
            "close-tolerance paper or film, 5%; the drawing prints none)",
        },
    }
    for f, (c_uf, l_mh) in LOW.items():
        v[f"c_lo_{f}_f"] = {
            "value": _f(c_uf * 1e-6),
            "source": f"dwg: C-1 = C-2 = {c_uf} uF on {f} cps (HLF-3C table)",
        }
        v[f"l_lo_{f}_h"] = {
            "value": _f(l_mh * 1e-3),
            "source": f"dwg-hlf3: the LF tapped toroid's {l_mh:g} mH tap on {f} cps (the HLF-3C "
            "table names L-1's taps by colour only; its LF positions are the HLF-3's); "
            f"constant-K at 500 ohm: {DESIGN_OHM / (4 * math.pi * f) * 1e3:.0f} mH",
        }
        v[f"r_lo_{f}_ohm"] = {"value": dcr_ohm(l_mh * 1e-3), "source": DCR_SOURCE}
    for f, (c_uf, l_mh) in HIGH.items():
        v[f"c_hi_{f}_f"] = {
            "value": _f(c_uf * 1e-6),
            "source": f"dwg: C-3 = {c_uf} uF on {f / 1000:g} kc (HLF-3C table)",
        }
        if l_mh is None:
            l_h = _f(DESIGN_OHM / (2 * math.pi * f))
            src = (
                f"derived: R / (2 pi f) = {l_h * 1e3:.2f} mH per half-section, constant-K at "
                "the drawing's 500 ohm (the HLF-3C's 15 kc tap is only a colour, RED; the HLF-3 "
                "has no 15 kc position)"
            )
        else:
            l_h = _f(l_mh * 1e-3)
            src = (
                f"dwg-hlf3: the HF tapped toroids' {l_mh:g} mH tap on {f / 1000:g} kc (L-2 = L-3; "
                "the HLF-3C table names them by colour only); constant-K at 500 ohm: "
                f"{DESIGN_OHM / (2 * math.pi * f) * 1e3:.1f} mH"
            )
        v[f"l_hi_{f}_h"] = {"value": l_h, "source": src}
        v[f"r_hi_{f}_ohm"] = {"value": dcr_ohm(l_h), "source": DCR_SOURCE}
    return v


CONTROLS = {
    "low_cut_hz": {
        "value": 0,
        "choices": [0, *LOW],
        "unit": "position",
        "source": "man: LOW CUT-OFF, eleven positions: OFF, 50, 80, 100, 150, 250, 500, 750, "
        "1000, 1500, 2000 cps",
        "notes": "0 = OFF (full transmission)",
    },
    "high_cut_hz": {
        "value": 0,
        "choices": [*HIGH, 0],
        "unit": "position",
        "source": "man: HIGH CUT-OFF, eleven positions: 1.5, 2, 3, 4, 5, 6, 8, 10, 12, 15 kcs "
        "and OFF",
        "notes": "0 = OFF (full transmission)",
    },
    "filter_in": {
        "value": 1,
        "choices": [0, 1],
        "unit": "switch",
        "source": "man: IN-OUT KEY, 'permits cutting the filter in and out on cue'; dwg-hlf3: "
        "the key switches both ends of the network",
        "notes": "1 IN, 0 OUT (the line straight through)",
    },
}


def sections() -> list[dict]:
    key = {
        "SKEY": {
            "switch": "filter_in",
            "parts": {
                "RKEY_I": _contact("in_s", "f_in", 1),
                "RKEY_O": _contact("f_out", "out", 1),
                "RKEY_BY": _contact("in_s", "out", 0),
            },
        },
        "RLK_I": {"R": ["f_in", "0"], "r": "numerical_leak_ohm", "tolerance": "none"},
        "RLK_O": {"R": ["f_out", "0"], "r": "numerical_leak_ohm", "tolerance": "none"},
    }
    lo: dict[str, dict] = {"RC1_OFF": _contact("f_in", "lo", 0), "RC2_OFF": _contact("lo", "hp", 0)}
    for f in LOW:
        lo[f"C1_{f}"] = {"C": ["f_in", "lo"], "c": f"c_lo_{f}_f", "in": [f]}
        lo[f"L1_{f}"] = {"L": ["lo", f"l1_{f}"], "l": f"l_lo_{f}_h", "in": [f]}
        lo[f"RL1_{f}"] = {
            "R": [f"l1_{f}", "0"],
            "r": f"r_lo_{f}_ohm",
            "tolerance": "none",
            "in": [f],
        }
        lo[f"C2_{f}"] = {"C": ["lo", "hp"], "c": f"c_lo_{f}_f", "in": [f]}
    hi: dict[str, dict] = {
        "RL2_OFF": _contact("hp", "hi", 0),
        "RL3_OFF": _contact("hi", "f_out", 0),
    }
    for f in HIGH:
        hi[f"L2_{f}"] = {"L": ["hp", f"l2_{f}"], "l": f"l_hi_{f}_h", "in": [f]}
        hi[f"RL2_{f}"] = {
            "R": [f"l2_{f}", "hi"],
            "r": f"r_hi_{f}_ohm",
            "tolerance": "none",
            "in": [f],
        }
        hi[f"C3_{f}"] = {"C": ["hi", "0"], "c": f"c_hi_{f}_f", "in": [f]}
        hi[f"L3_{f}"] = {"L": ["hi", f"l3_{f}"], "l": f"l_hi_{f}_h", "in": [f]}
        hi[f"RL3_{f}"] = {
            "R": [f"l3_{f}", "f_out"],
            "r": f"r_hi_{f}_ohm",
            "tolerance": "none",
            "in": [f],
        }
    return [
        {
            "title": "line",
            "parts": {
                "Rsrc": {"R": ["in", "in_s"], "r": "source_impedance_ohm", "tolerance": "none"},
                "Rload": {"R": ["out", "0"], "r": "load_ohm", "tolerance": "none"},
                **key,
            },
        },
        {"title": "low cut-off", "parts": {"SLO": {"switch": "low_cut_hz", "parts": lo}}},
        {"title": "high cut-off", "parts": {"SHI": {"switch": "high_cut_hz", "parts": hi}}},
    ]


def make() -> str:
    caps = [f"C1_{f}" for f in LOW] + [f"C2_{f}" for f in LOW] + [f"C3_{f}" for f in HIGH]
    doc = {
        "title": "Pultec HLF-3C program and sound effects filter",
        "input": "in",
        "probes": ["out", "in_s", "f_in", "lo", "hp", "hi", "f_out"],
        "full_scale": {
            "input_volts_peak": {
                "value": 13.8,
                "source": "derived: sim_settings' audio.full_scale_volts_peak, the EQP-1A's "
                "scale (the source's EMF)",
            },
            "output_volts_peak": {
                "value": 6.9,
                "source": "derived: half the input's: a 600 ohm source into the 600 ohm load "
                "reads 0 dB with the key at OUT (man: INSERTION LOSS: zero)",
            },
        },
        "controls": CONTROLS,
        "values": values(),
        "tolerance": {
            "source": "provisional: the drawing prints no tolerances; the filter's capacitors "
            "at 5% (the coils have no draw: inductors take none)",
            "seed": "passive_seed",
            "spread": "passive_spread",
            "bands": {"filter_c": "tol_filter_c_pct"},
            "classes": {"filter_c": caps},
        },
        "sections": sections(),
    }
    return HEADER + yaml.safe_dump(doc, sort_keys=False, width=100, allow_unicode=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = make()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale: rerun scripts/make_pultec_hlf3c.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
