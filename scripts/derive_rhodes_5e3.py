"""A Rhodes Mark I Stage into the Fender 5E3 (docs/RHODES_PLAN.md, RH2-RH3; the user's
choice: "out of the 5E3 amp from the start").

    uv run python scripts/derive_rhodes_5e3.py [--check]

Writes config/circuits/rhodes_stage_5e3.yaml from config/circuits/fender_5e3.yaml by
patching its text (its comments and sources carry over): the harp (a `harp` part: the
component MK1_HARP, its 73 keys played by note events, the pickups' EMFs summed by their
wiring, behind their coils: 73 of 180 ohm in the manual's Fig. 10-4 arrangement), then the
Stage's passive controls (the 1973-on "bass boost": .047 uF in series with a 50K
reverse-taper pot across it, into the 10K audio-taper volume), a cable, and the 5E3's input
jack (its old input node, now `jack`). The circuit's audio input `in` is unused
(terminated). The pickups drive the circuit one way (their coils' current is negligible on
the tines), so this is one coupled simulation: the harp is a medium in the netlist
(circuitsim's harp.rs), stepped with it.

The generated file says it is generated; edit the stock file (or the patches here) and
rerun (`--check` exits 1 when the file on disk differs: tests/test_rhodes_5e3.py).
"""

