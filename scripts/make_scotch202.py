"""Scotch 202 (Dynarange, 1962; docs/PERIOD_GEAR_BACKLOG.md PG1, MT1), derived from the fitted
Scotch 111 (`SCOTCH111@3`) by Eilers' table, until 3M's data sheet for #201 / 202 / 203 is
found (data/schematics/ampex_300_4/README.md, "Still missing"; then a fitted version 2):

- the particles' coercivities (hc_median, sigma_hi) scaled by 315 / 270 Oe (sigma_ln, the
  distribution's shape, kept);
- Ms so the saturated flux per width stays 111's: Eilers gives both 0.64 lines per 1/4 in
  (0 dB re 111) on a 0.51 mil coating against 0.5;
- the orientation kept (provisional);
- the grain's particle volume halved: "low noise" (provisional: a reseller's "3 dB greater
  dynamic range through a lowered noise floor, not higher output", web:
  https://reeltoreelwarehouse.com/tape/scotch-202/; hiss power goes as the particle volume at
  a fixed packing).

Saves `config/components/scotch202/<N>.yaml` when the derived data differ from the latest
version (`--check`: exit 1 when a version is due).

    uv run python scripts/make_scotch202.py [--check]
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys

import yaml

from varimu.config import REPO_ROOT
from varimu.devices import versions

BASE = "SCOTCH111@3"
NAME = "SCOTCH202"
PUBLISHED = REPO_ROOT / "data" / "datasheets" / "published_points.yaml"
NOISE_VOLUME_FACTOR = 0.5


def derive() -> dict:
    _, text = versions.read_text(BASE)
    base = yaml.safe_load(text)
    pub = yaml.safe_load(PUBLISHED.read_text(encoding="utf-8"))
    p111, p202 = pub["SCOTCH111"], pub[NAME]
    hc = p202["coercivity_a_m"] / p111["coercivity_a_m"]
    flux = (p202["remanence_wb_per_m"] / p111["remanence_wb_per_m"]) * (
        p111["oxide_m"] / p202["oxide_m"]
    )
    src = "data/datasheets/published_points.yaml SCOTCH202 (Eilers' table, AES, row 202)"
    pa, nz = base["particles"], base["noise"]
    return {
        "name": NAME,
        "kind": "tape",
        "source": (
            "Scotch 202 (Dynarange: gamma-Fe2O3 on polyester, 1962): SCOTCH111@3's fitted "
            "ensemble moved to Eilers' coercivity and flux by scripts/make_scotch202.py "
            "(provisional until 3M's data sheet: data/schematics/ampex_300_4/README.md)"
        ),
        "coating": {"thickness_m": float(p202["oxide_m"]), "source": f"{src}: 0.51 mil oxide"},
        "base": {"thickness_m": float(p202["base_m"]), "source": f"{src}: 1.42 mil polyester"},
        "particles": {
            "hc_median_a_m": float(pa["hc_median_a_m"] * hc),
            "sigma_ln_hc": float(pa["sigma_ln_hc"]),
            "sigma_hi_a_m": float(pa["sigma_hi_a_m"] * hc),
            "ms_a_m": float(pa["ms_a_m"] * flux),
            "h_max_a_m": float(pa["h_max_a_m"]),
            "n_table": int(pa["n_table"]),
            "source": (
                f"derived: {BASE}'s ensemble with its coercivities x {hc:.4f} (315 / 270 Oe) and "
                f"Ms x {flux:.4f} (the same 0.64 lines per 1/4 in on 0.51 mil instead of 0.5), "
                f"{src}; the shape (sigma_ln) kept: provisional"
            ),
        },
        "orientation": {
            "kappa": float(base["orientation"]["kappa"]),
            "n": int(base["orientation"]["n"]),
            "source": f"provisional: {BASE}'s (no bias curves for 202 found)",
        },
        "noise": {
            "particle_volume_m3": float(nz["particle_volume_m3"] * NOISE_VOLUME_FACTOR),
            "packing": float(nz["packing"]),
            "packing_sigma": float(nz["packing_sigma"]),
            "packing_corr_m": float(nz["packing_corr_m"]),
            "source": (
                f"provisional: {BASE}'s with the particle volume halved, 3 dB less hiss "
                "('low noise': 3 dB greater dynamic range through a lowered noise floor, not "
                "higher output; web: https://reeltoreelwarehouse.com/tape/scotch-202/, a "
                "reseller); packing and its field kept"
            ),
        },
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when a new version is due")
    a = ap.parse_args()
    data = derive()
    if versions.versions(NAME):
        ref, text = versions.read_text(NAME)
        if yaml.safe_load(text) == data:
            print(f"unchanged {ref}")
            return 0
    if a.check:
        print(f"{NAME}: a new version is due")
        return 1
    header = (
        f"# Generated by scripts/make_scotch202.py on {dt.date.today().isoformat()}.\n"
        "# Don't edit by hand: change the inputs (SCOTCH111, published_points.yaml) and rerun.\n"
    )
    ref = versions.save(NAME, header + yaml.safe_dump(data, sort_keys=False, width=100))
    print(f"saved {ref}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
