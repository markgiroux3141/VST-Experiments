"""Generate oscillators 2 and 3 of the Minimoog's board No. 1 (config/circuits/minimoog_osc2.yaml,
minimoog_osc3.yaml) from oscillator 1's file, config/circuits/minimoog_vco.yaml
(docs/MINIMOOG_PLAN.md
MM3; the readings in data/schematics/minimoog/README.md, "Oscillators 2 and 3"). Never edit the
generated files; edit oscillator 1's or this script and rerun.

    uv run python scripts/make_minimoog_oscillators.py [--check]

Fig 9-2 draws the three oscillators with the same core, expo converter and shapers, value for value
(the reset's and the rectangle's event tables are oscillator 1's:
config/events/minimoog_osc_*.json).
What differs:
  - SHIFT's series resistor: R53 / R93 82.5K 1% (oscillator 1's R13 is 69.8K);
  - OSC 2 / OSC 3 FREQUENCY: a 5K linear pot from +10 V over 5.1K to ground (7.5 V +- 2.5 V)
    through R54 / R96 402K 1% into the summer (+- a fifth); oscillator 1 has none (its R15 402K
    open);
  - oscillator 3's OSC 3 CONTROL switch (Fig 9-2 / 9-17): ON, pin 16A on -10 V (15A); OFF, on the
    board's -5 V, and its other pole puts the FREQUENCY pot's wiper through R97 121K into the summer
    as well (+- 2.75 octaves). 16A drives Q3 (2N3904, R61 100K) and Q19 (2N3904, R98 69.8K): off
    (ON), Q2 (E101, R60 1M gate to source) passes the primary summer's output to oscillator 3's
    SCALE; on (OFF), Q3 pulls Q2's gate to -10 V and Q19 holds the SCALE line near -10 V: the keys
    no longer reach oscillator 3;
  - oscillator 3's reverse sawtooth (REV SAW 3 OUT, 7B): Q20 (2N3904, emitter grounded) sinks
    current from +10 V through R123 330 (C37 5.6 uF) and R124 2.2K, its collector's node fed back to
    its base through R129 68K, the sawtooth in through R130 33K (R128 390K to -10 V): an inverting
    stage, about -68K / 33K; R133 7.5K / R134 18K to -10 V divide the collector down to 7B.
Each oscillator has its own trims (scripts/minimoog_vco_trim.py --circuit NAME --write); the
generated file keeps the values its trims last wrote (they're read back before regenerating).

Designators (oscillator 1 / 2 / 3; the parts keep oscillator 1's names): SHIFT R14 / R52 / R90 with
R13 / R53 / R93, SCALE R16 / R55 / R91 with R17 / R56 / R94, OCT ADJ R18 / R57 / R92 with R19 /
R58 /
R95, feedback R21 / R59 / R99, R22 / R62 / R100, R23 / R63 / R101, R24 / R64 / R102; the 726 IC5 /
IC10 / IC15 with R30 / R70 / R108 (I_R); the +5 V reference IC4A / IC9A / IC14A with C6 / C17 / C28;
C7 / C18 / C29; HI END R31 / R71 / R109; the reset JFET Q4 / Q9 / Q14; the ramp buffer IC7 / IC12 /
IC17 with Q5 / Q10 / Q15; the comparators IC8 / IC13 / IC18; the triangle's Q6 / Q11 / Q16 with
R40 /
R80 / R118, R41 / R81 / R119, C13 / C24 / C35; the duty select R135 / R136 / R137; the RANGE buffer
(board 6) IC1 / IC2 / IC3 on pins 14A / 13A / 11A.
"""

import argparse
import copy
import sys

import yaml

from varimu.config import CONFIG_DIR

CIRC = CONFIG_DIR / "circuits"
SRC = CIRC / "minimoog_vco.yaml"
TRIMS = ("r14_at", "r16_at", "r18_at", "r31_at")


def header(i: int) -> str:
    return (
        "# GENERATED by scripts/make_minimoog_oscillators.py from minimoog_vco.yaml "
        "(oscillator 1):\n"
        f"# the Minimoog's oscillator {i} (board No. 1, Fig 9-2), with the board's primary "
        "summer,\n"
        "# -5 V reference and range ladder. Never edit this file (its trims are written by\n"
        f"# scripts/minimoog_vco_trim.py --circuit minimoog_osc{i} --write, and kept on "
        "regenerating).\n"
        "# See the script's docstring for what differs from oscillator 1.\n"
    )


def section(d: dict, title: str) -> dict:
    return next(s for s in d["sections"] if s["title"] == title)


def kept_trims(i: int) -> dict:
    """The trims the generated file has now (its own, written by the trim script)."""
    path = CIRC / f"minimoog_osc{i}.yaml"
    if not path.exists():
        return {}
    v = yaml.safe_load(path.read_text(encoding="utf-8"))["values"]
    return {k: v[k] for k in TRIMS if k in v}


def oscillator(i: int) -> dict:
    d = copy.deepcopy(yaml.safe_load(SRC.read_text(encoding="utf-8")))
    d["title"] = f"Minimoog oscillator {i} (board No. 1)"
    d["sections"] = [
        {**s, "title": f"osc {i} summer"} if s["title"] == "osc 1 summer" else s
        for s in d["sections"]
    ]
    v = d["values"]
    n_shift = {2: "R53", 3: "R93"}[i]
    v["r13_ohm"] = {
        "value": 82.5e3,
        "source": f"Fig 9-2: {n_shift} 82.5K 1% (oscillator {i}'s SHIFT; network "
        f"{ {2: 'N3', 3: 'N4'}[i] }; oscillator 1's R13 is 69.8K)",
    }
    trims = kept_trims(i)
    for k in TRIMS:
        if k in trims:
            v[k] = {
                "value": trims[k]["value"],
                "source": f"trimmed: scripts/minimoog_vco_trim.py --circuit minimoog_osc{i} "
                "--write (Folkman's tuning through the keyboard, as oscillator 1's)",
            }
        else:
            v[k] = {
                **v[k],
                "source": f"provisional: oscillator 1's trim until oscillator {i}'s own "
                f"(scripts/minimoog_vco_trim.py --circuit minimoog_osc{i} --write)",
            }
    r_freq = {2: "R54", 3: "R96"}[i]
    v["r_freq_ohm"] = {"value": 5.0e3, "source": f"Fig 9-2 / 9-17: OSC {i} FREQ, a 5K LIN pot"}
    v["r_freq_foot_ohm"] = {"value": 5.1e3, "source": f"Fig 9-2: OSC {i} FREQ's 5.1K to ground"}
    v["r_freq_in_ohm"] = {
        "value": 402.0e3,
        "source": f"Fig 9-2: {r_freq} 402K 1% (OSC {i} FREQ into the summer, '7.5V +-2.5V, +-5TH')",
    }
    d["controls"]["freq"] = {
        "value": 0.5,
        "min": 0.0,
        "max": 1.0,
        "unit": "rotation",
        "source": f"Fig 9-2: OSC {i} FREQUENCY, a 5K linear pot from +10 V over 5.1K to ground "
        "(7.5 V +- 2.5 V, +- a fifth); 0.5 = centred",
    }
    panel = section(d, "rails and panel")["parts"]
    panel["RFREQ"] = {"pot": ["vp", "freqw", "freqf"], "r": "r_freq_ohm", "at": "freq"}
    panel["RFREQF"] = {"R": ["freqf", "0"], "r": "r_freq_foot_ohm"}
    summer = section(d, f"osc {i} summer")["parts"]
    summer["RFREQIN"] = {"R": ["freqw", "s6"], "r": "r_freq_in_ohm"}
    probes = list(d["probes"])
    if i == 3:
        osc3_control(d, v, panel, summer)
        probes += ["rsaw", "sl3", "n16"]
    d["probes"] = probes
    return d


def osc3_control(d: dict, v: dict, panel: dict, summer: dict) -> None:
    v.update(
        {
            "r97_ohm": {
                "value": 121.0e3,
                "source": (
                    "Fig 9-2: R97 121K 1% (network N4: OSC 3 CONTROL OFF, the FREQ pot into the "
                    "summer, '+-2.75 OCT')"
                ),
            },
            "r60_ohm": {"value": 1.0e6, "source": "Fig 9-2: R60 1M (Q2's gate to its source)"},
            "r61_ohm": {"value": 100.0e3, "source": "Fig 9-2: R61 100K (16A into Q3's base)"},
            "r98_ohm": {"value": 69.8e3, "source": "Fig 9-2: R98 69.8K 1% (16A into Q19's base)"},
            "r123_ohm": {
                "value": 330.0,
                "source": "Fig 9-2: R123 330 ohm (REV SAW's +10 V decoupling)",
            },
            "c37_f": {"value": 5.6e-6, "source": "Fig 9-2: C37 5.6 uF / 35 V tantalum"},
            "c37_esr_ohm": {
                "value": 2.0,
                "source": "provisional: model knowledge (a 5.6 uF solid tantalum's ESR, a few "
                "ohms)",
            },
            "r124_ohm": {"value": 2.2e3, "source": "Fig 9-2: R124 2.2K"},
            "r128_ohm": {"value": 390.0e3, "source": "Fig 9-2: R128 390K (Q20's base to -10 V)"},
            "r129_ohm": {"value": 68.0e3, "source": "Fig 9-2: R129 68K"},
            "r130_ohm": {
                "value": 33.0e3,
                "source": "Fig 9-2: R130 33K (the sawtooth into Q20's base)",
            },
            "r133_ohm": {
                "value": 7.5e3,
                "source": "Fig 9-2: R133 7.5K (Q20's collector, REV SAW 3 OUT, 7B)",
            },
            "r134_ohm": {"value": 18.0e3, "source": "Fig 9-2: R134 18K (to -10 V)"},
            "r_switch_open_ohm": {
                "value": 1.0e10,
                "source": (
                    "provisional: model knowledge (an open switch contact's insulation, 1e10-1e12"
                    " ohm; closed it is a pot's end, MIN_R_OHM)"
                ),
            },
            "q_e101": {
                "value": "2N5457@1",
                "source": (
                    "provisional: model knowledge (Fig 9-2's Q2 E101, a Siliconix general-purpose"
                    " N-channel JFET in the plastic E package; no card found): the 2N5457 card "
                    "(Central's typical part) stands in; its on resistance in series with SCALE's"
                    " ~97K is trimmed out by SCALE"
                ),
            },
        }
    )
    d["controls"]["control"] = {
        "value": 1,
        "choices": [0, 1],
        "unit": "switch",
        "source": "Fig 9-2 / 9-17: OSC 3 CONTROL (SW2): 1 ON (16A on -10 V: the keys play "
        "oscillator "
        "3), 0 OFF (16A on -5 V, the FREQUENCY pot also through R97); contacts always in the "
        "circuit, so a flip updates a stream in place",
    }
    d["devices"]["QE"] = {"device": "q_e101"}
    # the switch's poles: 10A (OFF: the FREQ wiper; ON: open), 16A (OFF: -5 V; ON: -10 V)
    panel["RCTLA"] = {"rheostat": ["freqw", "n10"], "r": "r_switch_open_ohm", "at": "control"}
    panel["RCTLB"] = {"rheostat": ["m5", "n16"], "r": "r_switch_open_ohm", "at": "control"}
    panel["RCTLC"] = {
        "rheostat": ["vn", "n16"],
        "r": "r_switch_open_ohm",
        "at": "control",
        "reverse": 1,
    }
    summer["R97"] = {"R": ["n10", "s6"], "r": "r97_ohm"}
    # the keys' path into SCALE: Q2 from the primary summer's output (its source) to the SCALE line
    summer["R16"] = {**summer["R16"], "rheostat": ["sl3", "s8"]}
    summer["JQ2"] = {"jfet": ["sl3", "g2", "pri"], "model": "QE"}
    summer["R60"] = {"R": ["pri", "g2"], "r": "r60_ohm"}
    summer["Q3"] = {"bjt": ["g2", "b3", "vn"], "model": "QN"}
    summer["R61"] = {"R": ["n16", "b3"], "r": "r61_ohm"}
    summer["Q19"] = {"bjt": ["sl3", "b19", "vn"], "model": "QN"}
    summer["R98"] = {"R": ["n16", "b19"], "r": "r98_ohm"}
    shapers = section(d, "shapers")["parts"]
    shapers.update(
        {
            "R123": {"R": ["vp", "va"], "r": "r123_ohm"},
            "C37": {"C": ["c37t", "0"], "c": "c37_f"},
            "RC37": {"R": ["va", "c37t"], "r": "c37_esr_ohm"},
            "R124": {"R": ["va", "vb"], "r": "r124_ohm"},
            "R129": {"R": ["vb", "b20"], "r": "r129_ohm"},
            "R128": {"R": ["vn", "b20"], "r": "r128_ohm"},
            "R130": {"R": ["out", "b20"], "r": "r130_ohm"},
            "Q20": {"bjt": ["vb", "b20", "0"], "model": "QN"},
            "R133": {"R": ["vb", "rsaw"], "r": "r133_ohm"},
            "R134": {"R": ["rsaw", "vn"], "r": "r134_ohm"},
        }
    )


def text_of(i: int) -> str:
    body = yaml.safe_dump(oscillator(i), sort_keys=False, default_flow_style=None, width=10**9)
    return header(i) + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = False
    for i in (2, 3):
        path = CIRC / f"minimoog_osc{i}.yaml"
        text = text_of(i)
        if a.check:
            ok = path.exists() and path.read_text(encoding="utf-8").replace("\r\n", "\n") == text
            print(f"{path.name}: {'up to date' if ok else 'STALE'}")
            stale |= not ok
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
