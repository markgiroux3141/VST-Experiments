"""The Ampex 300-4 (docs/PERIOD_GEAR_BACKLOG.md, PG1, MT5): four channels of the 351's
electronics on a 1/2 in four-track headblock, generated from the machine's own circuit file.

    uv run python scripts/make_ampex_300_4.py [--check]

Writes config/circuits/ampex_300_4.yaml from config/circuits/ampex_351.yaml, the 351's
alignment (reports/tape/ampex_351_alignment.json: its settings as the controls' values,
as scripts/make_351_echo.py does) and the deck's trims (config/ampex_300_4_trims.yaml, when
scripts/ampex_300_4_trim.py has written them):

- **Four channels**, each the 351 as drawn (its supply, record and reproduce amplifiers, the
  line output into 600 ohm): channel 1's parts and nodes as in the 351, channels 2-4's
  suffixed `_2` .. `_4` (the 351-2's precedent, DELAY_PLAN.md "PING-PONG": one chassis per
  channel, each with its own supply). Channel 1 records the input `in`; channels 2-4 the
  audio inputs `in2` .. `in4` (read in the record side's multi-rate island as the input is).
  The line outputs are `out`, `out_2` .. `out_4`.
- **One master bias oscillator** (Ampex AI-14 p 14: a Master Bias Oscillator and slave
  chassis; data/schematics/ampex_300_4/README.md): channel 1's 1V6 / 1T5 and its erase head;
  each slave's bias line (4R70 and its own BIAS ADJUST, `bias_adjust_f_2` ..) from the
  master's erase-head node. The slaves' oscillators and erase heads aren't in the circuit
  (provisional: their erase heads' load on the master isn't modelled; the tape starts
  erased).
- **One island**: the four record sides (record amplifier, bias and head driver) at the
  351's 20 steps per sample, one multi-rate part (decision 7, PERIOD_GEAR_BACKLOG.md).
- **The tape**: four tape parts on SCOTCH202@1, 70 mil tracks (the 354 manual's four-track
  master), one crosstalk group (`deck`, tracks 1-4: a head reads its neighbours' tracks,
  MT3), each record head's playback (Sel-Sync's readout, MT4) on `sy`, `sy_2` .. into a
  monitoring load. The repro heads are the 351's (decision 6a), wound for the full-track
  head's output (rep_h_per_a scaled by the widths, as the 351-2's two-track heads are) so the
  351's playback alignment carries over. 15 ips only (the 351's 7-1/2 ips tape part is left
  out with the speed switch).
- **The record heads' coupling** (MT3's record term): each head's coil coupled to its
  neighbour's (`k_rec_heads`) and a capacitance between their hot ends (`c_rec_heads_f`),
  sized by scripts/ampex_300_4_trim.py to the fit's record-side crosstalk at 10 kHz.

The generated file says it is generated; edit its sources and rerun (`--check` exits 1 when
the file on disk differs: tests/test_ampex_300_4.py).
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
from typing import Any

import yaml

from varimu.circuit import spec
from varimu.config import CONFIG_DIR, REPO_ROOT

BASE = "ampex_351"
OUT = "ampex_300_4"
OUT_CHANNEL = "ampex_300_4_channel"
ALIGNMENT = REPO_ROOT / "reports" / "tape" / "ampex_351_alignment.json"
#: A deck channel's own alignment (scripts/align_300_4.py: the 351's procedure on
#: ampex_300_4_channel.yaml); until it exists the deck carries the 351's.
CHANNEL_ALIGNMENT = REPO_ROOT / "reports" / "multitrack" / "deck" / "channel_alignment.json"
TRIMS = CONFIG_DIR / "ampex_300_4_trims.yaml"
FIT = REPO_ROOT / "reports" / "multitrack" / "crosstalk" / "fit.json"
TRACKS = 4
MIL = 25.4e-6
#: The master oscillator: channel 1's; the slaves keep only their bias line (4R70, BIAS
#: ADJUST) from the master's erase-head node. (make_351_echo.OSCILLATOR_NETWORK less those.)
OSCILLATOR = (
    "C35 C32 C36 R61 R62 R63 RT5A LT5A RT5B LT5B LT5S RT5S KAB KAS KBS R64 C33 C34 LER RER"
).split()
OSC_TUBES = ("V6A", "V6B")
ALIGNED_SOURCE = "derived: the {what}'s alignment ({path}, varimu.measure.tape_align, key {key})"
HEADER = """# GENERATED by scripts/make_ampex_300_4.py from config/circuits/{base}.yaml,
# reports/tape/ampex_351_alignment.json and config/ampex_300_4_trims.yaml: don't edit; edit
# those and rerun (`uv run python scripts/make_ampex_300_4.py`). The Ampex 300-4: four
# channels of the 351's electronics on a 1/2 in four-track headblock, one master bias
# oscillator, one tape (docs/PERIOD_GEAR_BACKLOG.md, PG1, MT5; the script's docstring).

"""


def deck_values(fit: dict, trims: dict) -> dict[str, dict]:
    """The deck's own values (the format, the crosstalk, the record heads' coupling)."""
    p4 = fit["four_track"]["params"]
    width = 70 * MIL
    fit_src = "reports/multitrack/crosstalk/fit.json, scripts/multitrack_crosstalk_study.py"
    k_rec = trims.get("k_rec_heads", 0.02)
    c_rec = trims.get("c_rec_heads_f", 50e-12)
    trimmed = (
        "derived: scripts/ampex_300_4_trim.py (config/ampex_300_4_trims.yaml): " if trims else ""
    )
    return {
        "tape_model": {
            "value": "SCOTCH202@1",
            "source": "config/components/scotch202/1.yaml (Scotch 202, 1962: the session's "
            "tape, provisional: scripts/make_scotch202.py; PERIOD_GEAR_BACKLOG.md decision 2)",
        },
        "track_m": {
            "value": width,
            "source": "data/schematics/ampex_300_4/README.md (the 354 manual p 44: the 4 track "
            "master's 70 mil tracks)",
        },
        "rep_h_per_a": {
            "value": 2.46e7 * 5.94e-3 / width,
            "source": "derived: the 351's full-track head's (2.46e7, calibrated to the drawing's "
            "-68 dB) times 5.94 mm / 70 mil: a four-track repro head wound for the full-track "
            "head's output (provisional, as the 351-2's two-track heads), so the 351's playback "
            "alignment carries over",
        },
        "track_pitch_m": {
            "value": 130 * MIL,
            "source": "data/schematics/ampex_300_4/README.md (the 354 manual p 44: 70 mil "
            "tracks 60 mil apart, 130 mil centres)",
        },
        "xt_unshielded": {
            "value": p4["unshielded"],
            "source": f"provisional: fitted to Ampex's measured crosstalk ({fit_src}: "
            "unshielded, the contour's flux the interchannel shields leave)",
        },
        "xt_contour_width_m": {
            "value": p4["contour_width_ratio"] * width,
            "source": f"derived: the fit's contour width ratio {p4['contour_width_ratio']:.5g} "
            f"({fit_src}) times the 70 mil track",
        },
        "xt_core": {
            "value": p4["core"],
            "source": f"derived: the fit's cores' coupling ({fit['fit']['core_db']:.1f} dB, "
            f"signed; {fit_src}) +5 dB for four tracks on 1/2 in (Ampex AI-14 p 13: ~50 dB "
            "against three tracks' ~55; varimu.multitrack.crosstalk.FOUR_VS_THREE_DB)",
        },
        "k_rec_heads": {
            "value": k_rec,
            "source": trimmed + "the record heads' mutual inductance (Ampex 354 manual p 12), "
            "provisional: model knowledge (stacked heads with interchannel shields)"
            if not trims
            else trimmed + "the record heads' mutual inductance (Ampex 354 manual p 12)",
        },
        "c_rec_heads_f": {
            "value": c_rec,
            "source": trimmed + "the capacitance between neighbouring record heads' hot ends "
            "(windings and leads; Ampex 354 manual p 12), sized with k_rec_heads to the fit's "
            f"record-side crosstalk at 10 kHz ({fit_src})"
            if trims
            else "provisional: model knowledge (windings and leads, ~50 pF: about the fit's "
            "record-side crosstalk at 10 kHz through the 351's head driver; "
            "scripts/ampex_300_4_trim.py sizes it)",
        },
        "r_sync_load_ohm": {
            "value": 1.0e6,
            "source": "provisional: model knowledge (Sel-Sync's monitoring tap: a reproduce "
            "preamp's grid leak, the readout barely loaded)",
        },
    }


def heads_section(c: dict) -> dict:
    return next(s for s in c["sections"] if s["title"] == "heads and tape")


def one_channel(base: dict, alignment: dict, fit: dict, trims: dict) -> dict:
    """The 351 aligned (`alignment`: the 351's or a deck channel's), at 15 ips, its tape part
    on the deck's tape and track 1 of the group, its record head's playback on `sy`."""
    c = copy.deepcopy(base)
    for k, v in alignment["overrides"].items():
        if k not in c["controls"]:
            continue  # the 7-1/2 ips trim: no 7-1/2 ips here
        ctl = c["controls"][k]
        ctl["value"] = float(v)
        ctl["source"] = ALIGNED_SOURCE.format(
            what=alignment["what"], path=alignment["path"], key=alignment["key"]
        )
    del c["controls"]["speed"]
    for k, v in deck_values(fit, trims).items():
        c["values"][k] = v
    heads = heads_section(c)
    stp = heads["parts"].pop("STP")
    tp = copy.deepcopy(stp["parts"]["TP"])
    tp.pop("in")
    tp["tape"] = [*tp["tape"], "sy"]
    tp["sync_l_h"] = "rec_l_h"
    tp["crosstalk_group"] = "deck"
    tp["crosstalk_track"] = 1
    tp["crosstalk_pitch_m"] = "track_pitch_m"
    tp["crosstalk_unshielded"] = "xt_unshielded"
    tp["crosstalk_contour_width_m"] = "xt_contour_width_m"
    tp["crosstalk_core"] = "xt_core"
    heads["parts"] = {
        "TP": tp,
        "RSY": {"R": ["sy", "0"], "r": "r_sync_load_ohm", "tolerance": "none"},
        **heads["parts"],
    }
    return c


def compose(base: dict, alignment: dict, fit: dict, trims: dict) -> dict:
    sys.path.insert(0, str(REPO_ROOT / "scripts"))
    from compose_chain import Renamer

    c = one_channel(base, alignment, fit, trims)
    c["title"] = "Ampex 300-4 (four tracks on 1/2 in)"
    # The channel's alignment includes its bias; each slave's BIAS ADJUST starts there
    # (scripts/ampex_300_4_trim.py matches each head's bias current to channel 1's).
    secs: list[dict[str, Any]] = c["sections"]
    devices = dict(c["devices"])
    classes = c["tolerance"]["classes"]
    first = {cls: list(names) for cls, names in classes.items()}  # channel 1's
    extra = []
    bias_ctl = c["controls"]["bias_adjust_f"]
    for ch in range(2, TRACKS + 1):
        tag = str(ch)
        r = Renamer(c, tag, keep_nodes=("ers",))
        r.keys = set()  # every channel reads the same values (identical chassis)
        for s in secs:
            b = copy.deepcopy(s)
            b["title"] = f"{s['title']} ({ch})"
            parts = {}
            for n, p in s["parts"].items():
                if s["title"] == "bias and head driver" and (n in OSCILLATOR or n == "SOSC"):
                    continue  # the master's
                parts[r.part_name(n)] = r.part(p)
            b["parts"] = parts
            if s["title"] == "bias and head driver":
                # The slave's BIAS ADJUST: its own control.
                parts[f"C13_{tag}"]["c"] = f"bias_adjust_f_{tag}"
            if s["title"] == "heads and tape":
                parts[f"TP_{tag}"]["crosstalk_track"] = ch
            extra.append(b)
        c["controls"][f"bias_adjust_f_{tag}"] = {
            **bias_ctl,
            "notes": f"channel {ch}'s BIAS ADJUST (5C13), on the master oscillator's line",
        }
        devices.update({f"{k}_{tag}": v for k, v in c["devices"].items() if k not in OSC_TUBES})
        for cls, names in first.items():
            osc = set(OSCILLATOR)
            classes[cls] = [*classes[cls], *(f"{n}_{tag}" for n in names if n not in osc)]
    # The record heads' coupling: each to its neighbour, in the island.
    coupling: dict[str, Any] = {}
    for ch in range(1, TRACKS):
        a = "" if ch == 1 else f"_{ch}"
        b = f"_{ch + 1}"
        coupling[f"KREC{ch}{ch + 1}"] = {"K": [f"LHEAD{a}", f"LHEAD{b}"], "k": "k_rec_heads"}
        coupling[f"CREC{ch}{ch + 1}"] = {
            "C": [f"rec{a}", f"rec{b}"],
            "c": "c_rec_heads_f",
            "tolerance": "none",
        }
    island = next(s for s in secs if s["title"] == "bias and head driver")
    c["sections"] = [
        *secs,
        *extra,
        {
            "title": "record heads' coupling",
            "substeps": island["substeps"],
            "method": island["method"],
            "tube_tables": island["tube_tables"],
            "parts": coupling,
        },
    ]
    # Each channel's BIAS ADJUST trimmed on the deck (its head's bias current at the
    # channel's alignment: the master drives four bias lines, the heads couple).
    for ch in range(1, TRACKS + 1):
        k = "bias_adjust_f" if ch == 1 else f"bias_adjust_f_{ch}"
        if k in trims:
            c["controls"][k]["value"] = float(trims[k])
            c["controls"][k]["source"] = (
                "derived: scripts/ampex_300_4_trim.py (config/ampex_300_4_trims.yaml): the "
                "head's bias current at the deck channel's alignment"
            )
    c["devices"] = devices
    c["audio_inputs"] = {f"in{ch}": f"in_{ch}" for ch in range(2, TRACKS + 1)}
    tags = [""] + [f"_{ch}" for ch in range(2, TRACKS + 1)]
    c["probes"] = [
        *(f"out{t}" for t in tags),
        *(f"sy{t}" for t in tags),
        *(f"rh{t}" for t in tags),
        *(f"hra{t}" for t in tags),
        *(f"rbc{t}" for t in tags),
        "ers",
        *(f"b330{t}" for t in tags),
    ]
    return c


def _alignment(path, what: str) -> dict:
    d = json.loads(path.read_text(encoding="utf-8"))
    return {**d, "what": what, "path": str(path.relative_to(REPO_ROOT)).replace("\\", "/")}


CHANNEL_HEADER = """# GENERATED by scripts/make_ampex_300_4.py from config/circuits/{base}.yaml and
# reports/tape/ampex_351_alignment.json: don't edit; edit those and rerun (`uv run python
# scripts/make_ampex_300_4.py`). One channel of the Ampex 300-4 (the 351 on the deck's tape
# and four-track head, 15 ips), for its alignment (scripts/align_300_4.py: the 351's procedure),
# which the deck's four channels then carry.

"""


def render() -> dict[str, str]:
    base = yaml.safe_load(spec.circuit_path(BASE).read_text(encoding="utf-8"))
    a351 = _alignment(ALIGNMENT, "Ampex 351")
    fit = json.loads(FIT.read_text(encoding="utf-8"))
    trims = (yaml.safe_load(TRIMS.read_text(encoding="utf-8")) if TRIMS.exists() else {}) or {}
    deck_al = _alignment(CHANNEL_ALIGNMENT, "deck channel") if CHANNEL_ALIGNMENT.exists() else a351
    dump = lambda c: yaml.safe_dump(c, sort_keys=False, width=100, allow_unicode=True)  # noqa: E731
    channel = one_channel(base, a351, fit, trims)
    channel["title"] = "Ampex 300-4, one channel (for its alignment)"
    return {
        OUT: HEADER.format(base=BASE) + dump(compose(base, deck_al, fit, trims)),
        OUT_CHANNEL: CHANNEL_HEADER.format(base=BASE) + dump(channel),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = False
    for name, text in render().items():
        path = CONFIG_DIR / "circuits" / f"{name}.yaml"
        if args.check:
            same = path.exists() and path.read_text(encoding="utf-8") == text
            print("current" if same else f"stale: {path}")
            stale = stale or not same
            continue
        path.write_text(text, encoding="utf-8")
        spec.load_circuit(path)  # it loads
        print(f"wrote {path}")
    if stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
