"""The Ampex 351's electronics as a microphone preamplifier (the chains build-out's WP7,
docs/CHAINS_PLAN.md), generated from the machine's own circuit file.

    uv run python scripts/make_351_record.py [--check]

Writes config/circuits/ampex_351_record.yaml from config/circuits/ampex_351.yaml: the
machine's **direct monitor**, the METER AND OUTPUT switch 4S3 at RECORD LEVEL with the tape
stopped (man p 28: "The program can be audibly monitored through either the phone jacks
(PHONES) 4J6, Monitor 5J4, or the line out connector (LINE OUTPUT) 5J5 before the tape is in
motion"; p 77: "with the METER AND OUTPUT SWITCH in the record position, only the first two
stages of the record amplifier and the last three stages of the reproduce amplifier are
connected in the circuit, omitting record pre-emphasis and reproduce equalization"). So the
path (sch p 95): the microphone at LINE INPUT 5J1 into 6T1 (INPUT TRANSFER SWITCH 4S1 at
MICROPHONE), 1V1b, 1C1 and 1R8, RECORD LEVEL 4R9, 1V1a, 1C3 / 1C4 into RECORD CALIBRATE 4R12,
its wiper through 4S3a to 2V4a's grid, 2V4b the inverter, 2V5 push-pull into 6T3, the line
output into 600 ohm.

What changes from the machine's file:
- not in record mode: the record relay 3K1 is released, so 3R54 is back in series with 3R55
  (3K1b open) and the record line (3K1c) is dead: the oscillator 1V6 and the head driver 1V2a
  draw nothing and leave the netlist with the heads, the tape and the bias network;
- the microphone stage is in the signal path (the machine's file has 1V1b idle): 6T1 (a part
  number only: its construction provisional, its ratio from the drawing's signal voltages);
- INPUT TRANSFER (`input_transfer`): 0 MICROPHONE, 1 UNBALANCED BRIDGE (the machine's
  bridging input, 4R5 / 4R4 / 4R3 into RECORD LEVEL, bypassing 6T1 and 1V1b), as contacts
  that are always in the circuit; the BALANCED BRIDGE position isn't modeled;
- RECORD CALIBRATE 4R12 is a pot (`record_calibrate`), its wiper on 2V4a's grid; the
  reproduce amplifier's PLAYBACK LEVEL and its coupling capacitor 2C17 are off the path (4S3a
  takes 2V4a's grid away from them), its stages stay as the rails' load;
- 1V2b (the record amplifier's third stage, with the record EQ) stays: its grid loads 1V1a's
  plate through 1C5, its current the 250 V node;
- the record side runs at the audio rate (no `substeps`: nothing above Nyquist is left), and
  no noise block (the chain list's preamps have none).

RECORD CALIBRATE is set as the manual's alignment sets it (man p 83: RECORD CALIBRATE for 0
VU on the RECORD LEVEL position): the bridging input's operating level, -10 dBm, at the
aligned RECORD LEVEL (reports/tape/ampex_351_alignment.json) reads 0 VU, +8 dBm out
(scripts/a351_record_trim.py sets `RECORD_CALIBRATE` below).

The generated file says it is generated; edit its sources and rerun (`--check` exits 1 when
the file on disk differs: tests/test_ampex_351_record.py).
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
from typing import Any

import yaml

from varimu.circuit import spec
from varimu.config import CONFIG_DIR, REPO_ROOT

BASE = "ampex_351"
OUT = "ampex_351_record"
ALIGNMENT = REPO_ROOT / "reports" / "tape" / "ampex_351_alignment.json"
#: RECORD CALIBRATE's rotation, from scripts/a351_record_trim.py (see the docstring).
RECORD_CALIBRATE = 0.1283

#: Sections of the machine kept, by title, and their parts left out.
KEEP = {
    "power supply": set(),
    "record amplifier": {"RIN_S", "RIN_SH", "RIN_F", "RMET"},
    "reproduce amplifier": {"CC3A", "RPLAY"},
    "output": set(),
}
#: The machine's devices the preamp doesn't use (the oscillator, the head driver).
DROP_DEVICES = {"V2A", "V6A", "V6B"}
#: The machine's controls the preamp has (the rest belong to the tape, the bias and playback).
KEEP_CONTROLS = ["record_level", "rec_eq_hi_f", "rec_eq_lo_f", "equalization", "rep_eq_hi",
                 "mains_v_rms", "mains_hz"]  # fmt: skip

ALIGNED = (
    "derived: the machine's alignment (reports/tape/ampex_351_alignment.json, "
    "scripts/align_351.py): the factory's setting"
)

#: What the script adds (controls, values, the microphone input, RECORD CALIBRATE's part, the
#: full scale), in the circuit files' YAML style.
ADDED = REPO_ROOT / "scripts" / "make_351_record.yaml"

PROBES = ["out", "ia", "t1p", "g1b", "p1b", "k1b", "mo", "ib", "g1a", "p1a", "k1a", "met",
          "g4a", "p4a", "k4a", "p4b", "p5a", "p5b", "k5", "fbw", "b330", "b300", "b250",
          "b220", "b215", "b190"]  # fmt: skip

HEADER = """# GENERATED by scripts/make_351_record.py from config/circuits/{base}.yaml: don't edit;
# edit that (or the script) and rerun (`uv run python scripts/make_351_record.py`). The Ampex
# 351's direct monitor as a microphone preamplifier (docs/CHAINS_PLAN.md, WP7): 6T1, the
# record amplifier's first two stages, RECORD CALIBRATE into the reproduce amplifier's last
# three stages and 6T3, the tape stopped (the script's docstring has the sources and what
# changes from the machine's file).

"""


def _refs(x: Any, out: set[str]) -> None:
    if isinstance(x, str):
        out.add(x)
    elif isinstance(x, dict):
        for v in x.values():
            _refs(v, out)
    elif isinstance(x, list):
        for v in x:
            _refs(v, out)


def compose(base: dict, alignment: dict, added: dict) -> dict:
    added = copy.deepcopy(added)
    added["controls"]["record_calibrate"]["value"] = RECORD_CALIBRATE
    by_title = {s["title"]: s for s in base["sections"]}
    sections = [added["microphone_section"]]
    for title, drop in KEEP.items():
        s = by_title[title]
        parts = {k: copy.deepcopy(v) for k, v in s["parts"].items() if k not in drop}
        if title == "power supply":
            # 3R54 back in series: 3R55's part between two nodes, 3R54 ahead of it.
            parts["RB300"] = {"R": ["b330", "b300p"], "r": "r_b300_play_ohm"}
            parts["RB300B"] = {"R": ["b300p", "b300"], "r": "r_b300_ohm"}
        if title == "record amplifier":
            parts["RMET"] = added["record_calibrate_part"]
            title = "record amplifier, first two stages (and 1V2b idle)"
        if title == "reproduce amplifier":
            title = "reproduce amplifier (idle: the rails' load)"
        if title == "output":
            title = "reproduce amplifier's last three stages and the output"
        sections.append({"title": title, "parts": parts})

    used: set[str] = set()
    _refs([s["parts"] for s in sections], used)
    _refs(base.get("mains"), used)
    _refs(base["tolerance"], used)
    _refs(base["devices"], used)

    controls = {k: copy.deepcopy(base["controls"][k]) for k in KEEP_CONTROLS}
    for k, v in alignment["overrides"].items():
        if k in controls:
            controls[k]["value"] = v
            controls[k]["source"] = f"{ALIGNED}; {controls[k]['source']}"
    controls.update(added["controls"])

    values = {k: copy.deepcopy(v) for k, v in base["values"].items() if k in used}
    values.update(added["values"])

    kept_parts = {n for s in sections for n in s["parts"]}
    tol = copy.deepcopy(base["tolerance"])
    tol["classes"] = {b: [p for p in v if p in kept_parts] for b, v in tol["classes"].items()}
    tol["classes"]["r10"] = [p for p in tol["classes"]["r10"] if p != "RMET"]  # now a pot
    tol["classes"]["r10"] += ["RB300B", "RG1B_OUT"]
    tol["classes"]["pot"] += ["RMET"]
    tol["classes"]["paper"] += ["CC1B"]
    tol["classes"] = {b: v for b, v in tol["classes"].items() if v}
    tol["bands"] = {b: v for b, v in tol["bands"].items() if b in tol["classes"]}
    tol["source"] = tol["source"] + "; 6T1's parts as the machine's"

    devices = {k: copy.deepcopy(v) for k, v in base["devices"].items() if k not in DROP_DEVICES}

    return {
        "title": "Ampex 351 (direct monitor)",
        "input": "in",
        "probes": PROBES,
        "full_scale": added["full_scale"],
        "controls": controls,
        "values": values,
        "mains": copy.deepcopy(base["mains"]),
        "tolerance": tol,
        "devices": devices,
        "sections": sections,
    }


def render() -> str:
    base = yaml.safe_load(spec.circuit_path(BASE).read_text(encoding="utf-8"))
    alignment = json.loads(ALIGNMENT.read_text(encoding="utf-8"))
    added = yaml.safe_load(ADDED.read_text(encoding="utf-8"))
    c = compose(base, alignment, added)
    body = yaml.safe_dump(c, sort_keys=False, width=100, allow_unicode=True)
    return HEADER.format(base=BASE) + body


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    path = CONFIG_DIR / "circuits" / f"{OUT}.yaml"
    text = render()
    if args.check:
        ok = path.exists() and path.read_text(encoding="utf-8") == text
        print(f"{path.name}: {'current' if ok else 'STALE'}")
        sys.exit(0 if ok else 1)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
