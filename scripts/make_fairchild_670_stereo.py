"""The stereo 670: both channels of drawing A-96039 and its S301 MATRIXING switch
(docs/STEREO_PLAN.md, ST3b).

    uv run python scripts/make_fairchild_670_stereo.py [--check]

Writes config/circuits/fairchild_670_stereo.yaml from config/circuits/fairchild_670.yaml (one
channel, channel 2 lumped as its draw on the rails). Here channel 2 is the drawing's 2xx parts,
built from channel 1's sections (designators 1xx -> 2xx, AT101 -> AT102; its nodes suffixed
`_2`, its input `in_r`, its output `out_r`), on the same supply. Its panel is channel 1's with
`_2` (input_atten_db_2, ac_threshold_2, time_constant_2, dc_threshold_2, balance_2, zero_2); its
values are channel 1's (the drawing prints the same, data/schematics/fairchild_670/README.md
"Channel 2 and S301").

**S301** (control `mode`: 1 LEFT & RIGHT, 2 LATERAL & VERTICAL; sch: notes) is ten wafer
sections, traced on the drawing (the README's "S301 MATRIXING"):
- S301A-E on the inputs. T101 and T201 each have two primaries (R101 / R102, R201 / R202 across
  them). At 1 each attenuator drives its own transformer's two in series; at 2 the left drives
  T101's first and T201's first in series, the right T101's second and T201's second reversed:
  T101 hears L + R (lateral), T201 L - R (vertical), and each source still sees 600 ohm.
- S301F-K on the outputs. T102 and T202 each have two secondaries (each with its own sidechain
  pad into one of T103's / T203's two primaries). At 1 each channel's two in series are its
  output; at 2 the left output is T102's first and T202's first in series, the right T102's
  second and T202's second reversed: the lateral and vertical recombined into left and right.

So the one-channel file's single primaries (T101, T103) and secondary (T102) are split here, as
drawn: half the turns, resistance and leakage share each (varimu/circuit/fairchild_670.py's
derived values), and R101 / R102 and the pads R145-R150 are the drawing's separate parts
(the one-channel file lumps the two pads' legs into two of 150 ohm, where the drawing has four;
`--set r145_r148_ohm=75` gives this file that file's pick-off, which tests/test_fairchild_670_
stereo.py uses to check that the split and the second channel change nothing else).

The generated file says it is generated; edit the one-channel file (or this script) and rerun
(`--check` exits 1 when the file on disk differs).
"""

from __future__ import annotations

import argparse
import copy
import re
import sys

import yaml

from varimu.config import CONFIG_DIR

STOCK = CONFIG_DIR / "circuits" / "fairchild_670.yaml"
OUT = CONFIG_DIR / "circuits" / "fairchild_670_stereo.yaml"
# The factory threshold adjustment (scripts/fairchild_670_stereo_trim.py --write).
TRIMS = CONFIG_DIR / "fairchild_670_stereo_trims.yaml"

HEADER = """\
# GENERATED by scripts/make_fairchild_670_stereo.py from config/circuits/fairchild_670.yaml:
# never edit this file; edit that one (or the script) and rerun. The Fairchild 670 as drawn on
# A-96039: both channels on one supply, and S301 MATRIXING (`mode`: 1 LEFT & RIGHT, 2 LATERAL &
# VERTICAL), the script's docstring and data/schematics/fairchild_670/README.md ("S301
# MATRIXING") say how. Channel 1's comments and sources are in the one-channel file.
"""

# The supply's nodes: shared by both channels (the README's "Supply rails").
SHARED_NODES = {"0", "bp", "ur", "sg", "nb2", "nb3", "nb4"}
# The sections of the one-channel file that are channel 1 (the rest: the supplies; channel 2's
# lump is dropped).
SUPPLY_SECTIONS = ("power supply", "bias supply")
LUMP_SECTION = "channel 2 (idle, lumped)"
# Channel 1's front panel and trims, each with a channel 2 twin `<key>_2`.
CHANNEL_CONTROLS = (
    "input_atten_db",
    "ac_threshold",
    "time_constant",
    "dc_threshold",
    "balance",
    "zero",
)
CH2_SOURCE = "sch: channel 2's twin of channel 1's {key} (the drawing's {parts}, printed alike)"
CH2_PARTS = {
    "input_atten_db": "AT102",
    "ac_threshold": "R215A / R215B",
    "time_constant": "S202",
    "dc_threshold": "R217",
    "balance": "R205A / R205B",
    "zero": "R242",
}
# The macros whose first key lists nodes (varimu/circuit/builder.py).
NODE_FIELDS = ("R", "C", "L", "pot", "tapped_pot", "t_pad", "device", "bridge", "mains")
CONTACT = "s301_contact_ohm"
# Device entries without instances (one model, shared): channel 2's parts name channel 1's.
SHARED_MODELS = {"CR101-104"}
# Channel 2's 6386 banks (the drawing's, as channel 1's BANK_TRIODES renamed).
BANKS_2 = {"a": "V201A, V202A, V203B, V204B", "b": "V201B, V202B, V203A, V204A"}


def ch2_designator(name: str) -> str:
    """Channel 1's designator as channel 2's: the drawing's 1xx -> 2xx (AT101 -> AT102)."""
    if name == "AT101":
        return "AT102"
    m = re.match(r"^([A-Za-z]*)1(\d\d)(.*)$", name)
    if m:
        return f"{m.group(1)}2{m.group(2)}{m.group(3)}"
    return f"{name}_2"


def ch2_node(n: str) -> str:
    n = str(n)
    if n in SHARED_NODES:
        return n
    return {"in": "in_r", "out": "out_r"}.get(n, f"{n}_2")


def ch2_device(name: str) -> str:
    """A device instance's name for channel 2 (V101A -> V201A); the bridge's diodes share one
    model (`instance: false`: CR101-104's is the SI_RECTIFIER model, CR201-204 the same)."""
    if name in SHARED_MODELS:
        return name
    return ch2_designator(name)


def rename_part(body: dict, devices: set[str]) -> dict:
    """A channel 1 part's body as channel 2's: its nodes, models, panel controls."""
    body = copy.deepcopy(body)
    for f in NODE_FIELDS:
        if f in body:
            body[f] = [ch2_node(x) for x in body[f]]
    if body.get("model") in devices:
        body["model"] = ch2_device(body["model"])
    if body.get("at") in CHANNEL_CONTROLS:
        body["at"] = f"{body['at']}_2"
    if "atten_db" in body and body["atten_db"] in CHANNEL_CONTROLS:
        body["atten_db"] = f"{body['atten_db']}_2"
    if "switch" in body:
        if body["switch"] in CHANNEL_CONTROLS:
            body["switch"] = f"{body['switch']}_2"
        body["parts"] = {
            ch2_designator(n): rename_part(b, devices) for n, b in body["parts"].items()
        }
    if "transformer" in body:
        for w in body["transformer"].values():
            w["nodes"] = [ch2_node(x) for x in w["nodes"]]
        if body.get("interwinding"):
            iw = body["interwinding"]
            iw["ends"] = [ch2_node(x) for x in iw["ends"]]
            iw["to"] = ch2_node(iw["to"])
    return body


# Each channel's transformer pins (the drawing's numbers): T101's primaries are pins 1-2 and
# 3-4, T201's 1-3 and 2-4 (as printed); T102 / T202's secondaries 5-7 and 8-10; T103 / T203's
# primaries 1-3 and 2-4. The first pin of each pair is the winding's dotted end (the end drawn
# at its top: the drawing draws each pair alike).
def pins(k: int) -> dict[str, str]:
    if k == 1:
        return {
            "in_a": ("pri", "t101_2"),  # AT101's output is pin 1
            "in_b": ("t101_3", "t101_4"),
            "out_a": ("out", "t102_7"),  # pin 5 is terminal 12
            "out_b": ("t102_8", "t102_10"),
            "sc_a": ("t103_1", "t103_3"),
            "sc_b": ("t103_2", "t103_4"),
        }
    return {
        "in_a": ("t201_1", "t201_3"),
        "in_b": ("t201_2", "t201_4"),
        "out_a": ("t202_5", "t202_7"),
        "out_b": ("t202_8", "t202_10"),
        "sc_a": ("t203_1", "t203_3"),
        "sc_b": ("t203_2", "t203_4"),
    }


def channel_parts(k: int, stock_parts: dict[str, dict], devices: set[str]) -> dict[str, dict]:
    """Channel k's input, 6386 and sidechain-input sections' changed parts, by designator, from
    channel 1's: the split windings and their resistors, the pads."""
    d = (lambda n: n) if k == 1 else ch2_designator
    nd = (lambda n: n) if k == 1 else ch2_node
    p = pins(k)
    t101 = copy.deepcopy(stock_parts["T101"])
    tr = t101["transformer"]
    half = {"ratio": 0.5, "r": "t101_r_pri_half_ohm", "leak": "t101_pri_half_leak_h"}
    t101["transformer"] = {
        "pa": {"nodes": list(p["in_a"]), **half},
        "pb": {"nodes": list(p["in_b"]), **half},
        "sa": {**tr["sa"], "nodes": [nd(x) for x in tr["sa"]["nodes"]]},
        "sb": {**tr["sb"], "nodes": [nd(x) for x in tr["sb"]["nodes"]]},
    }
    t101["interwinding"] = {
        "ends": [nd(x) for x in t101["interwinding"]["ends"]],
        "to": p["in_a"][0],
        "c": t101["interwinding"]["c"],
    }
    t102 = copy.deepcopy(stock_parts["T102"])
    tr = t102["transformer"]
    shalf = {"ratio": 0.5, "r": "t102_r_sec_half_ohm", "leak": "t102_sec_half_leak_h"}
    t102["transformer"] = {
        "pa": {**tr["pa"], "nodes": [nd(x) for x in tr["pa"]["nodes"]]},
        "pb": {**tr["pb"], "nodes": [nd(x) for x in tr["pb"]["nodes"]]},
        "sa": {"nodes": list(p["out_a"]), **shalf},
        "sb": {"nodes": list(p["out_b"]), **shalf},
    }
    t102["interwinding"] = {
        "ends": [nd(x) for x in t102["interwinding"]["ends"]],
        "to": p["out_a"][0],
        "c": t102["interwinding"]["c"],
    }
    t103 = copy.deepcopy(stock_parts["T103"])
    tr = t103["transformer"]
    phalf = {"ratio": 0.5, "leak": "t103_pri_half_leak_h"}
    t103["transformer"] = {
        "pa": {"nodes": list(p["sc_a"]), **phalf},
        "pb": {"nodes": list(p["sc_b"]), **phalf},
        "sa": {**tr["sa"], "nodes": [nd(x) for x in tr["sa"]["nodes"]]},
        "sb": {**tr["sb"], "nodes": [nd(x) for x in tr["sb"]["nodes"]]},
    }
    out_r = "out" if k == 1 else "out_r"
    return {
        "input": {
            d("T101"): t101,
            d("R101"): {"R": list(p["in_a"]), "r": "r101_r102_ohm"},
            d("R102"): {"R": list(p["in_b"]), "r": "r101_r102_ohm"},
        },
        "6386 push-pull": {
            d("T102"): t102,
            "Rload" if k == 1 else "Rload_2": {
                "R": [out_r, "0"],
                "r": "load_ohm",
                "tolerance": "none",
            },
        },
        "sidechain input": {
            # A pad across each T102 secondary into one of T103's primaries (as drawn).
            d("R145"): {"R": [p["out_a"][0], p["sc_a"][0]], "r": "r145_r148_ohm"},
            d("R146"): {"R": [p["out_a"][1], p["sc_a"][1]], "r": "r145_r148_ohm"},
            d("R149"): {"R": list(p["sc_a"]), "r": "r149_r150_ohm"},
            d("R147"): {"R": [p["out_b"][0], p["sc_b"][0]], "r": "r145_r148_ohm"},
            d("R148"): {"R": [p["out_b"][1], p["sc_b"][1]], "r": "r145_r148_ohm"},
            d("R150"): {"R": list(p["sc_b"]), "r": "r149_r150_ohm"},
            d("T103"): t103,
        },
    }


# Parts of channel 1's sections that the split replaces (the rest carry over).
REPLACED = {
    "input": {"R101", "T101"},
    "6386 push-pull": {"T102", "Rload"},
    "sidechain input": {"R145", "R147", "R149", "T103"},
}


def contacts(name: str, pairs: dict[int, tuple[str, str]]) -> dict:
    """A wafer section: per position, a contact between two nodes (built at that position)."""
    return {
        f"R{name}_{pos}": {"R": [a, b], "r": CONTACT, "in": [pos]} for pos, (a, b) in pairs.items()
    }


def matrix_sections() -> list[dict]:
    """S301 as traced (the README's "S301 MATRIXING"): poles to their position-1 and position-2
    contacts. The attenuators' and outputs' low sides are chassis ground (terminals 3 and 7
    strapped to 4, [MAN] p.6's note; 13 and 16 the loads' grounded ends)."""
    i1, i2 = pins(1), pins(2)
    o1, o2 = i1, i2
    inputs = {
        # pole: (position 1, position 2)
        "S301A": {1: ("t101_2", "t101_3"), 2: ("t101_2", i2["in_a"][0])},
        "S301B": {1: ("0", "t101_4"), 2: ("0", i2["in_a"][1])},
        "S301C": {1: ("pri_2", i2["in_a"][0]), 2: ("pri_2", "t101_3")},
        "S301D": {1: (i2["in_b"][0], i2["in_a"][1]), 2: (i2["in_b"][0], "0")},
        "S301E": {1: (i2["in_b"][1], "0"), 2: (i2["in_b"][1], "t101_4")},
    }
    outputs = {
        "S301F": {1: (o1["out_a"][1], o1["out_b"][0]), 2: (o1["out_a"][1], o2["out_a"][0])},
        "S301G": {1: ("0", o1["out_b"][1]), 2: ("0", o2["out_a"][1])},
        "S301H": {1: ("out_r", o2["out_a"][0]), 2: ("out_r", o1["out_b"][0])},
        "S301J": {1: (o2["out_b"][0], o2["out_a"][1]), 2: (o2["out_b"][0], "0")},
        "S301K": {1: (o2["out_b"][1], "0"), 2: (o2["out_b"][1], o1["out_b"][1])},
    }

    def section(title: str, name: str, wafers: dict) -> dict:
        parts = {}
        for wafer, pairs in wafers.items():
            parts.update(contacts(wafer, pairs))
        return {
            "title": title,
            "tolerance": "none",
            "parts": {name: {"switch": "mode", "parts": parts}},
        }

    return [
        section("S301 matrixing, inputs", "S301_IN", inputs),
        section("S301 matrixing, outputs", "S301_OUT", outputs),
    ]


def build() -> str:
    stock = yaml.safe_load(STOCK.read_text(encoding="utf-8"))
    devices = set(stock["devices"])
    out: dict = {}
    out["title"] = "Fairchild 670, both channels and S301 MATRIXING (left-right, lateral-vertical)"
    out["input"] = "in"
    out["audio_inputs"] = {"in_r": "in_r"}
    probes = list(stock["probes"])
    ch2_probes = [ch2_node(n) for n in probes if ch2_node(n) not in probes]
    out["probes"] = ["out", "out_r", *[n for n in probes if n != "out"], *ch2_probes[1:]]

    trims = yaml.safe_load(TRIMS.read_text(encoding="utf-8")) if TRIMS.exists() else {}
    controls = {}
    for key, c in stock["controls"].items():
        c = dict(c)
        if key in trims:
            c["value"] = trims[key]
            c["source"] = (
                f"{c['source']}. This file's default: its own factory adjustment "
                f"(config/fairchild_670_stereo_trims.yaml: {trims['source']})"
            )
        controls[key] = c
        if key in CHANNEL_CONTROLS:
            c2 = dict(c)
            c2["source"] = CH2_SOURCE.format(key=key, parts=CH2_PARTS[key]) + (
                "; its default channel 1's factory adjustment" if key in trims else ""
            )
            controls[f"{key}_2"] = c2
    controls["mode"] = {
        "value": 1,
        "choices": [1, 2],
        "unit": "position",
        "source": "sch: S301 MATRIXING (notes: 'POS. 1 LEFT & RIGHT, 2 LATERAL & VERTICAL'); "
        "[MAN] p.5 e) Mode Switch: 'Left-Right position: 2 independent limiters. "
        "Vertical-Lateral position: matrixing input and output, left and right in and out, "
        "limiting action vertical-lateral'",
        "notes": "1 = two independent limiters; 2 = channel 1 limits L + R (lateral), channel 2 "
        "L - R (vertical), recombined into L and R",
    }
    out["controls"] = controls

    values = dict(stock["values"])
    values["r101_r102_ohm"] = {
        "value": 180,
        "source": "sch: R101, R102 180 1%, one across each of T101's primaries (pins 1-2, 3-4); "
        "R201, R202 across T201's (1-3, 2-4)",
    }
    values["r149_r150_ohm"] = {
        "value": 680,
        "source": "sch: R149, R150 680 5%, the shunts of the two pads (one across each T102 "
        "secondary into one of T103's primaries; R249, R250 the same)",
    }
    values["r145_r148_ohm"] = {
        "value": 150,
        "source": "sch: R145-R148 150 5%, the pads' four series legs (two per pad; R245-R248 "
        "the same). 75 gives the one-channel file's lumped pick-off (its two 150 ohm legs for "
        "both pads in series)",
    }
    values[CONTACT] = {
        "value": 0.01,
        "source": "provisional: model knowledge (a wafer switch's closed contact, 5-20 mOhm)",
    }
    values["c105_c106_f"] = {
        **values["c105_c106_f"],
        "source": values["c105_c106_f"]["source"]
        + "; channel 2's C206 '20MMF' and C205 printed '10 MMF', read as 20 pF: the pair "
        "neutralizes a push-pull stage, both its sides alike (channel 1's are), and the "
        "drawing has other slips in channel 2 (R230 '150M', V206B '12BM7A')",
    }
    values["r115b_ohm"] = {
        **values["r115b_ohm"],
        "source": values["r115b_ohm"]["source"]
        + ". Channel 2's R215A / R215B both print 180K on this scan; channel 2 takes channel "
        "1's values (the same dual pot)",
    }
    out["values"] = values

    dp = dict(stock["device_params"])
    for bank in ("a", "b"):
        for f in ("emission_scale", "mu_spread", "grid_contact_v"):
            src = stock["device_params"][f"v6386_{bank}.{f}"]
            tubes = BANKS_2[bank]
            dp[f"v6386_2{bank}.{f}"] = {
                "value": src["value"],
                "source": f"as v6386_{bank}.{f} (the device file's, config/components/6386/1.yaml);"
                f" channel 2's bank {bank.upper()} ({tubes}); not in the genome (its 6386 banks"
                " are channel 1's)",
            }
    out["device_params"] = dp
    out["derived"] = {
        "module": "varimu.circuit.fairchild_670",
        "values": {
            "t101_pri_half_leak_h": {
                "source": "derived: half T101's series primary's leakage "
                "share (0.25 t101_leakage_h), each of its two primaries"
            },
            "t101_r_pri_half_ohm": {"source": "derived: half t101_r_pri_ohm, each primary"},
            "t102_sec_half_leak_h": {
                "source": "derived: half T102's series secondary's leakage "
                "share (0.25 t102_leakage_h), each of its two secondaries"
            },
            "t102_r_sec_half_ohm": {"source": "derived: half t102_r_sec_ohm, each secondary"},
            "t103_pri_half_leak_h": {
                "source": "derived: half T103's series primary's leakage "
                "share (0.25 t103_leakage_h), each of its two primaries"
            },
        },
    }
    out["mains"] = stock["mains"]

    # Every part of the channels by designator, for the tolerance classes.
    tol = copy.deepcopy(stock["tolerance"])
    tol["source"] = (
        tol["source"] + "; channel 2's parts in the same classes as their channel 1 twins (2xx)"
    )
    tol.pop("combined", None)
    classes = tol["classes"]
    classes["r1"] = list(classes["r1"])
    classes["r5"] = [*classes["r5"], "R146", "R148"]

    # Channel 1's sections, split as drawn; channel 2 the same renamed.
    sections = [s for s in stock["sections"] if s["title"] in SUPPLY_SECTIONS]
    ch1 = [s for s in stock["sections"] if s["title"] not in SUPPLY_SECTIONS + (LUMP_SECTION,)]
    ch_sections = {1: [], 2: []}
    for k in (1, 2):
        changed = channel_parts(k, {n: b for s in ch1 for n, b in s["parts"].items()}, devices)
        for s in ch1:
            parts = {}
            for name, body in s["parts"].items():
                if name in REPLACED.get(s["title"], ()):
                    if s["title"] in changed:
                        for n2, b2 in changed.pop(s["title"]).items():
                            parts[n2] = b2
                    continue
                if k == 1:
                    parts[name] = copy.deepcopy(body)
                else:
                    parts[ch2_designator(name)] = rename_part(body, devices)
            ch_sections[k].append({"title": f"{s['title']} (channel {k})", "parts": parts})
    # Channel 1's AT101 drives T101's pin 1 (node pri); channel 2's AT102 drives S301C's pole.
    sections += ch_sections[1] + ch_sections[2] + matrix_sections()
    out["sections"] = sections

    # Tolerance classes: every class's channel 1 designator also as channel 2's.
    ch1_names = {n for s in ch1 for n in s["parts"]} | {
        n for s in ch1 for b in s["parts"].values() if "switch" in b for n in b["parts"]
    }
    ch1_names |= {"R146", "R148", "R102", "R150"}
    for cls, names in classes.items():
        classes[cls] = [*names, *(ch2_designator(n) for n in names if n in ch1_names)]
    out["tolerance"] = tol

    # Devices: channel 1's, then channel 2's (renamed; its 6386 banks on their own params).
    devs = {}
    lumped = {"CH2_6386", "CH2_12BH7", "CH2_6973"}
    ch1_devices = [
        n for n in stock["devices"] if n not in lumped and not n.startswith(("V30", "GR30"))
    ]
    for n, dv in stock["devices"].items():
        if n not in lumped:
            devs[n] = dv
    for n in ch1_devices:
        if n in SHARED_MODELS:
            continue
        dv = dict(stock["devices"][n])
        for f in ("emission", "mu", "grid_contact_v"):
            if isinstance(dv.get(f), str) and dv[f].startswith("v6386_"):
                dv[f] = dv[f].replace("v6386_", "v6386_2", 1)
        devs[ch2_device(n)] = dv
    out["devices"] = devs
    # The supply's sections first, as the one-channel file; then the channels, then S301.
    order = [
        "title",
        "input",
        "audio_inputs",
        "probes",
        "controls",
        "values",
        "device_params",
        "derived",
        "mains",
        "tolerance",
        "devices",
        "sections",
    ]
    out = {k: out[k] for k in order}
    return HEADER + yaml.safe_dump(out, sort_keys=False, default_flow_style=None, width=100)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        print("up to date" if ok else "STALE: rerun scripts/make_fairchild_670_stereo.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
