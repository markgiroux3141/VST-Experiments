def derive() -> str:
    text = STOCK.read_text(encoding="utf-8")
    for anchor, new in PATCHES:
        n = text.count(anchor)
        if n != 1:
            raise SystemExit(f"{STOCK.name}: anchor found {n} times, not once: {anchor!r}")
        text = text.replace(anchor, new)
    return HEADER + text


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--check", action="store_true", help="exit 1 if the file on disk differs")
    args = ap.parse_args()
    text = derive()
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print(f"{OUT.name}: {'up to date' if same else 'stale (rerun the script)'}")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
