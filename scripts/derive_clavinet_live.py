"""The Hohner Clavinet D6 played live (docs/CLAVINET_PLAN.md, CL3): its electronics with the
strings as a medium in the netlist.

    uv run python scripts/derive_clavinet_live.py [--check]

Writes config/circuits/clavinet_d6_live.yaml from config/circuits/clavinet_d6.yaml by
patching its text (its comments and sources carry over): the three control inputs the
offline render drives (`centre`, `bridge`, `bridge_neg`: the strings' EMFs, rendered by
varimu.clavinet ahead of the circuit) give way to a `clav_strings` part (the component
D6_STRINGS, circuitsim's clavinet medium, its keys played by note events) driving the same
nodes. The pickups' coils and everything after them are the stock file's. The strings
sense nothing in the circuit (the coils' current doesn't act on them), so this is one
coupled simulation: the medium is stepped with the netlist. clavinet_d6.yaml itself stays
as it is (scripts/clavinet_render.py renders through it).

The generated file says it is generated; edit the stock file (or the patches here) and
rerun (`--check` exits 1 when the file on disk differs: tests/test_clavinet_live_circuit.py).
"""

from __future__ import annotations

import argparse
import sys

from varimu.config import CONFIG_DIR

STOCK = CONFIG_DIR / "circuits" / "clavinet_d6.yaml"
OUT = CONFIG_DIR / "circuits" / "clavinet_d6_live.yaml"

HEADER = """\
# GENERATED by scripts/derive_clavinet_live.py from config/circuits/clavinet_d6.yaml: don't
# edit; edit that file (or the script's patches) and rerun. The D6 played live
# (docs/CLAVINET_PLAN.md, CL3): the strings (the component D6_STRINGS, circuitsim's
# clavinet medium, played by note events) drive the pickups' EMF nodes where the offline
# render's control inputs do.
#
"""

# The stock file's volume control (the wear's controls follow it).
VOLUME = (
    '  volume: {value: 0.8, min: 0.0, max: 1.0, unit: rotation, source: "provisional: model'
    " knowledge (the D6's volume knob; default a design choice)\"}\n"
)

# (anchor in the stock file, its replacement): each anchor must occur exactly once.
PATCHES = [
    (
        'title: "Hohner Clavinet D6 electronics (pickups, rockers, two-stage BJT amp)"\n',
        'title: "Hohner Clavinet D6 (strings, pickups, rockers, two-stage BJT amp)"\n',
    ),
    ("cv_inputs:\n  centre: ec\n  bridge: eb\n  bridge_neg: ebn\n", ""),
    (
        "values:\n",
        "values:\n"
        "  # --- the strings (docs/CLAVINET_PLAN.md, CL3)\n"
        '  strings_model: {value: D6_STRINGS@3, source: "config/components/d6_strings/3.yaml'
        " (the D6's 60 strings from physics, compiled by varimu/clavinet/compile.py: the live"
        " band, the contacts, the pickups' maps)\"}\n"
        '  strings_rate_hz: {value: 96000.0, source: "numerical: the voices at the step rate'
        " (96 kHz at draft-1x / draft-2x; the live band's modes reach 12 kHz, the pickups'"
        " map's products ~24 kHz)\"}\n"
        "  strings_contact_rate_hz: {value: 1536000.0, source: \"numerical: the tangent's"
        " rubber and the anvil stepped at 16 x 96 kHz, as note.py's reference"
        ' (varimu/clavinet/live.py)"}\n',
    ),
    (
        '      RIN: {R: [in, "0"], r: r_in_ohm, tolerance: none}\n',
        '      RIN: {R: [in, "0"], r: r_in_ohm, tolerance: none}\n'
        "      # the strings: the centre pickup's EMF on ec, the bridge's on eb and negated on\n"
        "      # ebn (each to ground), the keys played by note events\n"
        "      STRINGS: {clav_strings: [ec, eb, ebn], component: strings_model,"
        " rate_hz: strings_rate_hz, contact_rate_hz: strings_contact_rate_hz,"
        " wear_seed: wear_unit, wear_age: wear_age, wear_tuning: wear_tuning,"
        " wear_strings: wear_strings, wear_tangents: wear_tangents, wear_yarn: wear_yarn,"
        " wear_pickups: wear_pickups}\n",
    ),
    (
        VOLUME,
        VOLUME + '  # The instrument\'s wear (docs/CLAVINET_PLAN.md, "Variation and wear";'
        " varimu/clavinet/wear.py):\n"
        "  # which unit, its age (0 freshly serviced, 1 a well-worn old one, 2 neglected) and"
        " each\n"
        "  # part's share of the age (1: as old as the instrument; 0 new, 2 twice as worn).\n"
        '  wear_unit: {value: 1, min: 1, max: 64, unit: position, source: "design choice:'
        ' the instrument (the seed of its per-key draws)"}\n'
        '  wear_age: {value: 0.5, min: 0.0, max: 2.0, unit: ratio, source: "design choice'
        " (2026-11-06: a played, maintained vintage D6 by default; the user's sliders for how"
        ' worn the instrument is)"}\n'
        '  wear_tuning: {value: 1.0, min: 0.0, max: 2.0, unit: ratio, source: "design'
        " choice: the strings' tuning drift's share of the age\"}\n"
        '  wear_strings: {value: 1.0, min: 0.0, max: 2.0, unit: ratio, source: "design'
        " choice: the strings' age's share (dull upper partials, false beats)\"}\n"
        '  wear_tangents: {value: 1.0, min: 0.0, max: 2.0, unit: ratio, source: "design'
        " choice: the tangents' rubber hardening's share\"}\n"
        '  wear_yarn: {value: 1.0, min: 0.0, max: 2.0, unit: ratio, source: "design choice:'
        " the yarn's wear's share (notes ring on after release)\"}\n"
        '  wear_pickups: {value: 1.0, min: 0.0, max: 2.0, unit: ratio, source: "design'
        " choice: the pickup heights' scatter's share\"}\n",
    ),
]


def derive() -> str:
    text = STOCK.read_text(encoding="utf-8").replace("\r\n", "\n")
    for anchor, new in PATCHES:
        if text.count(anchor) != 1:
            raise SystemExit(f"anchor not found exactly once: {anchor[:70]!r}")
        text = text.replace(anchor, new)
    return HEADER + text


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the file on disk differs")
    args = ap.parse_args()
    text = derive()
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        print(f"{OUT.name}: {'current' if same else 'STALE'}")
        sys.exit(0 if same else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
