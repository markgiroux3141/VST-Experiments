def _band(prefix: str, control: str, wiper: str, rotor: str, back: str, taps, table) -> dict:
    """A switched series LC from `wiper` to `back` through the coil's selected tap."""
    parts: dict[str, dict] = {}
    for mh in taps:
        pos = [f for f, (t, _) in table.items() if t == mh]
        if not pos:
            continue
        parts[f"L{prefix}{mh}"] = {
            "L": [wiper, f"{prefix.lower()}t{mh}"],
            "l": f"l_{prefix.lower()}_{mh}m_h",
            "in": pos,
            "source": GY_PAIR,
        }
        parts[f"RL{prefix}{mh}"] = {
            "R": [f"{prefix.lower()}t{mh}", rotor],
            "r": f"r_{prefix.lower()}_{mh}m_ohm",
            "tolerance": "none",
            "in": pos,
        }
    for nf in sorted({c for _, cs in table.values() for c in cs}):
        pos = [f for f, (_, cs) in table.items() if nf in cs]
        name = f"C{prefix}{f'{nf:g}'.replace('.', 'n')}"
        parts[name] = {
            "C": [rotor, back],
            "c": _cap_key(prefix.lower(), nf),
            "in": pos,
            "source": GY_PAIR,
        }
    return {f"S{prefix}": {"switch": control, "parts": parts}}


def network_section() -> dict:
    parts = {
        # LOW BOOST: the pot from lb_far (rotation 0: no boost) to eq_in; its wiper into the
        # coil, the selected tap and capacitor back to lb_far.
        "RLB": {"pot": ["eq_m1", "lb_w", "eq_in"], "r": "low_boost_pot_ohm", "at": "low_boost"},
        **_band("LB", "low_peak_hz", "lb_w", "lb_r", "eq_m1", LOW_TAPS, LOW),
        "RLSH": {"R": ["eq_m1", "0"], "r": "low_shunt_ohm"},
        "RMSER": {"R": ["eq_m1", "eq_m2"], "r": "mid_series_ohm"},
        # MID CUT: the pot from ground (rotation 0: no cut) to eq_m2, reverse-log; its wiper
        # through 270 ohm into the coil, the selected tap and capacitor to ground.
        "RMC": {
            "pot": ["0", "mc_w", "eq_m2"],
            "r": "mid_cut_pot_ohm",
            "at": "dip",
            "taper_mid": "audio_taper_mid",
            "reverse": 1,
        },
        "RMQ": {"R": ["mc_w", "mc_q"], "r": "mid_q_ohm"},
        **_band("MC", "dip_hz", "mc_q", "mc_r", "0", MID_TAPS, MID),
        # HIGH BOOST: as LOW BOOST, from eq_out (rotation 0) to eq_m2.
        "RHB": {"pot": ["eq_out", "hb_w", "eq_m2"], "r": "high_boost_pot_ohm", "at": "high_boost"},
        **_band("HB", "high_peak_hz", "hb_w", "hb_r", "eq_out", HIGH_TAPS, HIGH),
        "RHSH": {"R": ["eq_out", "0"], "r": "high_shunt_ohm"},
    }
    return {"title": "passive network", "parts": parts}


def make() -> str:
    src = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    controls = {k: v for k, v in src["controls"].items() if k not in DROP_CONTROLS}
    controls = {**CONTROLS, **controls}
    keys = list(src["values"])
    a, b = keys.index(NETWORK_FIRST), keys.index(NETWORK_LAST)
    dropped = set(keys[a : b + 1]) - {"audio_taper_mid"}
    values = {k: v for k, v in src["values"].items() if k not in dropped}
    values["audio_taper_mid"]["source"] = (
        "provisional: model knowledge (an audio taper: ~10% of the track at half rotation, the "
        "EQP-1A's); here MID CUT's 2K5C read from its far end (a reverse-log 'C' taper)"
    )
    values.update(network_values())
    net = network_section()
    caps = [
        n
        for sw in net["parts"].values()
        if "switch" in sw
        for n in sw["parts"]
        if n.startswith("C")
    ]
    tol = src["tolerance"]
    tol["classes"]["r10"] = [r for r in tol["classes"]["r10"] if r not in DROP_R10] + [
        "RLSH",
        "RMSER",
        "RMQ",
        "RHSH",
    ]
    tol["classes"]["pot"] = ["RLB", "RMC", "RHB"]
    tol["classes"]["network"] = caps
    sections = [net if s["title"] == "passive network" else s for s in src["sections"]]
    probes = [p for p in src["probes"] if p != "eq_m"]
    probes[probes.index("eq_out") + 1 : probes.index("eq_out") + 1] = ["eq_m1", "eq_m2"]
    doc = {
        "title": "Pultec MEQ-5 midrange equalizer",
        **{
            k: v
            for k, v in src.items()
            if k not in ("title", "probes", "controls", "values", "tolerance", "sections")
        },
        "probes": probes,
        "controls": controls,
        "values": values,
        "tolerance": tol,
        "sections": sections,
    }
    order = [
        "title",
        "input",
        "probes",
        "controls",
        "values",
        "mains",
        "tolerance",
        "devices",
        "sections",
    ]
    doc = {k: doc[k] for k in order if k in doc} | {k: v for k, v in doc.items() if k not in order}
    return HEADER + yaml.safe_dump(doc, sort_keys=False, width=100, allow_unicode=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = make()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale: rerun scripts/make_pultec_meq5.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
