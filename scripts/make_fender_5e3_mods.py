def derive() -> str:
    text = STOCK.read_text(encoding="utf-8")
    for anchor, new in PATCHES:
        if text.count(anchor) != 1:
            raise SystemExit(f"anchor not found exactly once: {anchor[:70]!r}")
        text = text.replace(anchor, new)
    return HEADER + text


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the file on disk differs")
    args = ap.parse_args()
    text = derive()
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print(f"{OUT.name}: {'current' if same else 'STALE'}")
        sys.exit(0 if same else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
