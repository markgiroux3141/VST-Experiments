"""The Nickel Organ compiled for the live tier, as a component version
(docs/NICKEL_ORGAN_DEVICE_PLAN.md; circuitsim's nickel.rs is the medium that plays it).

`scripts/compile_nickel_organ.py` writes the data: the circuit's values as plain floats, the
amplifier's idle point, the #327's table, and per key its bar's modes and voicing (from
config/nickel/organ.yaml through varimu/nickel/). It is saved as a component version of kind
`nickel_keys` (`save`): config/components/nickel_organ/<N>.yaml naming its data
<N>.organ.json by sha256, which the builders check (`ir_data`). A circuit's `nickel_keys`
part pins a version (`NICKEL_ORGAN@N`); moving it to a new one is an explicit edit.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
from pathlib import Path
from typing import Any

from varimu.config import REPO_ROOT
from varimu.devices import versions

COMPONENT = "NICKEL_ORGAN"
KIND = "nickel_keys"
DATA_SUFFIX = ".organ.json"


def dump(data: dict[str, Any]) -> str:
    """The data's text as saved (compact JSON, as circuitsim reads it)."""
    return json.dumps(data, separators=(",", ":"))


def _yaml(name: str, data_file: str, sha: str, source: str) -> str:
    return (
        f"# Generated by varimu/nickel/compile.py (scripts/compile_nickel_organ.py) on"
        f" {_dt.date.today().isoformat()}.\n"
        "# Don't edit by hand: change config/nickel/ or varimu/nickel/ and recompile.\n"
        f"name: {name}\n"
        f"kind: {KIND}\n"
        "source: \"the Nickel Organ's 61 keys for the live tier (docs/NICKEL_ORGAN_PLAN.md,\n"
        '  \\"The Rust voice\\"): the values in config/nickel/organ.yaml and their sources,\n'
        "  through varimu/nickel/ (each key's bar by finite elements, its voicing, the\n"
        "  amplifier's idle point, the #327's table), compiled for circuitsim's nickel.rs\"\n"
        "instrument:\n"
        f"  file: {source}\n"
        f"  sha256: {_file_sha(REPO_ROOT / source)}\n"
        "data:\n"
        f"  file: {data_file}\n"
        f"  sha256: {sha}\n"
    )


def _file_sha(p: Path) -> str:
    return versions.text_hash(p.read_text(encoding="utf-8"))


def latest() -> str | None:
    """The latest version (`NICKEL_ORGAN@N`), None without one."""
    have = versions.versions(COMPONENT)
    return f"{COMPONENT}@{have[-1]}" if have else None


def save(data: dict[str, Any], name: str = COMPONENT) -> versions.Ref | None:
    """Save as component `name`'s next version, unless the latest one's data is the same
    (None then)."""
    text = dump(data)
    sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
    have = versions.versions(name)
    if have:
        _, old, _ = files(f"{name}@{have[-1]}")
        if old == sha:
            return None
    n = (have or [0])[-1] + 1
    folder = versions.COMPONENT_DIR / name.lower()
    folder.mkdir(parents=True, exist_ok=True)
    df = f"{n}{DATA_SUFFIX}"
    (folder / df).write_text(text, encoding="utf-8", newline="\n")
    ref = versions.save(name, _yaml(name, df, sha, "config/nickel/organ.yaml"))
    if ref.version != n:
        raise RuntimeError(f"saved {ref}, expected version {n}")
    return ref


def files(ref: str) -> tuple[Path, str, dict[str, Any]]:
    """(the data's path, its sha256, the version's YAML) of organ version `ref`, the data
    checked against the sha256 the version names."""
    import yaml

    r, text = versions.read_text(ref)
    d = yaml.safe_load(text)
    if d.get("kind") != KIND:
        raise ValueError(f"{r} is not the Nickel Organ's keys (kind {d.get('kind')!r})")
    p = versions.COMPONENT_DIR / r.folder / d["data"]["file"]
    sha = versions.text_hash(p.read_text(encoding="utf-8"))
    if sha != d["data"]["sha256"]:
        raise versions.VersionError(f"{r}'s data {p.name} doesn't match its sha256")
    return p, sha, d


_CHECKED: dict[tuple[str, int, int], str] = {}


def ir_data(ref: str) -> tuple[str, str]:
    """(the data's path relative to the repository's root, forward slashes; its sha256) of
    organ version `ref`, as the IR's nickel_keys element names them (checked once per
    process while the file's size and time are unchanged)."""
    import yaml

    r, text = versions.read_text(ref)
    d = yaml.safe_load(text)
    if d.get("kind") != KIND:
        raise ValueError(f"{r} is not the Nickel Organ's keys (kind {d.get('kind')!r})")
    p = versions.COMPONENT_DIR / r.folder / d["data"]["file"]
    st = p.stat()
    key = (str(p), st.st_size, st.st_mtime_ns)
    sha = d["data"]["sha256"]
    if _CHECKED.get(key) != sha:
        files(ref)
        _CHECKED[key] = sha
    return p.resolve().relative_to(REPO_ROOT.resolve()).as_posix(), sha


def load(ref: str) -> dict[str, Any]:
    p, _, _ = files(ref)
    return json.loads(p.read_text(encoding="utf-8"))
