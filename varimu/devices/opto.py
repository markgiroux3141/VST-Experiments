"""LED / photoresistor optocouplers (a Vactrol): the Rhodes Suitcase vibrato's panner
(docs/RHODES_PLAN.md, "The Suitcase"; data/schematics/rhodes_suitcase/).

An optocoupler is a device with pins (la, lk, s, ra, rb) and four ports, all relative to rb:
V(la, rb), V(lk, rb), V(s, rb) and V(ra, rb).

- **The LED** (la to lk): a Shockley junction, I = Is (exp(v / (n Vt)) - 1), v = V(la, lk).
  Its series resistance (~4 ohm on the VTL5C1's sheet) is left out: it moves the knee by
  < 0.1 V at 20 mA, nothing behind the kilohms that drive a vibrato's LED. Past `V_LIN_V`
  the exponential continues as its tangent (numerics: no overflow on a wild Newton step).
- **Its light**: proportional to L = I+^2 / (I+ + I_eta), I+ = max(I, 0): an LED's quantum
  efficiency rises from zero at low current, where Shockley-Read-Hall recombination takes
  most carriers, toward a constant (the I_eta knee); that and the cell below give the
  photocell's slope that steepens toward low current (on the VTL5C1's sheet, -2 at ~1 mA,
  -0.8 at 40 mA in log R against log I).
- **The photocell** (ra to rb, CdS): its photoconductance g (siemens, the excess carriers'
  share) generated by the light and lost by recombination through single traps (lifetime
  tau0) and pairwise (bimolecular, kappa):

      dg/dt = a L - g / tau0 - g |g| / kappa,

  so a bright cell answers fast (the pairwise loss) and a dark one creeps back slowly (the
  1 / t tail of pairwise recombination, then tau0): the turn-on in milliseconds, the
  turn-off in tens. The cell conducts G = g_dark + max(g, 0).
- **The state node** s carries g as a voltage, `s_unit_s` siemens per volt: the circuit puts
  a 1 F capacitor from s to rb, and the device's current into pin s is -dg/dt / s_unit (as
  the lamp's thermal node, varimu.devices.lamp): the capacitor charges at dg/dt. The state
  current closes through s and rb only (the capacitor carries it back), so the LED and the
  cell stay isolated from each other: pin la's current returns at lk, ra's at rb.

The parameters are fitted per component version (`varimu fit-devices --only VTL5C1`:
library.build_vtl5c1) to the sheet's curves.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

VT_V = 0.025693  # kT/q at 25 C (the sheets' temperature)
V_LIN_V = 2.5  # the LED's exponential continues as its tangent above this


@dataclass(frozen=True)
class Optocoupler:
    name: str
    led_is_a: float
    led_n: float
    i_eta_a: float  # the LED's efficiency knee
    gen_s_per_s_a: float  # a: the photoconductance generated per second per amp of L
    tau0_s: float  # single-trap recombination
    kappa_s_s: float  # pairwise recombination: g^2 / kappa (siemens times seconds)
    g_dark_s: float
    s_unit_s: float = 1e-3  # the state node: siemens per volt

    # --- the parts ----------------------------------------------------------------------

    def led(self, v):
        """The LED's current and its derivative at junction voltage v (arrays)."""
        v = np.asarray(v, float)
        nvt = self.led_n * VT_V
        vc = np.minimum(v, V_LIN_V)
        e = np.exp(vc / nvt)
        i = self.led_is_a * (e - 1.0) + self.led_is_a * e / nvt * (v - vc)
        di = self.led_is_a * e / nvt
        return i, di

    def light(self, i):
        """L (amps) and dL/dI."""
        ip = np.maximum(np.asarray(i, float), 0.0)
        den = ip + self.i_eta_a
        return ip * ip / den, ip * (ip + 2.0 * self.i_eta_a) / (den * den)

    def steady_g(self, i):
        """The photoconductance a constant LED current holds."""
        lum = self.light(i)[0]
        k, t0 = self.kappa_s_s, self.tau0_s
        # a L = g / tau0 + g^2 / kappa
        return 0.5 * k / t0 * (np.sqrt(1.0 + 4.0 * self.gen_s_per_s_a * lum * t0 * t0 / k) - 1.0)

    def steady_r_ohm(self, i):
        return 1.0 / (self.g_dark_s + self.steady_g(i))

    def rate(self, g, lum):
        """dg/dt."""
        return self.gen_s_per_s_a * lum - g / self.tau0_s - g * np.abs(g) / self.kappa_s_s

    def response(self, i_a: float, g0: float, t_s: np.ndarray) -> np.ndarray:
        """The cell's resistance over t_s with the LED at a constant i_a from photoconductance
        g0 (the sheet's turn-on: g0 = 0, the dark cell; turn-off: i_a = 0 from steady_g):
        the Riccati equation's closed form."""
        lum = float(self.light(i_a)[0])
        a, t0, k = self.gen_s_per_s_a * lum, self.tau0_s, self.kappa_s_s
        # dg/dt = a - g / t0 - g^2 / k = -(g - g1)(g - g2) / k, g1 the steady root (>= 0)
        disc = math.sqrt(1.0 / (t0 * t0) + 4.0 * a / k)
        g1 = 0.5 * k * (-1.0 / t0 + disc)
        g2 = 0.5 * k * (-1.0 / t0 - disc)
        lam = disc  # (g1 - g2) / k
        c = (g0 - g1) / (g0 - g2)
        e = c * np.exp(-lam * np.asarray(t_s, float))
        g = (g1 - g2 * e) / (1.0 - e)
        return 1.0 / (self.g_dark_s + np.maximum(g, 0.0))

    # --- the device ---------------------------------------------------------------------

    def eval(self, v):
        """Port currents i (4,) and Jacobian (4, 4) at the port voltages v = (V(la, rb),
        V(lk, rb), V(s, rb), V(ra, rb))."""
        v0, v1, u, vr = (float(x) for x in v)
        il, dil = (float(x) for x in self.led(v0 - v1))
        lum, dlum = (float(x) for x in self.light(il))
        su = self.s_unit_s
        g = u * su
        dgdt = self.rate(g, lum)
        cond = self.g_dark_s + max(g, 0.0)
        i = np.array([il, -il, -dgdt / su, cond * vr])
        j = np.zeros((4, 4))
        j[0, 0], j[0, 1] = dil, -dil
        j[1, 0], j[1, 1] = -dil, dil
        dgen = self.gen_s_per_s_a * dlum * dil / su  # d(a L)/dv over s_unit
        j[2, 0], j[2, 1] = -dgen, dgen
        j[2, 2] = 1.0 / self.tau0_s + 2.0 * abs(g) / self.kappa_s_s
        j[3, 2] = su * vr if g > 0.0 else 0.0
        j[3, 3] = cond
        return i, j

    def currents(self, v):
        return self.eval(v)[0]

    @property
    def subckt_name(self) -> str:
        return "OPTO_" + "".join(c if c.isalnum() else "_" for c in self.name).upper()

    def subckt(self) -> str:
        """SPICE subcircuit with pins (la, lk, s, ra, rb): the LED as B-sources (the Shockley
        law with its tangent past V_LIN_V), the cell and the state current as B-sources."""
        from varimu.devices.triode import num

        nvt = self.led_n * VT_V
        vd = "V(la,lk)"
        vc = f"min({vd},{num(V_LIN_V)})"
        il = (
            f"({num(self.led_is_a)}*(exp({vc}/{num(nvt)})-1)"
            f"+{num(self.led_is_a / nvt)}*exp({vc}/{num(nvt)})*({vd}-{vc}))"
        )
        ip = "V(il)"
        lum = f"(max({ip},0)*max({ip},0)/(max({ip},0)+{num(self.i_eta_a)}))"
        su = num(self.s_unit_s)
        g = f"(V(s,rb)*{su})"
        rate = (
            f"({num(self.gen_s_per_s_a)}*{lum}-{g}/{num(self.tau0_s)}"
            f"-{g}*abs({g})/{num(self.kappa_s_s)})"
        )
        return (
            f"* {self.name}: generated by varimu.devices.opto\n"
            f".subckt {self.subckt_name} la lk s ra rb\n"
            f"Bil il 0 V={{{il}}}\n"
            f"Bled la lk I={{V(il)}}\n"
            f"Bs s rb I={{-{rate}/{su}}}\n"
            f"Bcell ra rb I={{({num(self.g_dark_s)}+max({g},0))*V(ra,rb)}}\n"
            f".ends {self.subckt_name}\n"
        )


def opto_from_data(d: dict, ref: str) -> Optocoupler:
    """An optocoupler component version's model."""
    led, cell = d["led"], d["cell"]
    return Optocoupler(
        d["name"],
        led["is_a"],
        led["n"],
        led["i_eta_a"],
        cell["gen_s_per_s_a"],
        cell["tau0_s"],
        cell["kappa_s_s"],
        cell["g_dark_s"],
    )


# --- the fits (varimu fit-devices --only VTL5C1 VTL5C2) -----------------------------------------

# The LED's forward curve read by eye at the VTL5C1 sheet's grid ("Input Characteristics",
# p.2): (volts, amps), the junction's range (the curve is ~4 ohm of series resistance above
# ~10 mA, left out: see the module's docstring).
VTL5C1_LED = ((1.376, 0.1e-3), (1.417, 0.36e-3), (1.457, 0.8e-3), (1.498, 2e-3), (1.55, 10e-3))
VTL5C1_DARK_OHM = 50e6  # the sheet's OFF resistance at 10 s (min.)


def fit_vtl5c1() -> dict:
    """The VTL5C1's LED and cell fitted to its sheet (`fit_vactrol`)."""
    return fit_vactrol("VTL5C1")


def fit_vtl5c2() -> dict:
    """The VTL5C2's (`fit_vactrol`): the sheet's slow type ("a very steep slope ... a small
    light history memory"; turn-off to 100 kOhm in 500 ms max., the VTL5C1's 35 ms)."""
    return fit_vactrol("VTL5C2")


# Per part: the sheet's OFF resistance at 10 s (min.), how the source names it, and the
# starting guesses' tau0 (the VTL5C2 darkens ~10x slower).
VACTROLS = {
    "VTL5C1": (VTL5C1_DARK_OHM, "50 MOhm", (1e-3, 1e-2, 1e-1)),
    "VTL5C2": (1e6, "1 MOhm", (1e-2, 1e-1, 1.0)),
}


def fit_vactrol(part: str) -> dict:
    """A VTL5C Vactrol's LED and cell fitted to its sheet: the LED's Shockley line through its
    forward curve's points (one "Input Characteristics" plot serves both parts); the cell's
    four values (a, tau0, kappa, I_eta) by least squares in log R over the light-adapted
    steady curve (condition 2) and the four response curves (the sheet's response times follow
    condition 2), started from a grid of guesses."""
    import csv

    from scipy import optimize

    from varimu.config import REPO_ROOT

    dark_ohm, dark_text, t0_grid = VACTROLS[part]
    low = part.lower()
    ds = REPO_ROOT / "data" / "datasheets"
    with (ds / f"{low}_resistance.csv").open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    steady = np.array([[float(r["i_a"]), float(r["r_ohm"])] for r in rows if r["curve"] == "2"])
    resp: dict[str, list[tuple[float, float]]] = {}
    with (ds / f"{low}_response.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            resp.setdefault(r["curve"], []).append((float(r["t_s"]), float(r["r_ohm"])))
    led = np.array(VTL5C1_LED)
    slope, icpt = np.polyfit(led[:, 0], np.log(led[:, 1]), 1)
    n, is_a = 1.0 / (slope * VT_V), float(np.exp(icpt))
    g_dark = 1.0 / dark_ohm

    def model(p):
        a, t0, k, ie = np.exp(p)
        return Optocoupler(part, is_a, n, ie, a, t0, k, g_dark)

    def curve(m, name, t):
        i = 40e-3 if "40" in name else 10e-3
        if name.startswith("on"):
            return m.response(i, 0.0, t)
        return m.response(0.0, float(m.steady_g(i)), t)

    def resid(p):
        m = model(p)
        out = [np.log(m.steady_r_ohm(steady[:, 0]) / steady[:, 1])]
        for name, pts in resp.items():
            pts = np.array(pts)
            use = pts[:, 0] > 0  # t = 0: the plot's edge, not a reading
            out.append(np.log(curve(m, name, pts[use, 0]) / pts[use, 1]))
        return np.concatenate(out)

    best = None
    with np.errstate(all="ignore"):
        for t0 in t0_grid:
            for ie in (1e-3, 5e-3, 2e-2):
                for k in (1e-4, 1e-3, 1e-2):
                    for a in (1e-2, 1.0, 1e2):
                        try:
                            s = optimize.least_squares(
                                resid, np.log([a, t0, k, ie]), method="lm", max_nfev=4000
                            )
                        except (ValueError, FloatingPointError):
                            continue
                        if np.all(np.isfinite(s.fun)) and (best is None or s.cost < best.cost):
                            best = s
    m = model(best.x)

    def rms(x):
        return float(np.sqrt(np.mean(np.log(x) ** 2)))

    st_err = rms(m.steady_r_ohm(steady[:, 0]) / steady[:, 1])
    errs = {}
    for name, pts in resp.items():
        pts = np.array(pts)
        use = pts[:, 0] > 0
        errs[name] = round(rms(curve(m, name, pts[use, 0]) / pts[use, 1]), 3)
    src = f"data/datasheets/{low}.provenance.yaml (PerkinElmer's {part} sheet, p.2)"
    return {
        "name": part,
        "kind": "optocoupler",
        "source": f"fitted (varimu.devices.opto.fit_{low}) to the {part} Vactrol's sheet: "
        f"{src}. Standing in for the Rhodes Suitcase preamp's unidentified LED / photocell "
        "(Rhodes P/N 013556; data/schematics/rhodes_suitcase/README.md): provisional",
        "led": {
            "is_a": is_a,
            "n": float(n),
            "i_eta_a": float(np.exp(best.x[3])),
            "source": "is_a, n: a Shockley line through the sheet's forward curve, 0.1-10 mA "
            "(varimu.devices.opto.VTL5C1_LED, read at its grid); i_eta_a fitted with the cell "
            "(it carries the cell's superlinear sensitization at low light too)",
        },
        "cell": {
            "gen_s_per_s_a": float(np.exp(best.x[0])),
            "tau0_s": float(np.exp(best.x[1])),
            "kappa_s_s": float(np.exp(best.x[2])),
            "g_dark_s": g_dark,
            "source": "least squares in log R over the light-adapted steady curve (condition "
            f"2) and the four response curves; g_dark_s the sheet's OFF resistance ({dark_text} "
            "min. at 10 s)",
        },
        "fit": {
            "rms_log_r_steady": round(st_err, 3),
            "rms_log_r_response": errs,
            "source": "the fit's residuals (ln R). The cell has one state: a dim LED's turn-on "
            "delay (the 10 mA curve's first millisecond, trap filling) is not in it",
        },
    }
