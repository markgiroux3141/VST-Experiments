"""Koren pentode / beam-power tube model.

Koren, "Improved vacuum tube models for SPICE simulations", 1996:
    E1  = (Vg2 / Kp) * ln(1 + exp(Kp * (1/mu + Vg1 / Vg2)))
    Ip  = (E1^Ex / Kg1) * (1 + sgn(E1)) * atan(Vp / Kvb)
    Ig2 = (Vg1 + Vg2/mu)^1.5 / Kg2

The control grid conducts with the triode's grid-current law (GridCurrent), if
the model has one.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from varimu.devices.triode import GridCurrent, num, softplus, spice_softplus

_VG2_MIN = 1e-3  # avoids division by zero when the screen is at 0 V


@dataclass(frozen=True)
class KorenPentode:
    mu: float  # grid-1 to screen amplification factor
    ex: float
    kg1: float
    kg2: float
    kp: float
    kvb: float

    def ip(self, vg1, vg2, vp):
        vg1, vg2, vp = (np.asarray(v, float) for v in (vg1, vg2, vp))
        g2 = np.maximum(vg2, _VG2_MIN)
        e1 = g2 / self.kp * softplus(self.kp * (1 / self.mu + vg1 / g2))
        return 2.0 / self.kg1 * np.maximum(e1, 0.0) ** self.ex * np.arctan(vp / self.kvb)

    def ig2(self, vg1, vg2):
        x = np.asarray(vg1, float) + np.asarray(vg2, float) / self.mu
        return np.maximum(x, 0.0) ** 1.5 / self.kg2

    def spice_ip(self, vg1: str, vg2: str, vp: str) -> str:
        g2 = f"max({vg2},{num(_VG2_MIN)})"
        arg = f"{num(self.kp)}*({num(1 / self.mu)}+{vg1}/{g2})"
        e1 = f"{g2}/{num(self.kp)}*{spice_softplus(arg)}"
        return f"{num(2.0 / self.kg1)}*pow(max({e1},0),{num(self.ex)})*atan({vp}/{num(self.kvb)})"

    def spice_ig2(self, vg1: str, vg2: str) -> str:
        return f"pow(max({vg1}+{vg2}/{num(self.mu)},0),1.5)/{num(self.kg2)}"


@dataclass(frozen=True)
class Pentode:
    name: str
    model: KorenPentode
    grid: GridCurrent | None = None  # control-grid current
    c_g1k: float = 0.0  # input capacitance (F)
    c_g1p: float = 0.0
    c_pk: float = 0.0  # output capacitance

    def ip(self, vg1, vg2, vp):
        return self.model.ip(vg1, vg2, vp)

    def ig2(self, vg1, vg2):
        return self.model.ig2(vg1, vg2)

    def ig1(self, vg1):
        return np.zeros_like(np.asarray(vg1, float)) if self.grid is None else self.grid.ig(vg1)

    @property
    def subckt_name(self) -> str:
        return "PENTODE_" + "".join(c if c.isalnum() else "_" for c in self.name).upper()

    def subckt(self) -> str:
        """SPICE subcircuit with pins (plate, screen, grid 1, cathode)."""
        vg1, vg2, vp = "V(g1,k)", "V(g2,k)", "V(p,k)"
        lines = [
            f"* {self.name}: generated by varimu.devices.pentode",
            f".subckt {self.subckt_name} p g2 g1 k",
            f"Bp p k I={{{self.model.spice_ip(vg1, vg2, vp)}}}",
            f"Bg2 g2 k I={{{self.model.spice_ig2(vg1, vg2)}}}",
        ]
        if self.grid is not None:
            lines.append(f"Bg1 g1 k I={{{self.grid.spice_ig(vg1)}}}")
        for nm, a, b, c in (
            ("Cg1k", "g1", "k", self.c_g1k),
            ("Cg1p", "g1", "p", self.c_g1p),
            ("Cpk", "p", "k", self.c_pk),
        ):
            if c > 0:
                lines.append(f"{nm} {a} {b} {num(c)}")
        lines.append(f".ends {self.subckt_name}")
        return "\n".join(lines) + "\n"


def koren_pentode_from_spec(
    *, vp, vg2, vg1, ip, gm, rp, ig2, cutoff_vg1, cutoff_ip, ex: float = 1.35
) -> KorenPentode:
    """Solve mu, kg1, kg2, kp and kvb from one class-A point plus one cutoff point."""
    from scipy.optimize import least_squares

    def make(x):
        return KorenPentode(*np.exp(x[:1]), ex, *np.exp(x[1:]))

    def resid(x):
        m = make(x)
        d = 1e-3
        g = (m.ip(vg1 + d, vg2, vp) - m.ip(vg1 - d, vg2, vp)) / (2 * d)
        r = 2 * d / (m.ip(vg1, vg2, vp + d) - m.ip(vg1, vg2, vp - d))
        return [
            np.log(m.ip(vg1, vg2, vp) / ip),
            np.log(g / gm),
            np.log(r / rp),
            np.log(m.ig2(vg1, vg2) / ig2),
            np.log(m.ip(cutoff_vg1, vg2, vp) / cutoff_ip),
        ]

    # x = log(mu, kg1, kg2, kp, kvb)
    sol = least_squares(resid, np.log([8.0, 1000.0, 5000.0, 50.0, 30.0]), xtol=1e-14, ftol=1e-14)
    if np.max(np.abs(sol.fun)) > 1e-6:
        raise RuntimeError(f"Koren pentode spec fit did not converge: residuals {sol.fun}")
    return make(sol.x)
