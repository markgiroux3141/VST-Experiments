"""Tabulated triode plate current for SPICE (XSPICE `table2D`).

The 32-section 6386 as one behavioral expression costs about 1.3 ms per
timepoint in ngspice 47, because the symbolic derivatives of the nested
expression blow up. A table of the same Python reference model, interpolated
by the `table2D` code model, costs about 0.06 ms (measured; see CLAUDE.md).

table2D interpolates the output bilinearly (its derivatives use ENO
interpolation). `bilinear()` is the Python reference for what the table
returns. `interpolation_error()` measures how far that is from the analytic
model on a dense grid, and the grids below are chosen to keep it small
in the region the 670 operates in.

Grid current and interelectrode capacitances stay analytic (they're cheap).
"""

from __future__ import annotations

import hashlib
import inspect
import os
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from varimu.config import REPO_ROOT
from varimu.devices import triode as triode_module
from varimu.devices.triode import Triode, num

TABLE_DIR = REPO_ROOT / "cache" / "tables"


def _ranges(*parts: tuple[float, float, float]) -> np.ndarray:
    """Concatenate arange(lo, hi, step) segments; the last segment includes its end."""
    pieces = [np.arange(lo, hi, step) for lo, hi, step in parts[:-1]]
    lo, hi, step = parts[-1]
    pieces.append(np.arange(lo, hi + step / 2, step))
    return np.unique(np.round(np.concatenate(pieces), 9))


@dataclass(frozen=True)
class TableGrid:
    vg: np.ndarray  # grid-cathode volts, increasing (table2D x axis)
    vp: np.ndarray  # plate-cathode volts, increasing (table2D y axis)


# Finest where the grid spends its time (CV from 0 to about -70 V, plus audio
# swing); plate from below 0 (cutoff row) to 2.5x B+ for inductive swings.
# 544 x 316 points, about 2.5 MB of text. Bilinear error vs the analytic model
# is 1.4e-5 of max current over Vg -80..0 V, Vp 50..450 V, and 2.7e-5 around
# idle (Vg -30..0 V, Vp 150..330 V). Halving every step gives ~3e-6 at 10 MB.
GRID_6386 = TableGrid(
    vg=_ranges((-250.0, -80.0, 4.0), (-80.0, -30.0, 0.5), (-30.0, 10.0, 0.1)),
    vp=_ranges((-50.0, 0.0, 10.0), (0.0, 20.0, 1.0), (20.0, 600.0, 2.0)),
)

# Sidechain triodes. 12AX7: 4.7e-5 over Vg -4..0 V, Vp 50..300 V (3.8 MB).
# 12BH7: 1.1e-4 over Vg -15..0 V, Vp 20..300 V (2.2 MB).
_VP_SMALL = _ranges((-50.0, 0.0, 10.0), (0.0, 20.0, 1.0), (20.0, 500.0, 2.0))
GRIDS = {
    "6386": GRID_6386,
    "12AX7": TableGrid(_ranges((-60.0, -10.0, 0.5), (-10.0, 5.0, 0.02)), _VP_SMALL),
    "12BH7": TableGrid(_ranges((-150.0, -40.0, 2.0), (-40.0, 5.0, 0.1)), _VP_SMALL),
    # The Pultec EQP-1A's output stage (idles near Vg -9 V, Vp 250 V).
    "12AU7": TableGrid(_ranges((-100.0, -30.0, 1.0), (-30.0, 5.0, 0.05)), _VP_SMALL),
    # The 5E3's V1 (idles near Vg -1.8 V, Vp 135 V; cutoff near -11 V at 250 V).
    "12AY7": TableGrid(_ranges((-60.0, -10.0, 0.5), (-10.0, 5.0, 0.02)), _VP_SMALL),
    # The regulator's pass tube (idles near Vg -5 V, Vp 195 V; Vp to 700 V for start-up).
    "EL34T": TableGrid(
        _ranges((-100.0, -20.0, 1.0), (-20.0, 5.0, 0.05)),
        _ranges((-50.0, 0.0, 10.0), (0.0, 20.0, 1.0), (20.0, 700.0, 2.0)),
    ),
}


def table_text(triode: Triode, grid: TableGrid) -> str:
    """The table2D file: x = Vgk columns, y = Vpk rows, values = Ip."""
    if not (np.any(grid.vg == 0) and np.any(grid.vp == 0)):
        raise ValueError("table2D needs the point (0, 0) for the operating point")
    g, p = np.meshgrid(grid.vg, grid.vp)
    ip = triode.ip(g, p)
    lines = [
        f"* {triode.name}: plate current table generated by varimu.devices.table",
        str(len(grid.vg)),
        str(len(grid.vp)),
        " ".join(f"{x:.9g}" for x in grid.vg),
        " ".join(f"{x:.9g}" for x in grid.vp),
    ]
    lines += [" ".join(f"{x:.12g}" for x in row) for row in ip]
    return "\n".join(lines) + "\n"


def table_subckt(triode: Triode, table_file: str) -> str:
    """Subcircuit (plate, grid, cathode) whose plate current comes from `table_file`.

    ngspice lower-cases file names, so `table_file` should be lower case
    and must be in the simulator's working directory.
    """
    name = triode.subckt_name
    model = f"tab_{name.lower()}"
    lines = [
        f"* {triode.name}: tabulated plate current (varimu.devices.table)",
        f".subckt {name} p g k",
        f"a_ip %vd(g k) %vd(p k) %id(p k) {model}",
        f'.model {model} table2d(offset=0 gain=1 order=3 file="{table_file}")',
    ]
    if triode.grid is not None:
        lines.append(f"Bg g k I={{{triode.grid.spice_ig('V(g,k)')}}}")
    for nm, a, b, c in (
        ("Cgk", "g", "k", triode.c_gk),
        ("Cgp", "g", "p", triode.c_gp),
        ("Cpk", "p", "k", triode.c_pk),
    ):
        if c > 0:
            lines.append(f"{nm} {a} {b} {num(c)}")
    lines.append(f".ends {name}")
    return "\n".join(lines) + "\n"


def bilinear(triode: Triode, grid: TableGrid, vg, vp) -> np.ndarray:
    """What table2D returns: bilinear interpolation of the table, clamped at its edges."""
    vg = np.clip(np.asarray(vg, float), grid.vg[0], grid.vg[-1])
    vp = np.clip(np.asarray(vp, float), grid.vp[0], grid.vp[-1])
    i = np.clip(np.searchsorted(grid.vg, vg, side="right") - 1, 0, len(grid.vg) - 2)
    j = np.clip(np.searchsorted(grid.vp, vp, side="right") - 1, 0, len(grid.vp) - 2)
    x0, x1 = grid.vg[i], grid.vg[i + 1]
    y0, y1 = grid.vp[j], grid.vp[j + 1]
    tx, ty = (vg - x0) / (x1 - x0), (vp - y0) / (y1 - y0)
    f = triode.ip
    return (
        f(x0, y0) * (1 - tx) * (1 - ty)
        + f(x1, y0) * tx * (1 - ty)
        + f(x0, y1) * (1 - tx) * ty
        + f(x1, y1) * tx * ty
    )


def interpolation_error(
    triode: Triode, grid: TableGrid, vg_range=(-80.0, 0.0), vp_range=(50.0, 450.0), n=401
) -> float:
    """Max |table - analytic| relative to the max current in the region."""
    g, p = np.meshgrid(np.linspace(*vg_range, n), np.linspace(*vp_range, n))
    exact = triode.ip(g, p)
    return float(np.max(np.abs(bilinear(triode, grid, g, p) - exact)) / np.max(exact))


def _table_key(triode: Triode, grid: TableGrid) -> str:
    """Hash of everything a table depends on: the model, the grid, and the code that makes
    it (table_text and the triode models). The source comes through `inspect`, so its
    newlines are normalized (a CRLF checkout keys the same as LF) and the grids above
    aren't part of it (each table's own grid is)."""
    h = hashlib.sha256(repr(triode).encode())
    h.update(np.ascontiguousarray(grid.vg, "<f8").tobytes())
    h.update(np.ascontiguousarray(grid.vp, "<f8").tobytes())
    h.update(inspect.getsource(table_text).encode())
    h.update(inspect.getsource(triode_module).encode())
    return h.hexdigest()[:32]


def cached_table(triode: Triode, grid: TableGrid, cache_dir: Path = TABLE_DIR) -> Path:
    """Path to the table file for this model and grid, generating it on first use."""
    path = cache_dir / f"{_table_key(triode, grid)}.tab"
    if not path.exists():
        cache_dir.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(f".{os.getpid()}.tmp")
        tmp.write_text(table_text(triode, grid), encoding="utf-8")
        os.replace(tmp, path)
    return path
