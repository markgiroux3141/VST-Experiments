"""Rectifier models: semiconductor junction diode and vacuum (thermionic) diode."""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from scipy.special import lambertw, wrightomega

from varimu.devices.triode import num, softplus, spice_softplus

# Thermal voltage kT/q at the SPICE default TNOM = 27 C, with the CODATA constants ngspice uses.
VT_TNOM = 1.38064852e-23 * 300.15 / 1.6021766208e-19


@dataclass(frozen=True)
class JunctionDiode:
    """Shockley diode with series resistance: SPICE's built-in D model (IS, N, RS).

    The Python reference solves the series-resistance equation exactly with the Lambert W function.
    """

    name: str
    is_a: float
    n: float
    rs_ohm: float = 0.0

    def i(self, v):
        v = np.asarray(v, float)
        nvt = self.n * VT_TNOM
        if self.rs_ohm == 0:
            return self.is_a * np.expm1(v / nvt)
        a = self.is_a * self.rs_ohm / nvt
        t = (v + self.is_a * self.rs_ohm) / nvt
        # W(a e^t); where e^t overflows (far forward), the Wright omega W(e^y) at
        # y = ln a + t, as the Rust engine does.
        with np.errstate(over="ignore"):
            z = a * np.exp(t)
        far = ~np.isfinite(z)
        w = lambertw(np.where(far, 1.0, z)).real
        if np.any(far):
            w = np.where(far, wrightomega(np.log(a) + t).real, w)
        return nvt / self.rs_ohm * w - self.is_a

    @property
    def model_name(self) -> str:
        return "D_" + "".join(c if c.isalnum() else "_" for c in self.name).upper()

    def model_card(self) -> str:
        return (
            f".model {self.model_name} D(IS={num(self.is_a)} N={num(self.n)} "
            f"RS={num(self.rs_ohm)})\n"
        )


@dataclass(frozen=True)
class VacuumDiode:
    """Space-charge-limited thermionic diode: I = perveance * V^1.5 (Child-Langmuir),
    with the same softplus knee as the triode grid current."""

    name: str
    perveance: float  # A / V^1.5
    smooth_v: float = 0.1

    def i(self, v):
        x = self.smooth_v * softplus(np.asarray(v, float) / self.smooth_v)
        return self.perveance * x**1.5

    @property
    def subckt_name(self) -> str:
        return "VDIODE_" + "".join(c if c.isalnum() else "_" for c in self.name).upper()

    def subckt(self) -> str:
        """SPICE subcircuit with pins (anode, cathode)."""
        x = f"{num(self.smooth_v)}*{spice_softplus(f'V(a,k)/{num(self.smooth_v)}')}"
        return (
            f"* {self.name}: generated by varimu.devices.diode\n"
            f".subckt {self.subckt_name} a k\n"
            f"Ba a k I={{{num(self.perveance)}*pow({x},1.5)}}\n"
            f".ends {self.subckt_name}\n"
        )
