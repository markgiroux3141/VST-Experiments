"""Granular carbon pressed by a force: a carbon button (Edison's lamp-black button, 1877; the
Hughes microphone principle, 1878), the Victorian synth's relay (docs/VICTORIAN_SYNTH_PLAN.md,
V2: a receiver's diaphragm pressing a button in a second battery's circuit).

A carbon device has pins (a, b, f, ref) and three ports, all relative to ref:

- the carbon from a to b: a conductance G(F) carrying G (V(a) - V(b)), into a and out of b;
- the force pin f: no current. F = V(f, ref) is the force on the carbon in newtons (1 V =
  1 N): a circuit makes it from a diaphragm's displacement (a spring's force).

    G(F) = G_open + G0 (F_s / F0)^n,  F_s = s ln(1 + exp(F / s))

Granular carbon conducts through its grains' contact spots; their number and size grow with
the force, so the conductance follows a power of it (Holm's constriction law gives 1/3-1/2
for one spot, ~1 as spots multiply; Du Moncel reports Edison's button changing its resistance
almost in proportion to the pressure). F_s is the force softened over `s` (a softplus) so G
and its derivative stay smooth through zero force for Newton: a button pulled off its
diaphragm keeps its loose grains' G_open.

Left out (later): the granules' 1/f and burst noise (they grow with the current), their
packing (a slow drift and hysteresis), heating at high currents.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

from varimu.devices.triode import num


@dataclass(frozen=True)
class Carbon:
    name: str
    g0_s: float  # the conductance at force f0_n (above G_open)
    f0_n: float
    exponent: float
    g_open_s: float  # loose grains: no force
    soft_n: float  # the softplus's force scale s

    def g(self, f):
        """The conductance at force f (arrays) and its derivative."""
        f = np.asarray(f, float)
        z = f / self.soft_n
        fs = self.soft_n * np.logaddexp(0.0, z)
        sig = 0.5 * (1.0 + np.tanh(0.5 * z))
        ratio = fs / self.f0_n
        g = self.g_open_s + self.g0_s * ratio**self.exponent
        dg = self.g0_s * self.exponent * ratio ** (self.exponent - 1.0) / self.f0_n * sig
        return g, dg

    def eval(self, v):
        """Port currents i (3,) and Jacobian (3, 3) at the port voltages v = (V(a, ref),
        V(b, ref), V(f, ref))."""
        va, vb, vf = (float(x) for x in v)
        g, dg = (float(x) for x in self.g(vf))
        d = va - vb
        i = np.array([g * d, -g * d, 0.0])
        j = np.zeros((3, 3))
        j[0, 0], j[0, 1], j[0, 2] = g, -g, dg * d
        j[1, 0], j[1, 1], j[1, 2] = -g, g, -dg * d
        return i, j

    def currents(self, v):
        return self.eval(v)[0]

    @property
    def subckt_name(self) -> str:
        return "CARBON_" + "".join(c if c.isalnum() else "_" for c in self.name).upper()

    def subckt(self) -> str:
        """SPICE subcircuit with pins (a, b, f, ref): the carbon as one B-source (the softplus
        written overflow-safe: max(z, 0) + ln(1 + exp(-|z|)))."""
        z = f"(V(f,ref)/{num(self.soft_n)})"
        fs = f"({num(self.soft_n)}*(max({z},0)+ln(1+exp(-abs({z})))))"
        law = f"pwr({fs}/{num(self.f0_n)},{num(self.exponent)})"
        g = f"({num(self.g_open_s)}+{num(self.g0_s)}*{law})"
        return (
            f"* {self.name}: generated by varimu.devices.carbon\n"
            f".subckt {self.subckt_name} a b f ref\n"
            f"Bc a b I={{{g}*V(a,b)}}\n"
            f".ends {self.subckt_name}\n"
        )


def carbon_from_data(d: dict, ref: str) -> Carbon:
    """A carbon component version's model."""
    c = d["carbon"]
    return Carbon(
        d["name"],
        float(c["g0_s"]),
        float(c["f0_n"]),
        float(c["exponent"]),
        float(c["g_open_s"]),
        float(c["soft_n"]),
    )


def resistance_at(c: Carbon, f_n: float) -> float:
    """The button's resistance at force f_n (a figure for reports)."""
    g, _ = c.g(f_n)
    return 1.0 / float(g) if math.isfinite(float(g)) else math.inf
