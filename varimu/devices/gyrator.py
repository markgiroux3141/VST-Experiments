"""A gyrator whose conductance follows a sensed voltage: the electrodynamic motor of a
moving-coil speaker whose field is an electromagnet (docs/VICTORIAN_SYNTH_PLAN.md: the
Siemens moving-coil cone, its field coil fed by the batteries).

A gyrator device has pins (a, b, f, ref) and three ports, all relative to ref:
- a and b: the gyrator's two ports, i_a = g V(b, ref) into a, i_b = -g V(a, ref) into b;
- f: no current. g = g_per_v V(f, ref): a voltage proportional to the field current (the
  drop across the field coil's own resistance).

A fixed gyrator (two Vccs of conductance g1) in cascade with this one is an ideal
transformer of ratio g / g1 between the voice coil's electrical side and the motional
network: the motional network is built for the force factor BL0 at the nominal field
current, and the transformer scales it to BL = BL0 i_field / i_nominal (the gap's flux
proportional to the field's ampere-turns: an air gap that dominates the reluctance and iron
far below saturation). The device is bilinear (smooth everywhere, signed: a reversed field
reverses the force), so Newton needs no softening.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from varimu.devices.triode import num


@dataclass(frozen=True)
class Gyrator:
    name: str
    g_per_v: float  # siemens per volt of V(f, ref)

    def eval(self, v):
        """Port currents i (3,) and Jacobian (3, 3) at the port voltages v = (V(a, ref),
        V(b, ref), V(f, ref))."""
        va, vb, vf = (float(x) for x in v)
        g = self.g_per_v * vf
        i = np.array([g * vb, -g * va, 0.0])
        j = np.zeros((3, 3))
        j[0, 1], j[0, 2] = g, self.g_per_v * vb
        j[1, 0], j[1, 2] = -g, -self.g_per_v * va
        return i, j

    def currents(self, v):
        return self.eval(v)[0]

    @property
    def subckt_name(self) -> str:
        return "GYRATOR_" + "".join(c if c.isalnum() else "_" for c in self.name).upper()

    def subckt(self) -> str:
        """SPICE subcircuit with pins (a, b, f, ref): two B-sources."""
        g = f"({num(self.g_per_v)}*V(f,ref))"
        return (
            f"* {self.name}: generated by varimu.devices.gyrator\n"
            f".subckt {self.subckt_name} a b f ref\n"
            f"Bga a ref I={{{g}*V(b,ref)}}\n"
            f"Bgb b ref I={{-{g}*V(a,ref)}}\n"
            f".ends {self.subckt_name}\n"
        )
