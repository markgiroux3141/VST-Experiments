"""A switch contact worked by a control voltage: a key's springs and bus bars (the Hammond
Novachord's playing keys, docs/NOVACHORD_PLAN.md), a relay's contact.

A contact is a device with pins (a, b, c, ref) and three ports, all relative to ref (the
circuit passes ground):

- the contact itself, from a to b: a conductance g(V(c, ref)) carrying g (V(a) - V(b)),
  the same current into a and out of b;
- the control pin c: no current (the control voltage is a circuit's control input, a key's
  gate). A make contact (v_closed_v above v_open_v) is open at or below `v_open_v` and
  closed at or above `v_closed_v`; a break contact (v_closed_v below v_open_v) the other
  way round: closed with its control low, opened as the control rises.

Between the two the conductance moves from 1 / r_off_ohm to 1 / r_on_ohm logarithmically
along a smoothstep (3x^2 - 2x^3), so g and its derivative are continuous for Newton:

    ln g = ln g_off + (ln g_on - ln g_off) s(x),  x = (v - v_open) / (v_closed - v_open).

The contact is otherwise ideal: no bounce, no arc, no wiping resistance (a closed contact is
r_on, an open one r_off: insulation). It closes when its control does, within the sample a
control input steps in.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

from varimu.devices.triode import num


@dataclass(frozen=True)
class Contact:
    name: str
    r_on_ohm: float  # closed: the contact's resistance
    r_off_ohm: float  # open: the insulation between the springs
    v_open_v: float  # the control here or past it (away from v_closed_v): open
    v_closed_v: float  # here or past it: closed (below v_open_v: a break contact)

    def _x(self, v):
        span = self.v_closed_v - self.v_open_v
        return np.clip((np.asarray(v, float) - self.v_open_v) / span, 0.0, 1.0), span

    def g(self, v):
        """The conductance at control voltage v (arrays) and its derivative."""
        x, span = self._x(v)
        lo, hi = -math.log(self.r_off_ohm), -math.log(self.r_on_ohm)
        s = x * x * (3.0 - 2.0 * x)
        g = np.exp(lo + (hi - lo) * s)
        dg = g * (hi - lo) * 6.0 * x * (1.0 - x) / span
        return g, dg

    def eval(self, v):
        """Port currents i (3,) and Jacobian (3, 3) at the port voltages v = (V(a, ref),
        V(b, ref), V(c, ref))."""
        va, vb, vc = (float(x) for x in v)
        g, dg = (float(x) for x in self.g(vc))
        d = va - vb
        i = np.array([g * d, -g * d, 0.0])
        j = np.zeros((3, 3))
        j[0, 0], j[0, 1], j[0, 2] = g, -g, dg * d
        j[1, 0], j[1, 1], j[1, 2] = -g, g, -dg * d
        return i, j

    def currents(self, v):
        return self.eval(v)[0]

    @property
    def subckt_name(self) -> str:
        return "CONTACT_" + "".join(c if c.isalnum() else "_" for c in self.name).upper()

    def subckt(self) -> str:
        """SPICE subcircuit with pins (a, b, c, ref): the contact as one B-source."""
        lo, hi = -math.log(self.r_off_ohm), -math.log(self.r_on_ohm)
        span = self.v_closed_v - self.v_open_v
        x = f"min(max((V(c,ref)-{num(self.v_open_v)})/{num(span)},0),1)"
        s = f"({x}*{x}*(3-2*{x}))"
        return (
            f"* {self.name}: generated by varimu.devices.contact\n"
            f".subckt {self.subckt_name} a b c ref\n"
            f"Bc a b I={{exp({num(lo)}+{num(hi - lo)}*{s})*V(a,b)}}\n"
            f".ends {self.subckt_name}\n"
        )


def contact_from_data(d: dict, ref: str) -> Contact:
    """A contact component version's model."""
    c = d["contact"]
    return Contact(
        d["name"],
        float(c["r_on_ohm"]),
        float(c["r_off_ohm"]),
        float(c["v_open_v"]),
        float(c["v_closed_v"]),
    )
