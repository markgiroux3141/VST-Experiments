"""The invented keyboards saved as component versions of kind `invented_keys`
(docs/INVENTED_LIVE_PLAN.md; circuitsim's invented.rs plays them).

Each instrument is a component of its own (ROSIN_WHEEL, BUZZ_ZITHER, ...): its version file
config/components/<name>/<N>.yaml names its data <N>.keys.json by sha256, and the builders
check it (`ir_data`). The data's "instrument" field says which voice reads it. A circuit's
`invented_keys` part pins a version (`ROSIN_WHEEL@1`); moving it is an explicit edit.
`scripts/compile_invented_keys.py [--check] [NAME ...]` writes them.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
from pathlib import Path
from typing import Any

from varimu.config import REPO_ROOT
from varimu.devices import versions

KIND = "invented_keys"
DATA_SUFFIX = ".keys.json"


def models() -> dict[str, Any]:
    """Component name -> the function giving its data (one per instrument)."""
    from varimu.invented.keys import rosin, zither

    return {"ROSIN_WHEEL": rosin.model, "BUZZ_ZITHER": zither.model}


def dump(data: dict[str, Any]) -> str:
    """The data's text as saved (compact JSON, as circuitsim reads it)."""
    return json.dumps(data, separators=(",", ":"))


def _yaml(name: str, data_file: str, sha: str, instrument: str, source: str) -> str:
    return (
        f"# Generated by varimu/invented/keys/compile.py (scripts/compile_invented_keys.py)"
        f" on {_dt.date.today().isoformat()}.\n"
        "# Don't edit by hand: change varimu/invented/ and recompile.\n"
        f"name: {name}\n"
        f"kind: {KIND}\n"
        f"instrument: {instrument}\n"
        f'source: "{source} (docs/INVENTED_LIVE_PLAN.md; values and their sources in the\n'
        '  modules: mostly provisional, model knowledge)"\n'
        "data:\n"
        f"  file: {data_file}\n"
        f"  sha256: {sha}\n"
    )


def latest(name: str) -> str | None:
    have = versions.versions(name)
    return f"{name}@{have[-1]}" if have else None


def save(name: str, data: dict[str, Any]) -> versions.Ref | None:
    """Save as component `name`'s next version, unless the latest one's data is the same
    (None then)."""
    text = dump(data)
    sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
    have = versions.versions(name)
    if have:
        _, old, _ = files(f"{name}@{have[-1]}")
        if old == sha:
            return None
    n = (have or [0])[-1] + 1
    folder = versions.COMPONENT_DIR / name.lower()
    folder.mkdir(parents=True, exist_ok=True)
    df = f"{n}{DATA_SUFFIX}"
    (folder / df).write_text(text, encoding="utf-8", newline="\n")
    ref = versions.save(name, _yaml(name, df, sha, data["instrument"], data["source"]))
    if ref.version != n:
        raise RuntimeError(f"saved {ref}, expected version {n}")
    return ref


def files(ref: str) -> tuple[Path, str, dict[str, Any]]:
    """(the data's path, its sha256, the version's YAML) of version `ref`, the data checked
    against the sha256 the version names."""
    import yaml

    r, text = versions.read_text(ref)
    d = yaml.safe_load(text)
    if d.get("kind") != KIND:
        raise ValueError(f"{r} is not an invented keyboard (kind {d.get('kind')!r})")
    p = versions.COMPONENT_DIR / r.folder / d["data"]["file"]
    sha = versions.text_hash(p.read_text(encoding="utf-8"))
    if sha != d["data"]["sha256"]:
        raise versions.VersionError(f"{r}'s data {p.name} doesn't match its sha256")
    return p, sha, d


_CHECKED: dict[tuple[str, int, int], str] = {}


def ir_data(ref: str) -> tuple[str, str, str]:
    """(the instrument, the data's path relative to the repository's root with forward
    slashes, its sha256) of version `ref`, as the IR's invented_keys element names them
    (checked once per process while the file's size and time are unchanged)."""
    import yaml

    r, text = versions.read_text(ref)
    d = yaml.safe_load(text)
    if d.get("kind") != KIND:
        raise ValueError(f"{r} is not an invented keyboard (kind {d.get('kind')!r})")
    p = versions.COMPONENT_DIR / r.folder / d["data"]["file"]
    st = p.stat()
    key = (str(p), st.st_size, st.st_mtime_ns)
    sha = d["data"]["sha256"]
    if _CHECKED.get(key) != sha:
        files(ref)
        _CHECKED[key] = sha
    return d["instrument"], p.resolve().relative_to(REPO_ROOT.resolve()).as_posix(), sha


def load(ref: str) -> dict[str, Any]:
    p, _, _ = files(ref)
    return json.loads(p.read_text(encoding="utf-8"))
