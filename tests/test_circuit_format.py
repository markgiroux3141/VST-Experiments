"""The generic circuit format (device builder, B1): varimu.circuit.spec / builder / parts.

The 670's file builds the hand-coded IR byte for byte (test_netlist_golden.py,
test_circuit_ir.py: the fixtures); here a second, small circuit builds from the
same format and runs on both engines, and the format's checks catch bad files.
"""

import dataclasses
import textwrap

import pytest

from varimu.circuit import builder, parts
from varimu.circuit import netlist as nl
from varimu.circuit.ir import Capacitor, Device, Resistor, VoltageSource
from varimu.circuit.spec import load_circuit, resolve
from varimu.config import CONFIG_DIR, ConfigError
from varimu.devices.library import V5651_REF_A, load_device

SMALL = CONFIG_DIR / "circuits" / "triode_stage.yaml"


def test_small_circuit_builds_its_ir():
    """The second circuit is tests/test_circuitsim_nonlinear.py's triode_stage."""
    spec = load_circuit(SMALL)
    c = builder.build(spec, cores="linear")
    t = load_device("12AX7")
    assert c.ir.models == (dataclasses.replace(t, name="12AX7_V1"),)
    assert list(c.ir.elements()) == [
        VoltageSource("VB", "bp", "0", 250.0),
        Resistor("RS", "in", "a", 10e3),
        Capacitor("CI", "a", "g", 100e-9),
        Resistor("RG", "g", "0", 1e6),
        Device("XV1", "12AX7_V1", ("p", "g", "k")),
        Resistor("RP", "bp", "p", 100e3),
        Resistor("RK", "k", "0", 1.5e3),
        Capacitor("CK", "k", "0", 22e-6),
        Capacitor("CO", "p", "o", 100e-9),
        Resistor("RL", "o", "0", 470e3),
    ]
    assert c.save == ("v(g)", "v(p)", "v(k)", "v(o)") and c.text is not None
    # No transformers: both core modes are the same circuit.
    assert builder.build(spec, cores="ja").ir == c.ir


def test_small_circuit_draws_its_parts():
    spec = load_circuit(SMALL)
    nominal = builder.build_ir(spec, resolve(spec))
    a = builder.build_ir(spec, resolve(spec, {"passive_spread": 1.0, "passive_seed": 3}))
    b = builder.build_ir(spec, resolve(spec, {"passive_spread": 1.0, "passive_seed": 3}))
    assert a == b
    band = {"RS": 5, "RG": 5, "RP": 5, "RK": 5, "RL": 5, "CI": 10, "CO": 10, "CK": 50}
    for e0, e1 in zip(nominal.elements(), a.elements(), strict=True):
        if e0.name in band:
            v0 = getattr(e0, "r_ohm", None) or e0.c_f
            v1 = getattr(e1, "r_ohm", None) or e1.c_f
            assert v1 != v0 and abs(v1 / v0 - 1) <= band[e0.name] / 100, e0.name
        else:
            assert e1 == e0
    assert a.models[0].plate.kg1 != nominal.models[0].plate.kg1  # the tube's own draw


def test_small_circuit_agrees_on_both_engines():
    """circuitsim against ngspice on the second circuit, as the triode_stage fixture
    (test_circuitsim_nonlinear.py: -62.8 dB at k = 8, bound -60 dB)."""
    pytest.importorskip("circuitsim", reason="needs `uv sync --extra fast`")
    from varimu.sim import ngspice

    try:
        ngspice.find_ngspice()
    except ngspice.SimulatorNotFound:
        pytest.skip("ngspice not available")
    from engine_compare import compare, signal

    ir = builder.build(load_circuit(SMALL), cores="linear").ir
    err_db, dc = compare(ir, signal(amp=3.0), 8)
    assert err_db < -60 and dc < 1e-6, (err_db, dc)


