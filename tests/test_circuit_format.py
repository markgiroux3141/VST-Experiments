def test_670_tolerance_designators_are_the_old_rule():
    """Every element the file draws is a part by the hand-coded builder's naming rule
    (netlist.part_designator), and every such part is drawn."""
    p = nl.resolve({"passive_spread": 1.0})
    drawn = {
        e.name
        for e0, e in zip(
            nl.build_ir(nl.resolve()).elements(), nl.build_ir(p).elements(), strict=True
        )
        if e != e0 and isinstance(e, Resistor | Capacitor)
    }
    ruled = {
        e.name
        for e in nl.build_ir(p).elements()
        if isinstance(e, Resistor | Capacitor) and nl.part_designator(e.name)
    }
    assert drawn == ruled


# --- The format's checks ---------------------------------------------------------------

BASE = """
title: t
input: in
probes: [o]
values:
  r_ohm: {value: 1.0e+3, source: "test"}
  c_f: {value: 1.0e-6, source: "test"}
"""


def _spec(tmp_path, body, base=BASE):
    path = tmp_path / "c.yaml"
    path.write_text(textwrap.dedent(base) + textwrap.dedent(body), encoding="utf-8")
    return load_circuit(path)


def _build(tmp_path, body, base=BASE, **ov):
    spec = _spec(tmp_path, body, base)
    return builder.build_ir(spec, resolve(spec, ov))


RC = """
sections:
  - title: rc
    parts:
      R1: {R: [in, o], r: r_ohm}
      C1: {C: [o, "0"], c: c_f}
"""


def test_a_minimal_file_builds(tmp_path):
    ir = _build(tmp_path, RC)
    assert [e.name for e in ir.elements()] == ["R1", "C1"] and ir.models == ()


@pytest.mark.parametrize(
    "part, message",
    [
        ("{R: [in, o], r: 1000.0}", "parameter key or"),  # a bare physical number
        ("{R: [in, o], r: nope}", "unknown parameter 'nope'"),
        ("{R: [in, o], r: {value: 1.0}}", "needs a `source`"),
        ("{R: [in, o]}", "needs `r`"),
        ("{R: [in], r: r_ohm}", "takes 2 nodes"),
        ("{R: [in, o], C: [in, o], r: r_ohm}", "exactly one macro"),
        ("{X: [in, o]}", "exactly one macro"),
        ("{R: [in, o], r: r_ohm, rr: 1}", "unknown keys ['rr']"),
        ("{R: [in, o], r: r_ohm, parallel: 1.5}", "is not a count"),
        ("{R: [in, o], r: r_ohm, tolerance: r5}", "tolerance: 'r5'"),
    ],
)
def test_bad_parts_are_errors(tmp_path, part, message):
    body = f"""
    sections:
      - title: rc
        parts:
          R1: {part}
          C1: {{C: [o, "0"], c: c_f}}
    """
    with pytest.raises(ConfigError, match=message.replace("[", r"\[").replace("(", r"\(")):
        _build(tmp_path, body)


def test_inline_values_and_structural_numbers(tmp_path):
    body = """
    sections:
      - title: rc
        parts:
          R1: {R: [in, o], r: {value: 2.0e+3, source: "test"}, parallel: 2}
          C1: {C: [o, "0"], c: c_f}
    """
    assert next(_build(tmp_path, body).elements()).r_ohm == 1e3


@pytest.mark.parametrize(
    "extra, message",
    [
        ('  x: {value: 1.0e6, source: "test"}\n', "is not a number"),
        ("  x: {value: 1.0}\n", "needs a `source`"),
        ('controls:\n  r_ohm: {value: 1.0, min: 0, max: 2, source: "test"}\n', "defined twice"),
        ('controls:\n  k: {value: 1.0, source: "test"}\n', "needs `min` and `max`"),
    ],
)
def test_bad_parameters_are_errors(tmp_path, extra, message):
    with pytest.raises(ConfigError, match=message):
        _spec(tmp_path, RC, BASE + extra)


FULL_SCALE = (
    "full_scale:\n"
    '  input_volts_peak: {value: 1.0, source: "test"}\n'
    '  output_volts_peak: {value: 60, source: "test"}\n'
)


def test_full_scale_is_the_circuits_or_the_settings(tmp_path):
    from varimu.sim.io import TransientSettings, full_scale

    s = TransientSettings.from_sim_settings()
    plain = _spec(tmp_path, RC)
    own = _spec(tmp_path, RC, BASE + FULL_SCALE)
    assert plain.full_scale is None and own.full_scale == (1.0, 60.0)
    assert full_scale(s, plain) == (s.full_scale_volts_peak,) * 2
    assert full_scale(s, None) == (s.full_scale_volts_peak,) * 2
    assert full_scale(s, own) == (1.0, 60.0)
    # Not a parameter, not in the IR: the circuit itself is the same.
    assert builder.build_ir(own, resolve(own)) == builder.build_ir(plain, resolve(plain))
    assert builder.build(own).full_scale == (1.0, 60.0)


@pytest.mark.parametrize(
    "block, message",
    [
        ("full_scale: 1.0\n", "needs exactly"),
        ('full_scale:\n  input_volts_peak: {value: 1.0, source: "test"}\n', "needs exactly"),
        (FULL_SCALE.replace(', source: "test"}', "}", 1), "input_volts_peak: needs a `source`"),
        (FULL_SCALE.replace("60", "0"), "output_volts_peak: value 0 is not a positive"),
        (FULL_SCALE.replace("60", "high"), "output_volts_peak: value 'high' is not a positive"),
    ],
)
def test_bad_full_scale_is_an_error(tmp_path, block, message):
    with pytest.raises(ConfigError, match=message):
        _spec(tmp_path, RC, BASE + block)


TOL = """
  seed: {value: 0, source: "test"}
  spread: {value: 1.0, source: "test"}
  r_pct: {value: 5.0, source: "test"}
tolerance:
  source: test
  seed: seed
  spread: spread
  bands: {r: r_pct, c: [10.0, 20.0]}
"""


def test_tolerance_classes_must_cover_the_parts(tmp_path):
    with pytest.raises(ConfigError, match=r"without a tolerance class: \['C1'\]"):
        _build(tmp_path, RC, BASE + TOL + "  classes: {r: [R1]}\n")
    with pytest.raises(ConfigError, match=r"name no part: \['R9'\]"):
        _build(tmp_path, RC, BASE + TOL + "  classes: {r: [R1, R9], c: [C1]}\n")
    ir = _build(tmp_path, RC, BASE + TOL + "  classes: {r: [R1], c: [C1]}\n")
    r, c = ir.elements()
    assert 0.95 <= r.r_ohm / 1e3 <= 1.05 and 0.9 <= c.c_f / 1e-6 <= 1.2
    exempt = RC.replace("c: c_f}", "c: c_f, tolerance: none}")
    assert list(_build(tmp_path, exempt, BASE + TOL + "  classes: {r: [R1]}\n").elements())[
        1
    ] == Capacitor("C1", "o", "0", 1e-6)


def test_devices_and_switches(tmp_path):
    body = """
    controls:
      pos: {value: 2, min: 1, max: 3, unit: position, source: "test"}
    devices:
      V1: {device: 12AX7@1}
      V2: {device: 12AX7@1, parallel: 2}
    sections:
      - title: t
        parts:
          R1: {R: [in, g], r: r_ohm}
          XV1: {device: [p, g, "0"], model: V1}
          RP: {R: [p, o], r: r_ohm}
          S1:
            switch: pos
            parts:
              C1: {C: [o, "0"], c: c_f, in: [1]}
              R2: {R: [o, "0"], r: r_ohm, in: [2, 3]}
              XV2: {device: [p, g, "0"], model: V2, in: [3]}
    """
    spec = _spec(tmp_path, body)
    names = {
        pos: [e.name for e in builder.build_ir(spec, resolve(spec, {"pos": pos})).elements()]
        for pos in (1, 2, 3)
    }
    assert names[1] == ["R1", "XV1", "RP", "C1"]
    assert names[2] == ["R1", "XV1", "RP", "R2"]
    assert names[3] == ["R1", "XV1", "RP", "R2", "XV2"]
    models = builder.build_ir(spec, resolve(spec)).models
    base = load_device("12AX7")
    assert [m.name for m in models] == ["12AX7_V1", "12AX7_V2"]
    assert models[1].plate.kg1 == pytest.approx(base.plate.kg1 / 2)
    with pytest.raises(ValueError, match="outside"):
        resolve(spec, {"pos": 4})
    with pytest.raises(ConfigError, match="has pins"):
        _build(tmp_path, body.replace('[p, g, "0"], model: V1', "[p, g], model: V1"))
    with pytest.raises(ConfigError, match=r"no part uses: \['V3'\]"):
        _build(tmp_path, body.replace("devices:\n", "devices:\n      V3: {device: 12AX7@1}\n"))


def test_transformer_part_matches_the_library(tmp_path):
    """A transformer part is parts.transformer with the file's values."""
    body = """
      n: {value: 100.0, source: "test"}
      area: {value: 1.0e-4, source: "test"}
      path: {value: 0.07, source: "test"}
      gap: {value: 1.0e-5, source: "test"}
      leak: {value: 1.0e-3, source: "test"}
      mat: {value: mumetall, source: "test"}
    sections:
      - title: t
        parts:
          R1: {R: [in, p], r: r_ohm}
          T1:
            transformer:
              p: {nodes: [p, "0"], r: r_ohm}
              s: {nodes: [o, "0"], ratio: 3.0, c: c_f}
            core: {material: mat, area_m2: area, path_m: path, gap_m: gap}
            turns: n
            leakage_h: leak
    """
    spec = _spec(tmp_path, body)
    for cores in ("ja", "linear"):
        ir = builder.build_ir(spec, resolve(spec), cores)
        els, core = parts.transformer(
            "T1",
            [
                parts.WindingSpec("p", "p", "0", 1.0, 1e3),
                parts.WindingSpec("s", "o", "0", 3.0, 0.0, 1e-6),
            ],
            parts.CoreSpec("mumetall", 1e-4, 0.07, 1e-5),
            turns=100.0,
            leakage_h=1e-3,
            cores=cores,
        )
        assert list(ir.elements())[1:] == els
        assert ir.models == (() if cores == "linear" else (core,))
    assert builder.transformer_core(spec, "T1", resolve(spec)) == core


def test_tapers_rheostats_and_turns():
    assert parts.taper(0.3) == 0.3  # linear
    assert parts.taper(0.5, 0.1) == pytest.approx(0.1)  # audio: 10% at half rotation
    assert parts.taper(0.0, 0.1) == 0.0 and parts.taper(1.0, 0.1) == pytest.approx(1.0)
    assert parts.taper(0.25, 0.1) < 0.25 * 0.1 * 2  # log: fine at the bottom
    r = parts.rheostat("R1", "a", "b", 1e4, 0.5, 0.1)
    assert r.r_ohm == pytest.approx(1e3)
    assert parts.rheostat("R1", "a", "b", 1e4, 0.0).r_ohm == parts.MIN_R_OHM
    # A reverse-taper pot's wiper-to-end track: full at 0, none at 1, the mirror image.
    assert parts.rheostat("R1", "a", "b", 1e4, 0.0, 0.1, reverse=True).r_ohm == 1e4
    assert parts.rheostat("R1", "a", "b", 1e4, 1.0, 0.1, reverse=True).r_ohm == parts.MIN_R_OHM
    assert (
        parts.rheostat("R1", "a", "b", 1e4, 0.3, 0.1, reverse=True).r_ohm
        == parts.rheostat("R1", "a", "b", 1e4, 0.7, 0.1).r_ohm
    )
    a, b = parts.pot("R2", "x", "w", "y", 1e4, 0.5, 0.1)
    assert (a.r_ohm, b.r_ohm) == (pytest.approx(1e3), pytest.approx(9e3))
    # Turns for an inductance, back through the transformer's own linear core and gap.
    core = parts.CoreSpec("mumetall", 0.5e-4, 0.05, 10e-6)
    n = parts.turns_for_inductance(35.0, core)
    els, model = parts.transformer(
        "T9", [parts.WindingSpec("p", "a", "0")], core, turns=n, leakage_h=0.0, cores="linear"
    )
    g = sum(
        1 / e.r_ohm for e in els if isinstance(e, Resistor) and e.name in ("RT9_core", "RT9_gap")
    )
    from varimu.devices.core import TESLA_PER_V

    assert n**2 * core.area_m2 * TESLA_PER_V / g == pytest.approx(35.0, rel=1e-9)
