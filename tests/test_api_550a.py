"""The API 550A (docs/EQ_PLAN.md EQ3): config/circuits/api_550a.yaml, its network check
api_550a_network.yaml and its live circuit api_550a_live.yaml, all GENERATED by
scripts/make_api_550a.py.

The files are current with their generator and every value is sourced; the pre-flight checks
pass on a covering set of switch positions (each band's own switches in every combination,
and every combination of the global ones: the full product is 37 million); the network (the
2520s and followers as linear op-amps, varimu.measure.ac) puts each band's peaks where the
drawing's capacitors put them, reaches its panel's steps, and cuts as the exact reciprocal of
its boost; the real circuit (2520s, discrete followers) idles at sane DC; the live circuit
(what Play and the drafts run) tracks the real one in level, response and clipping.

Measure with BLAS on one thread (OPENBLAS_NUM_THREADS=1) when renders run beside: the
network's small solves slow ~100x on a busy machine.
"""

import dataclasses
import importlib.util
import itertools

import numpy as np
import pytest

from varimu import preflight
from varimu.circuit import builder, spec
from varimu.config import CONFIG_DIR, REPO_ROOT
from varimu.measure import ac

EQ = CONFIG_DIR / "circuits" / "api_550a.yaml"
NET = CONFIG_DIR / "circuits" / "api_550a_network.yaml"
LIVE = CONFIG_DIR / "circuits" / "api_550a_live.yaml"
F = np.geomspace(20, 25000, 120)


@pytest.fixture(scope="module")
def eq():
    return spec.load_circuit(EQ)


@pytest.fixture(scope="module")
def net():
    return spec.load_circuit(NET)


def _gen():
    path = REPO_ROOT / "scripts" / "make_api_550a.py"
    m = importlib.util.spec_from_file_location("make_api_550a", path)
    mod = importlib.util.module_from_spec(m)
    m.loader.exec_module(mod)
    return mod


def _db(s, ov, f=F):
    ir = builder.build_ir(s, spec.resolve(s, ov), cores="linear").without_devices()
    return 20 * np.log10(np.abs(ac.transfer(ir, f, "out")))


def test_the_files_are_current_and_sourced(eq, net):
    gen = _gen()
    assert EQ.read_text(encoding="utf-8") == gen.make()
    assert NET.read_text(encoding="utf-8") == gen.make(ideal=True)
    assert LIVE.read_text(encoding="utf-8") == gen.make(live=True)
    live = spec.load_circuit(LIVE)
    assert live.controls == eq.controls  # the app's panel is the real circuit's
    for s in (eq, net, live):
        assert spec.check_genome_links(s) == []
        builder.build_ir(s, spec.resolve(s))


def test_preflight_on_a_covering_set(eq):
    groups = [
        ["eq_in", "bandpass", "level", "gain_trim_db"],
        ["hf_gain_db", "hf_freq", "hf_shelf", "eq_in"],
        ["mf_gain_db", "mf_freq", "eq_in"],
        ["lf_gain_db", "lf_freq", "lf_shelf", "eq_in"],
    ]
    problems = []
    for keys in groups:
        for combo in itertools.product(*(eq.controls[k]["choices"] for k in keys)):
            cfg = dict(zip(keys, combo, strict=True))
            ir = builder.build_ir(eq, spec.resolve(eq, cfg), "linear")
            problems += [(cfg, p.message) for p in preflight.check_ir(ir)]
    assert problems == []


# Each band's peak frequency per position (Hz) as the drawing's capacitors put it (the
# network, 2026-11-15; API's 550A panels read LF 50-400, MF 400-5k, HF 5k-15k).
PEAKS = {
    "lf": (421, 302, 203, 102, 53),
    "mf": (4840, 2950, 1470, 770, 381),
    "hf": (15000, 11600, 9360, 6850, 4760),
}


@pytest.mark.parametrize("band", ["lf", "mf", "hf"])
def test_peaks_fall_where_the_capacitors_put_them(net, band):
    f = np.geomspace(30, 20000, 200)
    flat = _db(net, {}, f)
    for pos, hz in enumerate(PEAKS[band], start=1):
        d = _db(net, {f"{band}_gain_db": -12, f"{band}_freq": pos}, f) - flat
        assert f[np.argmin(d)] == pytest.approx(hz, rel=0.06), (band, pos)


@pytest.mark.parametrize("band", ["lf", "mf"])
def test_steps_reach_the_panel_and_cut_is_the_reciprocal(net, band):
    flat = _db(net, {})
    for g in (2, 4, 6, 9, 12):
        up = _db(net, {f"{band}_gain_db": g, f"{band}_freq": 3}) - flat
        down = _db(net, {f"{band}_gain_db": -g, f"{band}_freq": 3}) - flat
        assert np.max(up) == pytest.approx(g, abs=0.5)
        # Mirrored within 0.5 dB to 10 kHz (C39 / C43, 47 pF across the boost strings, and R106
        # in front of MF's part them at the top: 0.32 dB at 10 kHz, ~0.4 at 25 kHz).
        assert np.max(np.abs(up + down)[F <= 10000]) < 0.5


def test_hf_steps(net):
    """HF falls short of its marking at the top (the drawing's S9A / S9B capacitors differ,
    C37 68 pF bridges the boost string): within 2 dB."""
    flat = _db(net, {})
    for g in (-12, -6, 6, 12):
        d = _db(net, {"hf_gain_db": g, "hf_freq": 3}) - flat
        assert np.max(np.sign(g) * d) == pytest.approx(abs(g), abs=2.0)


def test_shelves_and_flat(net):
    flat = _db(net, {})
    i20, i20k, i1k = (int(np.argmin(np.abs(F - x))) for x in (20, 20000, 1000))
    lo = _db(net, {"lf_gain_db": 12, "lf_freq": 5, "lf_shelf": 1}) - flat
    hi = _db(net, {"hf_gain_db": 12, "hf_freq": 1, "hf_shelf": 1}) - flat
    assert lo[i20] > 11 and abs(lo[i20k]) < 0.5
    assert hi[i20k] > 11 and abs(hi[i20]) < 0.5
    # Unity within a dB at 1 kHz at both levels (the installation page), the band-pass in
    # cuts 50 Hz and 15 kHz.
    assert abs(flat[i1k]) < 1.0
    assert abs(_db(net, {"level": 1})[i1k]) < 1.0
    bp = _db(net, {"bandpass": 1}) - flat
    assert bp[int(np.argmin(np.abs(F - 50)))] < -2 and bp[int(np.argmin(np.abs(F - 15000)))] < -2


def test_the_real_circuit_idles(eq):
    fast = pytest.importorskip("varimu.sim.fast")
    from varimu.circuit.ir import VoltageProbe
    from varimu.sim.io import TransientSettings

    nodes = ("a1o", "a6o", "a4o", "a3o", "a5o", "a2o", "a6_x", "a4_e")
    ir = builder.build_ir(eq, spec.resolve(eq))
    ir = dataclasses.replace(ir, probes=tuple(VoltageProbe(n) for n in nodes))
    s = dataclasses.replace(TransientSettings.from_sim_settings(engine="circuitsim"), settle_s=0.0)
    v = fast.run_transient(ir, np.zeros(96), settings=s).vectors
    dc = {n: float(v[f"v({n})"][-1]) for n in nodes}
    for n in ("a1o", "a6o", "a4o", "a3o", "a5o", "a2o"):
        assert abs(dc[n]) < 0.5, dc  # outputs near 0 V
    assert 0.5 < dc["a6_x"] < 0.9  # the PNP follower's emitter, a Vbe above its base
    assert -14.1 < dc["a4_e"] < -13.7  # the sink's emitter: 36K / 2.2K less a Vbe


def _tones(name, panel, amp_v, freqs):
    """Circuit `name` at draft-1x driven by equal sines at `freqs` (Hz), each `amp_v` peak:
    the output's amplitude at each, and its peak."""
    fast = pytest.importorskip("varimu.sim.fast")
    from varimu.circuit.ir import VoltageProbe
    from varimu.sim.io import TransientSettings

    s = spec.load_circuit(CONFIG_DIR / "circuits" / f"{name}.yaml")
    ir = builder.build_ir(s, spec.resolve(s, panel))
    ir = dataclasses.replace(ir, probes=(VoltageProbe("out"),))
    st = TransientSettings.from_sim_settings(engine="circuitsim", quality="draft-1x")
    st = dataclasses.replace(st, settle_s=0.05)
    fs = st.sample_rate
    t = np.arange(int(0.1 * fs)) / fs
    x = sum(amp_v * np.sin(2 * np.pi * f * t) for f in freqs) * np.minimum(1, t / 0.005)
    y = fast.run_transient(ir, x, settings=st).vectors["v(out)"][int(0.05 * fs) :]
    tt = t[int(0.05 * fs) :]
    amps = [2 * abs(np.mean(y * np.exp(-2j * np.pi * f * tt))) for f in freqs]
    return np.array(amps), float(np.max(np.abs(y)))


def test_the_live_circuit_tracks_the_real_one():
    """Measured 2026-11-15 on program: within 0.04 dB to 15 kHz (-0.38 dB at 20 kHz, the
    discrete 2520s' extra pole), -70 dB past a fixed filter."""
    freqs = (100, 1000, 10000)  # whole cycles in 50 ms
    panel = {"hf_gain_db": 6, "mf_gain_db": -4, "lf_gain_db": 6, "lf_freq": 4}
    real, _ = _tones("api_550a", panel, 1.0, freqs)
    live, _ = _tones("api_550a_live", panel, 1.0, freqs)
    assert np.max(np.abs(20 * np.log10(live / real))) < 0.1
    # Clipping: both clip at A2 (flat, 1 kHz, far over): the output's peak within 5%.
    _, real_pk = _tones("api_550a", {}, 30.0, (1000,))
    _, live_pk = _tones("api_550a_live", {}, 30.0, (1000,))
    assert live_pk == pytest.approx(real_pk, rel=0.05)
