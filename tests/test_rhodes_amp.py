from varimu.circuit import builder, spec

ROOT = Path(__file__).resolve().parents[1]
CIRCUIT = "rhodes_suitcase_100w"


def load():
    return spec.load_circuit(spec.circuit_path(CIRCUIT))


def test_generated_file_is_current():
    r = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "make_rhodes_suitcase_100w.py"), "--check"],
        capture_output=True,
        text=True,
    )
    assert r.returncode == 0, r.stdout + r.stderr


def test_the_checks_pass_at_every_switch():
    assert preflight.check_circuit(load()) == []


def _run(x, **controls):
    from varimu.sim import fast, io

    st = io.TransientSettings.from_sim_settings(engine="circuitsim", quality="draft")
    st = dataclasses.replace(st, newton_reltol=1e-5, newton_vntol=1e-5, settle_s=0.4)
    q = dict(spec.resolve(load()))
    q.update(accessory_in=1, vibrato=0, volume=1.0)
    q.update(controls)
    ir = builder.build_ir(load(), q, speaker_readout=False)
    v = fast.run_transient(ir, x, settings=st).vectors
    return {k[2:-1]: np.asarray(a) for k, a in v.items()}, st.sample_rate


def test_idle_is_trimmed():
    """Silence: each output at 0 V (OFFSET ADJUST), 25 mA through each output transistor pair
    (BIAS ADJ), the rails near +-30 V less their ripple's mean sag."""
    pytest.importorskip("circuitsim")
    v, fs = _run(np.zeros(int(0.12 * 96000)))
    k = int(0.05 * fs)
    for x in "ab":
        out = np.mean(v[f"{x}_amp"][-k:])
        iq_ma = 1000 * (np.mean(v[f"{x}_e8"][-k:]) - out) / 0.4
        assert abs(out) < 0.01, (x, out)
        assert 22.0 < iq_ma < 28.0, (x, iq_ma)
    assert 29.0 < np.mean(v["vp"][-k:]) < 31.0
    assert -31.0 < np.mean(v["vn"][-k:]) < -29.0


def test_gain_and_clipping():
    """1 kHz at ACCESSORY IN: the power amp's gain pre_a -> a_amp is -R1 / (680 + R22) = 25.4 dB
    (18.6x) and clean (THD < 0.1%) at 14 V peak; driven hard it clips near its rails, 22-26
    W into the speakers' 16 ohm (the README's arithmetic: ~23 W)."""
    pytest.importorskip("circuitsim")
    fs = 96000
    t = np.arange(int(0.45 * fs)) / fs
    env = np.clip(t / 0.02, 0, 1)

    def run(level):
        v, _ = _run(level * np.sin(2 * np.pi * 1000 * t) * env)
        k = int(0.2 * fs)
        pre, amp, spk = v["pre_a"][-k:], v["a_amp"][-k:], v["a_spk"][-k:]
        p = float(np.mean(spk * (amp - spk) / 0.02))
        w = np.hanning(len(amp))
        tt = np.arange(len(amp)) / fs
        h = [abs(np.sum(w * amp * np.exp(-2j * np.pi * n * 1000 * tt))) for n in range(1, 8)]
        return np.ptp(amp) / np.ptp(pre), p, np.sqrt(sum(a * a for a in h[1:])) / h[0]

    gain, _, thd = run(0.02)
    assert 20 * np.log10(gain) == pytest.approx(25.3, abs=0.5)  # model: 25.31
    assert thd < 1e-3  # model: 0.019 %
    _, p, thd_hard = run(0.2)
    assert 20.0 < p < 27.0, p  # model: 24.2 W
    assert thd_hard > 0.1  # clipped


_PAIR = """\
title: "speaker pair"
input: in
probes: [PROBES]
values:
  speaker_model: {value: P12R@1, source: "config/components/p12r/1.yaml"}
  r_src_ohm: {value: 0.5, source: "test"}
  d_m: {value: 1.0, source: "test"}
  w_m: {value: 1.2, source: "test"}
  h_m: {value: 0.7, source: "test"}
  dp_m: {value: 0.35, source: "test"}
sections:
  - title: s
    parts:
      RS: {R: [in, a], r: r_src_ohm, tolerance: none}
"""
_CAB = "component: speaker_model, distance_m: d_m, width_m: w_m, height_m: h_m, depth_m: dp_m"
_TWO = (
    f"      SPK1: {{speaker: [a, m, o1], {_CAB}}}\n"
    f'      SPK2: {{speaker: [m, "0", o2], {_CAB}, readout: 0}}\n'
)
_ONE = f'      SPK: {{speaker: [a, "0", o1], {_CAB}, series: 2}}\n'


def _pair(tmp_path, name, parts, live):
    from varimu.sim import fast, io

    path = tmp_path / f"{name}.yaml"
    probes = "o1, o2, a, m" if "SPK2" in parts else "o1, a"
    path.write_text(_PAIR.replace("PROBES", probes) + parts)
    c = spec.load_circuit(path)
    ir = builder.build_ir(c, dict(spec.resolve(c)), speaker_readout=not live)
    st = io.TransientSettings.from_sim_settings(engine="circuitsim", quality="draft")
    st = dataclasses.replace(st, settle_s=0.0)
    t = np.arange(int(0.06 * st.sample_rate)) / st.sample_rate
    x = 0.3 * np.sin(2 * np.pi * 180 * t) + 0.2 * np.sin(2 * np.pi * 2900 * t)
    return {
        k[2:-1]: np.asarray(a) for k, a in fast.run_transient(ir, x, settings=st).vectors.items()
    }


def test_a_series_pair_is_one_part(tmp_path):
    """Two identical drivers in series (the Suitcase's front and rear speakers) are exactly
    one `series: 2` speaker part: one current, one force, one velocity in each, every
    impedance doubled. The part's readout is one driver's pressure and, live, one driver's
    terminal voltage; a `readout: 0` driver is only a load."""
    pytest.importorskip("circuitsim")
    two = _pair(tmp_path, "two", _TWO, live=False)
    one = _pair(tmp_path, "one", _ONE, live=False)
    ref = np.sqrt(np.mean(two["o1"] ** 2))
    assert ref > 0
    assert np.sqrt(np.mean((one["o1"] - two["o1"]) ** 2)) < 1e-9 * ref  # the front's pressure
    assert np.max(np.abs(one["a"] - two["a"])) < 1e-9 * np.max(np.abs(two["a"]))  # the load
    two_live = _pair(tmp_path, "two_live", _TWO, live=True)
    one_live = _pair(tmp_path, "one_live", _ONE, live=True)
    front = two_live["a"] - two_live["m"]
    assert np.max(np.abs(one_live["o1"] - front)) < 1e-9 * np.max(np.abs(front))
    assert np.max(np.abs(two_live["o2"] - two_live["m"])) < 1e-9 * np.max(np.abs(front))


APP_PARTITION = (
    "speakers A",
    "speakers B",
    "|",
    "output amp A",
    "power amp A",
    "|",
    "output amp B",
    "power amp B",
    "|",
    "mains supply",
)  # fmt: skip  (panel::Device::partition of the app's rhodes_suitcase)


def test_the_pan_does_not_crackle_live():
    """The app's live settings (draft, Newton (4e-3, 4e-2), its partition) against a tight
    solve (1e-5), a steady tone through ACCESSORY IN with the pan sweeping: the outputs'
    difference above 5 kHz (the crackle the user heard at every cycle, -5 to -18 dB re the
    signal before the fixes) stays under -30 dB (measured -38 to -40 dB). The fixes: the
    photocell's cell port converges to 1e-2 of the tolerance (circuitsim's `Optocoupler::
    tol_scale`), its state node at 1 uS per volt (VTL5C2@2), the output stage's devices at
    0.025 (`tol_scale` in the circuit's `devices`)."""
    pytest.importorskip("circuitsim")
    from scipy import signal

    from varimu.sim import fast, io

    c = load()
    q = dict(spec.resolve(c))
    q.update(accessory_in=1, vibrato=1)
    ir = builder.build_ir(c, q, speaker_readout=False)
    base = io.TransientSettings.from_sim_settings(engine="circuitsim", quality="draft")
    fs = base.sample_rate
    t = np.arange(int(1.2 * fs)) / fs
    x = 0.02 * np.sin(2 * np.pi * 440 * t) * np.clip(t / 0.05, 0, 1)

    def run(rel, vn):
        st = dataclasses.replace(base, newton_reltol=rel, newton_vntol=vn, partition=APP_PARTITION)
        v = fast.run_transient(ir, x, settings=st).vectors
        return {k: np.asarray(v[f"v({k})"]) for k in ("out", "out_r")}

    live, tight = run(4e-3, 4e-2), run(1e-5, 1e-5)
    sos = signal.butter(4, 5000, "highpass", fs=fs, output="sos")
    k0 = int(0.3 * fs)
    for node in ("out", "out_r"):
        h = signal.sosfiltfilt(sos, live[node] - tight[node])[k0:]
        rms = np.sqrt(np.mean(tight[node][k0:] ** 2))
        assert 20 * np.log10(np.max(np.abs(h)) / rms) < -30.0, node


def _loud_chords(seconds):
    """Chords at velocity 127 in both hands, the pedal down, one every 0.5 s (the
    diagnostic's that latched the live power amps)."""
    shapes = [(0, 4, 7, 12), (0, 3, 7, 10), (0, 5, 9, 12), (0, 4, 7, 11)]
    roots = [36, 41, 43, 48, 53, 55]
    notes = [(0.4, "pedal", 0, 1)]
    t, i = 0.5, 0
    while t < seconds - 0.2:
        for o in shapes[i % 4]:
            for base in (roots[i % 6] - 12, roots[i % 6]):
                notes.append((t, "on", base + o, 127))
                notes.append((t + 0.4, "off", base + o, 0))
        t, i = t + 0.5, i + 1
    return sorted(notes, key=lambda e: (e[0], e[1] != "off"))


def test_loud_chords_do_not_latch_the_power_amps_live():
    """The app's live settings (draft, Newton (4e-3, 4e-2), its partition), loud chords from
    the harp: before Q4 (the voltage amplifier) converged to 0.025 of the tolerance, Newton
    accepted a false state there within ~1.25 s and each power amp's output latched at +20 V
    for good (the user heard one channel go silent with the rail's hum until a restart; the
    tight solve doesn't latch). Each output's mean over every 0.25 s stays near 0 V."""
    pytest.importorskip("circuitsim")
    from varimu.sim import fast, io

    c = load()
    ir = builder.build_ir(c, dict(spec.resolve(c)), speaker_readout=False)
    st = io.TransientSettings.from_sim_settings(engine="circuitsim", quality="draft")
    st = dataclasses.replace(st, newton_reltol=4e-3, newton_vntol=4e-2, partition=APP_PARTITION)
    seconds = 2.5
    fs = st.sample_rate
    x = np.zeros(int(seconds * fs))
    v = fast.run_transient(ir, x, settings=st, notes=_loud_chords(seconds))
    w = int(0.25 * fs)
    for node in ("a_amp", "b_amp"):
        y = np.asarray(v.vectors[f"v({node})"])
        means = [abs(np.mean(y[k : k + w])) for k in range(0, len(y) - w + 1, w)]
        assert max(means) < 2.0, (node, max(means))  # latched: 20.2 V; fixed: <= 0.3 V


def test_only_the_output_stage_and_q4_are_tightened():
    models = {m.name: m for m in builder.build_ir(load(), dict(spec.resolve(load()))).models}
    tight = {n for n, m in models.items() if getattr(m, "tol_scale", None) is not None}
    assert tight == {"2N5781_QP", "RCA29B_QD", "RCA30B_QPD", "2N6254_QO"}, tight
    assert all(models[n].tol_scale == 0.025 for n in tight)
